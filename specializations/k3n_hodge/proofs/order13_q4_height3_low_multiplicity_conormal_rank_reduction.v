Theorem regular_local_combination_of_the_two_final_cuts:
  There is an invertible constant GL_2(C) change of generators

    L=(h,k)

  such that h is a nonzerodivisor on Cbar.

  Moreover

    h in m^3.

Proof:
  The image of L in Cbar is m-primary because Cbar/L*Cbar is a quotient of the
  finite-dimensional algebra A.

  Since Cbar is one-dimensional Cohen--Macaulay, its associated primes are its
  finitely many minimal primes.  No associated prime can contain both images
  of f and g, because then it would contain the m-primary ideal generated by
  them.

  For each associated prime P, the constant pairs (lambda,mu) for which

    lambda*f+mu*g belongs to P

  form a proper C-linear subspace of C^2.  Their finite union cannot fill C^2.
  Choose a pair outside the union and complete it to a GL_2(C) basis.  The
  resulting h avoids every associated prime and is therefore Cbar-regular.

  Since both original generators have degree at least three, every constant
  combination belongs to m^3.
Qed.

