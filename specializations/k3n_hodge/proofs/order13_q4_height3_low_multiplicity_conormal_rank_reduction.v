Theorem exact_two_generator_conormal_connecting_sequence:
  There is an exact sequence

    0 -> Hom_B(M,A)
      -> Hom_B(L,A)
      -> Ann_A(D)
      --partial--> Ext^1_B(M,A).

Proof:
  The principal ideal Hh is isomorphic to B/D by multiplication by h.  Hence

    Hom_B(Hh,A)
      ~= Hom_B(B/D,A)
      ~= Ann_A(D).

  Apply Hom_B(-,A) to

    0 -> Hh -> L -> M -> 0.
Qed.

