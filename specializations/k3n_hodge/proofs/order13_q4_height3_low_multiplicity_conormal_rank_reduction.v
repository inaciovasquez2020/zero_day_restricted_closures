    epsilon>=6.
Qed.

Interpretation:
  The bounded embedded torsion is not itself large enough to create an
  order-13 tangent deficit.  A surviving low-multiplicity q=4 height-three
  candidate must instead exhibit a genuinely two-generator phenomenon: the
  connecting map

    Ann_A(D) -> Ext^1_B(M,A)

  must have rank at least six larger than the entire space Hom_B(M,A).

  This is the first obstruction that is absent from the q=5 principal-cut
  closure and is not removed by the saturated-core degree compression.

