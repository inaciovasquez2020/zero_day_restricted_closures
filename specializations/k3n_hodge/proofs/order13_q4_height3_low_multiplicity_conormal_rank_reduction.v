Corollary exact_two_generator_conormal_dimension:
  One has

    dim_C Hom_B(L,A)
      = dim_C Ann_A(D)-epsilon.

Proof:
  Exactness gives

    dim Hom_B(L,A)
      = dim Hom_B(M,A)
        + dim Ann_A(D)
