Theorem selected_principal_colon_lives_in_saturation_torsion:
  One has

    D=0:_T h,

  hence

    D subseteq T.

Proof:
  Apply multiplication by h to

    0 -> T -> B -> Cbar -> 0.

  The kernel on Cbar is zero because h is Cbar-regular.  Therefore the kernel
  on B is exactly the kernel on T.
Qed.

Lemma selected_colon_is_graded_and_has_only_one_possible_top_action:
  The vector space D is graded.  More precisely,

    T_2 direct_sum T_3 direct_sum T_4 subseteq D,

  and the only possibly nonzero contribution of h on T is the degree-three
  part of h acting

    T_1 -> T_4.

Proof:
  Every homogeneous component of h has degree at least three.

  Because T_n=0 for n>=5, every component of T of degree at least two is killed
  by h.  On T_1, every homogeneous component of h of degree at least four also
  lands in degree at least five and vanishes.  Thus only h_3:T_1->T_4 can be
  nonzero.

  Consequently

    D=ker(h_3:T_1->T_4)
      direct_sum T_2 direct_sum T_3 direct_sum T_4,

  proving the claim.
Qed.

Theorem selected_principal_annihilator_has_codimension_at_most_fourteen:
  In A, let

    Ann_A(D):={z in A : z*D=0}.

  Then

    length_C(A/Ann_A(D)) <= 14,

  equivalently

    dim_C Ann_A(D) >= N-14.

Proof:
  The four quadratic minimal generators and the absence of linear generators
  give

    dim A_0=1,
    dim A_1=4,
    dim A_2=6.

  Since D subseteq T and m^4*T=0,

    m_A^4*D=0.

  Therefore every homogeneous piece A_n for n>=4 lies in Ann_A(D).

  It remains to bound the degree-three contribution to the action of A on D.
  For z in A_3, multiplication by z kills D_n for n>=2 because the result lies
  in T_(n+3)=0.  Hence z acts only through

    D_1 -> T_4.

  The preceding bounds give

    dim D_1 <= dim T_1 <=3,
    dim T_4<=1.

  Thus the image of the action map

    A_3 -> Hom_C(D_1,T_4)

  has dimension at most three.

  The quotient A/Ann_A(D) identifies with the image of the full action
  representation A->End_C(D).  Its contribution from degrees zero, one, and
  two has dimension at most

    1+4+6=11,

  its degree-three contribution has dimension at most three, and all higher
  degrees contribute zero.  Therefore

    length(A/Ann_A(D))<=11+3=14.
Qed.

