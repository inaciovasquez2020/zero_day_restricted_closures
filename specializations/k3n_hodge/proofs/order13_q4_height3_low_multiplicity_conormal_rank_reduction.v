Theorem top_saturation_defect_has_dimension_at_most_one:
  One has

    dim_C T_4 <= 1.

Proof:
  On X the sheaf ideal generated by a is the image of

    O_X(-2) -> O_X.

  Let F be its kernel.  Since X is zero-dimensional,

    H^1(X,F(4))=0.

  Hence global sections give a surjection

    H^0(X,O_X(2)) -> H^0(X,J~(4)).

  The target identifies with Jsat_4 inside R_4 because

    R_4 ~= H^0(X,O_X(4)).

  The ordinary degree-four principal piece J_4 is the image of

    R_2 -> H^0(X,O_X(2)) -> H^0(X,J~(4)).

  Now

    dim H^0(X,O_X(2))=8,
    dim R_2=7,

  and R_2 injects into H^0(X,O_X(2)) because R is one-dimensional
  Cohen--Macaulay.  Therefore replacing the full eight-dimensional source by
  R_2 can lose at most one image dimension.  Thus

    dim(Jsat_4/J_4)<=1,

  which is exactly dim T_4<=1.
Qed.

Theorem first_saturation_defect_has_dimension_at_most_three:
  One has

    dim_C T_1 <= 3.

Proof:
  Since J is generated in degree two,

    J_1=0,

  so

    T_1=Jsat_1.

  The vector space R_1 has dimension four.  If Jsat_1=R_1, then Jsat contains
  the irrelevant ideal generated by R_1, so Proj(R/Jsat) is empty.  But

    Cbar=R/Jsat

  is one-dimensional of positive multiplicity e>=1, hence has nonempty
  projective support.  Therefore Jsat_1 is a proper subspace of R_1 and has
  dimension at most three.
Qed.

