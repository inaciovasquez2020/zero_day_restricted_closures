  Substitute the definition of epsilon.
Qed.

Theorem order13_tangent_gate_forces_connecting_rank_excess_six:
  If the necessary order-13 tangent gate holds,

    dim_C Hom_S(I,A) <= N-20,

  then

    epsilon >= 6.

Proof:
  Maps I->A which vanish on Q contain the natural subspace

    Hom_B(L,A),

  so

    dim Hom_S(I,A)>=dim Hom_B(L,A).

  By the preceding annihilator and conormal bounds,

    dim Hom_B(L,A)
      = dim Ann_A(D)-epsilon
      >= N-14-epsilon.

  If the tangent gate holds, then

    N-14-epsilon <= N-20,

