Qed.

Theorem skew_line_core_has_minimal_deficiency_module:
  As a graded B0-module,

    H^1_m(B0) ~= C

  concentrated in degree zero.

Proof:
  Apply local cohomology with support in m to

    0 -> B0
      -> S/P1 direct_sum S/P2
      -> C
      -> 0.

  Because Q0 is saturated,

    H^0_m(B0)=0.

