    H^0_m(C)=C.

  The beginning of the long exact sequence is therefore

    0 -> C -> H^1_m(B0) -> 0.

  Thus H^1_m(B0) is exactly one copy of C, and the grading is degree zero
  because the right-hand C is S/m in degree zero.
Qed.

