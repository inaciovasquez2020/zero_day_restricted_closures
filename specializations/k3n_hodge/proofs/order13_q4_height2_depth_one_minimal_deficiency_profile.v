1. THE MINIMAL FOUR-QUADRIC MODEL
--------------------------------------------------------------------------

Put

  P1 := (x1,x2),
  P2 := (x3,x4),

and define

  Q0 := P1 intersect P2.

Because the variable sets are disjoint,

  Q0 = P1*P2
     = (x1*x3, x1*x4, x2*x3, x2*x4).

Theorem skew_line_core_has_exact_four_quadric_presentation:
  Q0 is minimally generated by exactly four linearly independent quadrics and

    ht(Q0)=2.

Proof:
  The displayed four monomials are distinct degree-two monomials, hence are
  linearly independent.

  Since Q0 has no degree-one elements, none of those quadrics can be generated
  from lower degree.  Since its degree-two part is exactly their span, all four
  are minimal generators.

  The minimal primes P1 and P2 both have height two, so

    ht(Q0)=2.
Qed.

Theorem skew_line_core_is_already_saturated:
  One has

    Q0sat=Q0.

Proof:
  Each Pi is generated by linear forms and is saturated with respect to

    m=(x1,x2,x3,x4).

  Suppose m^r*f is contained in Q0=P1 intersect P2 for some r.  Then m^r*f is
  contained in each Pi.  Saturation of Pi gives f in Pi for i=1,2.  Therefore

    f in P1 intersect P2=Q0.

  Hence Q0 is saturated.
Qed.

Corollary minimal_model_has_zero_saturation_torsion:
