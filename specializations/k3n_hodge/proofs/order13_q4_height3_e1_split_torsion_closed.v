Theorem multiplicity_one_saturated_core_is_a_polynomial_ring:
  For a general linear nonzerodivisor ell in Cbar_1, the natural graded map

    C[ell] -> Cbar

  is an isomorphism.  Hence

    Cbar ~= C[ell].

Proof:
  The saturated-core profile gives the graded C[ell]-module decomposition

    Cbar ~= C[ell]

  when the Artin-reduction h-vector is (1).  The degree-zero generator is the
  unit of Cbar, so this module isomorphism is the natural algebra map generated
  by ell.  Therefore it is an isomorphism of graded C-algebras.
Qed.

Theorem multiplicity_one_degree_three_torsion_has_dimension_at_most_four:
  One has

    dim_C T_3 <= 4.

Proof:
  Since dim Cbar_3=1 and dim R_3=8,

    dim_C Jsat_3=7.

  The ordinary degree-three principal piece is

    J_3=a*R_1.

  We bound the kernel of multiplication by a on R_1.

  On X, multiplication by the quadratic section a gives

    H^0(X,O_X(1)) --a--> H^0(X,O_X(3)).

  Its cokernel is the degree-three section space of the zero scheme of a on X,
  namely Y=Proj(Cbar).  Since e(Cbar)=length(Y)=1, that cokernel has dimension
  one.  Source and target both have dimension eight, so the kernel also has
  dimension one.

  Because R is one-dimensional Cohen--Macaulay, H^0_m(R)=0.  Hence the natural
  map

    R_1 -> H^0(X,O_X(1))

  is injective.  The kernel of a:R_1->R_3 therefore has dimension at most one.
  Since dim R_1=4,

    dim J_3=rank(a:R_1->R_3)>=3.

  Thus

    dim T_3
      = dim(Jsat_3/J_3)
      <= 7-3
      =4.
Qed.

