Theorem active_cut_annihilator_is_exactly_the_saturation_torsion:
  One has

    0:_B h = T.

Proof:
  The preceding theorem gives T subseteq 0:_B h.

  Conversely suppose h*b=0 in B.  Modulo T,

    hbar*bbar=0

  in Cbar=C[ell].  Since hbar is nonzero and C[ell] is a domain, bbar=0.
  Thus b belongs to T.
Qed.

Theorem active_principal_ideal_meets_torsion_trivially:
  One has

    hB intersect T = 0.

