Theorem multiplicity_one_two_cut_ideal_splits:
  Put

    L:=(h,k)B.

  Then as B-modules

    L=hB direct_sum kB.

  Consequently the natural short exact sequence

    0 -> hB -> L -> L/hB -> 0

  splits B-linearly and

    L/hB ~= kB.

Proof:
  The sum hB+kB is L by definition, and the preceding corollary proves that
  the intersection is zero.  Projection onto the kB factor gives the splitting.
Qed.

