Theorem active_core_cut_has_degree_at_least_nineteen:
  One has

    n>=19.

Proof:
  Since Cbar~=C[ell], every nonzero homogeneous element of degree n is a scalar
  multiple of ell^n.  Therefore the saturated final ideal is principal:

    (fbar,gbar)=(ell^n).

  Hence

    length_C(Cbar/(fbar,gbar))=n.

  The exact torsion/core quotient sequence gives

    0 -> T/(T intersect (f,g)B)
      -> A
      -> Cbar/(fbar,gbar)
      -> 0.

  Thus

    N=n+kappa

  with

    0<=kappa<=length(T)<=13.

  Since N>=32,

    n>=32-13=19.
Qed.

Theorem the_second_minimal_cut_is_pure_embedded_torsion:
  The other final generator k has zero image in Cbar.  Hence

    k in T.

  Moreover

    deg(k) in {3,4}.

Proof:
  Suppose instead that kbar is nonzero.  By the choice of h,

    deg(k)>=n.

  Since Cbar=C[ell], there is a scalar c such that

    kbar=c*ell^(deg(k)-n)*hbar.

  Therefore in B

    t:=k-c*ell^(deg(k)-n)*h

  belongs to T_(deg(k)).

  But

    deg(k)>=n>=19>=5

  and T_m=0 for every m>=5.  Hence t=0, so

    k in hB.

  This makes k redundant in the B-ideal (f,g)B.  Equivalently, it is redundant
  modulo Q in I=Q+(f,g), contradicting the assumption that I has exactly six
  minimal generators with four quadratic generators and the two displayed
  higher-degree generators minimal.

  Thus kbar=0 and k belongs to T.

  Since k is a nonzero homogeneous minimal generator, deg(k)>=3.  Since T has
  no components in degree five or above, deg(k)<=4.  Therefore

    deg(k) in {3,4}.
Qed.

