4. CYCLIC THIRD EXT FORCES ONE LAST SYZYGY OF B
--------------------------------------------------------------------------

Since depth_m(B)=1 and S has depth four, Auslander--Buchsbaum gives

    pd_S(B)=3.

Thus a minimal resolution of B has the form

    0 -> F3 -> F2 -> S(-2)^4 -> S -> B -> 0.

After dualizing by S(-4), the module Ext^3_S(B,S(-4)) is the cokernel of

    Hom_S(F2,S(-4)) -> Hom_S(F3,S(-4)).

Because the resolution is minimal, every entry of this dual presentation lies
in the homogeneous maximal ideal. Therefore the minimal generators of Ext^3
are exactly the dual basis generators contributed by the summands of F3.

Section 3 says Ext^3_S(B,S(-4)) has exactly one minimal generator, and that its
degree is -1. Consequently

    F3 = S(-5).

Theorem H01_m2_R2_last_syzygy_is_unique:
  The minimal resolution of B has exactly one third-syzygy summand, namely

    beta_{3,5}(B)=1,

  and beta_{3,j}(B)=0 for j!=5.
Qed.

In particular all possible quartic or higher ghost-pair alternatives are
eliminated without a tangent estimate.

