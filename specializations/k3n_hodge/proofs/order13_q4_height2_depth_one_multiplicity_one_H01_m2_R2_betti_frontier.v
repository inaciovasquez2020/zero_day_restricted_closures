    Ext^3_S(D,S(-4)) ~= S/(r,q1,q2,q3)(1).

Theorem H01_m2_R2_ext3_is_cyclic:
  Ext^3_S(D,S(-4)) has exactly one minimal generator, in degree -1.
Qed.

By Section 2 the same is true for Ext^3_S(B,S(-4)).

