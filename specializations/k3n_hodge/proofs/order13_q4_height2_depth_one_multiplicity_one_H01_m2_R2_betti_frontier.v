3. THIRD EXT OF D IS CYCLIC WITH GENERATOR DEGREE -1
--------------------------------------------------------------------------

Dualize the exact R2 resolution of D by S(-4).

The final dual target is

    Hom_S(S(-5),S(-4)) = S(1).

The preceding dual source is

    Hom_S(S(-3)^3 direct_sum S(-4),S(-4))
      = S(-1)^3 direct_sum S.

All entries in the original minimal differential lie in the homogeneous maximal
ideal, so the image in S(1) contains no degree-zero unit. Therefore the cokernel

    Ext^3_S(D,S(-4))

is minimally generated by the single class of the generator of S(1), in graded
degree -1.

Equivalently, for suitable homogeneous forms

