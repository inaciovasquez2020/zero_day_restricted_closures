2. THIRD EXT OF B IS IDENTICAL TO THIRD EXT OF D
--------------------------------------------------------------------------

The line ring S/P has projective dimension two over S. Therefore

    Ext^i_S(S/P,S(-4))=0

for every i>=3.

Apply Hom_S(-,S(-4)) to

    0 -> D -> B -> S/P -> 0.

The long exact Ext sequence gives a graded isomorphism

    Ext^3_S(B,S(-4)) ~= Ext^3_S(D,S(-4)).

Theorem H01_m2_R2_ext3_transfer:
  The natural map induced by D -> B gives

    Ext^3_S(B,S(-4)) ~= Ext^3_S(D,S(-4)).
Qed.

This is the key rigidity input: the last syzygy module of B must encode the
same minimal generator structure as the already-known R2 canonical module of D.

