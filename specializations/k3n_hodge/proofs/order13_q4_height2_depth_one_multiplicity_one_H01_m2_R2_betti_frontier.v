1. EXACT HILBERT SERIES OF B
--------------------------------------------------------------------------

Because Q=Qsat and D=P/Q, there is an exact sequence

    0 -> D -> B -> S/P -> 0.

Since

    Hilb_(S/P)(t)=1/(1-t)^2

and

    Hilb_D(t)=(2*t+t^2)/(1-t),

one gets

    Hilb_B(t)
      = 1/(1-t)^2 + (2*t+t^2)/(1-t)
      = (1+2*t-t^2-t^3)/(1-t)^2.

Hence

    dim_C B_0=1,
    dim_C B_1=4,
    dim_C B_2=6,
    dim_C B_3=7,

and for every n>=2,

    dim_C B_n=n+4.

Multiplying by (1-t)^4 gives the exact ambient Hilbert numerator

    (1-t)^4 Hilb_B(t)
      = 1-4*t^2+3*t^3+t^4-t^5.

The coefficient 3 in degree three agrees with the standing value sigma=3.

