2. REDUCE THE MINIMAL R1 PRESENTATION MODULO h
--------------------------------------------------------------------------

The established R1 minimal resolution remains minimal after the D-regular cut.
In particular the presentation of

    E=D/hD

has two generators in degree one, five minimal relations in degree two, and one
minimal relation in degree three.

Choose the rank-one normal-form basis

    e0,e1 in E_1

so that

    m_R*e0=0,
    v*e1=w*e1=0,
    u*e1!=0,
    u^2*e1=0.

Thus the full degree-two relation space is

    R_1*e0 direct_sum span_C{v,w}*e1,

and the unique minimal cubic relation is represented by

    u^2*e1.

A constant GL_2 change of the two generators of P induces the same change on
the two degree-one generators of E.  Choose homogeneous linear generators

    a,b

of the image Pbar=(P+(h))/(h) so that a maps to e0 and b maps to e1.

The intrinsic P-Koszul relation is then

    b*e0-a*e1=0.

Because the coefficient of e1 in every degree-two relation belongs to
span_C{v,w}, the intrinsic relation forces

    a in span_C{v,w}.

Since a,b are independent, exactly two incidence types remain:

  TYPE I:
    b also belongs to span_C{v,w};

  TYPE II:
    b does not belong to span_C{v,w}.

Theorem H01_m2_R1_Artinian_P_incidence_split:
  After coordinates, every R1 endpoint lies in exactly one of these two types.
Qed.

