4. TYPE II NORMAL FORM AND ITS REDUCED COLON
--------------------------------------------------------------------------

Assume Type II.  Normalize

    a=v.

Since b is outside span_C{v,w}, its image in the one-dimensional quotient
R_1/span_C{v,w} is nonzero.  Replace the chain coordinate u by b and then
change the basis inside span_C{v,w}; this preserves the rank-one module normal
form.  Thus we may take

    a=v,
    b=u,
    span_C{v,w}=Ann_R(e1)_1.

The degree-two relation space again maps by

    A*e0+B*e1 |-> A*v+B*u.

After removing the intrinsic relation

    u*e0-v*e1,

the four-dimensional quadratic image is

    Qbar_2
      = span_C{u*v,v^2,v*w,u*w}.

Hence

    Qbar=(u*v,v^2,v*w,u*w).

The unique cubic relation u^2*e1 maps to

    gammabar=u^3

modulo Qbar.

A direct monomial colon calculation gives

    (Qbar:u^3)=(v,w).

Indeed v*u^3 is divisible by u*v and w*u^3 is divisible by u*w, while no power
of u alone lies in Qbar.

Theorem H01_m2_R1_TypeII_reduced_colon:
  In Type II one has

    Qbar=(u*v,v^2,v*w,u*w),
    gammabar=u^3,
    (Qbar:gammabar)=(v,w).
Qed.

