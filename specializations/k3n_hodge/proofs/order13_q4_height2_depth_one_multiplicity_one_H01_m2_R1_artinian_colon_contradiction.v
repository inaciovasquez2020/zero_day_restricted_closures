3. TYPE I NORMAL FORM AND ITS REDUCED COLON
--------------------------------------------------------------------------

Assume Type I.  Since a,b are independent in span_C{v,w}, change coordinates
inside that plane and normalize

    a=v,
    b=w.

The map from a degree-two relation

    A*e0+B*e1

back to the ideal Qsat modulo h sends it to

    A*a+B*b=A*v+B*w.

The degree-two relation space is

    R_1*e0 direct_sum (v,w)*e1.

After quotienting by the one intrinsic relation

    w*e0-v*e1,

the image is the four-dimensional quadratic space

    Qbar_2
      = span_C{u*v,v^2,v*w,w^2}.

Because Q and Qsat have exactly the same degree-two part and Q is generated by
its four quadrics,

    Qbar=(u*v,v^2,v*w,w^2)

inside R.

The unique minimal cubic relation u^2*e1 maps to the cubic saturation class

    gammabar=u^2*w

modulo Qbar, after replacing gamma by an equivalent representative modulo Q_3
if necessary.

Now compute the monomial colon.  A monomial multiple of u^2*w belongs to Qbar
exactly when the multiplier belongs to (v,w).  Hence

    (Qbar:gammabar)=(v,w).

Theorem H01_m2_R1_TypeI_reduced_colon:
  In Type I one has

    Qbar=(u*v,v^2,v*w,w^2),
    gammabar=u^2*w,
    (Qbar:gammabar)=(v,w).
Qed.

