1. THE CYCLIC SATURATION COLON IS m-PRIMARY
--------------------------------------------------------------------------

Because

    T=Qsat/Q

is the saturation defect, T has finite length.  Since Qsat=Q+(gamma), the map

    S -> T,
    s |-> s*gamma+Q

is surjective with kernel

    Kgamma=(Q:gamma).

Thus

    T ~= S/Kgamma(-3).

Since T is nonzero finite length, Kgamma is a proper homogeneous m-primary
ideal.  Therefore for some N>>0,

    m^N subset Kgamma.

For every linear form h, its image

    Kbar:=(Kgamma+(h))/(h)

in R=S/(h) is consequently m_R-primary.

Theorem H01_m2_R1_saturation_colon_mprimary:
  Kgamma is homogeneous m-primary, and its image Kbar modulo the chosen general
  D-regular h is homogeneous m_R-primary.
Qed.

