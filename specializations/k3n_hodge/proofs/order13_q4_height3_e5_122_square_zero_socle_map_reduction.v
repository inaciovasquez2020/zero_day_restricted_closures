The purpose of this file is one bounded sharpening.  In the square-zero case
the embedded torsion surviving inside X has a one-dimensional graded socle.
Because K_1 is minimally two-generated, arbitrary images of its two minimal
generators into that socle give a two-dimensional plane of C-linear maps.
Grading shows that this plane intersects the ordinary multiplication maps in
at most one dimension, and in zero dimensions when the final-cut ideal already
contains the top torsion line T_3.

Combining this with the exact length-eighteen regular-cubic section in the
square-zero case closes the T_3-contained subcase and reduces the other subcase
to a rigid equality configuration with eta_1=17.

Theorem final_cut_intersection_with_square_zero_torsion_is_top_line_or_zero:
  One has

    L intersect T in {0,T_3}.

Proof:
  The final-cut ideal L is homogeneous and generated in degrees at least three.
  The torsion module T is concentrated in degrees one, two, and three, with

    dim_C T_3=1.

  Therefore L intersect T has no degree-one or degree-two part and is a graded
  subspace of the one-dimensional degree-three line T_3.  Hence it is either
  zero or all of T_3.
Qed.

