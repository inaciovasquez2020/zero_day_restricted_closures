Theorem square_zero_regular_cubic_section_has_length_eighteen:
  There is a homogeneous cubic

    q=ell*(a+lambda*b) in K_1

  whose image in C is a nonzerodivisor and such that

    0:_B q=T,
    0:_J q=T.

  Consequently

    length_C(J/qJ)=18,
    dim_C(0:_X q)<=18,
    dim_C A_1<=18.

Proof:
  Since K_0=(a,b) is m-primary in the one-dimensional Cohen--Macaulay ring C,
  a general constant combination

    q0:=a+lambda*b

  is a nonzerodivisor on C.  Then q:=ell*q0 is again regular on C and belongs
  to K_1 because

    q=ell*a+lambda*ell*b.

  The element q has degree three and m_B^3*T=0, so q kills T.  Conversely,
  regularity on C shows every element killed by q in B belongs to T.  Hence

    0:_B q=T.

  In ZERO_SELF_ACTION one has T subseteq J, so

    0:_J q=J intersect (0:_B q)=T,

  of length three.

  Since B/J has finite length, J has multiplicity five.  The multiplication
  exact sequence by the cubic q on J therefore gives

    length(J/qJ)
      =3*e(J)+length(0:_J q)
      =15+3
      =18.

  Since X=J/L, the quotient X/qX is a quotient of J/qJ, so

    dim(0:_X q)=length(X/qX)<=18.

  Finally K_1 contains q, hence

    A_1=0:_X K_1 subseteq 0:_X q.
Qed.

