Theorem the_square_zero_socle_plane_has_at_most_one_multiplication_direction:
  One has

    dim_C(P intersect im(mu))<=1.

  If L intersect T=T_3, then in fact

    P intersect im(mu)=0.

Proof:
  First suppose L intersect T=0.  Then S_X=T_3 lies in degree three.

  If a multiplication map mu(x) belongs to P, both

    a*x and ell*b*x

  lie in the single degree-three line T_3.  The element ell*b has degree three.
  A degree-three output from multiplication by ell*b could only come from the
  degree-zero part of x.  But

    X_0=J_0=0,

  because J=Ann_B(T) is a proper homogeneous ideal and T is nonzero.  All
  positive-degree parts of x produce degree at least four.  Since mu(x) belongs
  to P, those higher-degree outputs must vanish.  Therefore

    ell*b*x=0.

  Hence every element of P intersect im(mu) lies in the one-dimensional line of
  socle maps

    a |-> S_X,
    ell*b |-> 0.

  Thus the intersection has dimension at most one.

  Now suppose L intersect T=T_3.  Then S_X is represented by T_2 and lies in
  degree two.  Multiplication by a has degree two, so a degree-two output would
  require a degree-zero component of x, which is zero.  Multiplication by
  ell*b has degree three and cannot produce degree two from any nonnegative
  degree.  Hence both generator images vanish, so the multiplication map is
  zero.  Therefore P intersect im(mu)=0.
Qed.

