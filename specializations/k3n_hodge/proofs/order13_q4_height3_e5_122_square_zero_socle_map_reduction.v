Theorem arbitrary_socle_values_define_two_independent_square_zero_maps:
  For every ordered pair (s,t) in S_X direct_sum S_X there is a unique C-linear
  homomorphism

    psi_(s,t):K_1 -> T_X subset X

  satisfying

    a |-> s,
    ell*b |-> t.

  Consequently these maps form a two-dimensional subspace

    P subseteq Hom_C(K_1,X).

Proof:
  Because a and ell*b form a minimal generating set of K_1 over the graded
  local ring (C,m_C), every coefficient in every relation

    p*a+q*ell*b=0

  belongs to m_C.  Since S_X is killed by m_C, both p*s and q*t vanish for
  arbitrary s,t in S_X.  Thus every assignment of the two generators to S_X
  respects all relations and defines a C-linear map.

  Evaluation on the two minimal generators identifies the resulting map space
  with S_X direct_sum S_X.  Since dim_C S_X=1, this plane has dimension two.
Qed.

