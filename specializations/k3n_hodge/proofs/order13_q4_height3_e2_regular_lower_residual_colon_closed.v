For completeness, write the three minors as

  Delta12:=a*d0-b*c,
  Delta13:=a*s-b*p,
  Delta23:=c*s-d0*p.

The Cramer identities are

  x*Delta12 = d0*(x*a+y*b)-b*(x*c+y*d0),
  y*Delta12 = a*(x*c+y*d0)-c*(x*a+y*b),

and similarly for Delta13 and Delta23.  Thus each Delta_ij visibly annihilates
J/G inside B; the residual-intersection theorem proves that they generate the
whole annihilator.

Theorem annihilator_of_saturation_torsion_has_at_most_three_generators:
  In B=V/G,

    Ann_B(T)
      = (G:J)/G
      = (G+I_2(Psi))/G.

  Hence Ann_B(T) is generated as a B-module by the images of

    Delta12, Delta13, Delta23,

  and therefore

    mu_B(Ann_B(T))<=3.

Proof:
  Since T=J/G, an element b+G in B annihilates T exactly when

    b*J subseteq G,

  namely when b belongs to G:J.  This identifies Ann_B(T) with (G:J)/G.
  Substitute the exact residual-colon formula.  The three minors generate
  I_2(Psi).
Qed.

