Theorem residual_colon_has_height_three:
  Put

    H:=G:J=G:(x,y)

  in V.  Then

    ht(H)=3.

Proof:
  The quotient J/G=T is finite length because J is the homogeneous saturation
  of G.  Hence for every homogeneous prime P different from the irrelevant
  maximal ideal,

    G_P=J_P.

  Localizing the colon gives

    H_P=G_P:J_P=J_P:J_P=V_P.

  Therefore no nonmaximal homogeneous prime contains H.  Since V has dimension
  three, H is supported at the irrelevant maximal ideal and has height three.
Qed.

Theorem exact_residual_colon_formula_for_the_e2_defect:
  One has

    G:(x,y)=G+I_2(Psi).

Proof:
  The ring V is Cohen--Macaulay because it is a hypersurface quotient of S.
  The preceding theorems give that x,y is a regular sequence and that the
