Theorem normalize_the_e2_saturation_complete_intersection:
  After a linear change of coordinates, the saturated ideal Qsat has the form

    Qsat=(x,y,q0),

  where x,y are independent linear forms and q0 is a quadric, and x,y,q0 form
  an S-regular sequence.

Proof:
  The rank-two core Cbar=S/Qsat is a one-dimensional graded Gorenstein algebra
  with h-vector (1,1).  Equivalently it is a quadratic hypersurface after two
  independent linear equations.  Thus its defining height-three ideal is the
  complete intersection CI(1,1,2).  Choose the two linear generators as x,y
  and the quadratic generator as q0.
Qed.

Theorem normalize_three_quadrics_inside_Qsat:
  After changing the basis of three quadratic generators inside Q, one may
  write

    q1=x*a+y*b,
    q2=x*c+y*d0,
    q3=q0,

  for linear forms a,b,c,d0.

Proof:
  Choose any regular sequence of three quadratic combinations q1,q2,q3 inside
  Q.  Since Q subseteq Qsat=(x,y,q0), every qi has an expression

    qi=x*ai+y*bi+lambda_i*q0

  with ai,bi linear and lambda_i scalar.

  At least one lambda_i is nonzero; otherwise all three quadrics would lie in
  (x,y), contradicting height three.  A GL_3(C) change of the regular-sequence
  basis makes

    lambda_1=lambda_2=0,
    lambda_3=1.

  Replacing the chosen quadratic generator q0 of Qsat by q3 preserves
  Qsat=(x,y,q0).  This yields the displayed form.
Qed.

Let r be the fourth quadratic generator of Q after the preceding basis choice.

Theorem fourth_quadric_has_one_more_row_form:
  Modulo q0 one may write

    r=x*p+y*s

  for linear forms p,s.

  Consequently, in

    V:=S/(q0),

  the ideal defining B is

    G=(x*a+y*b,
       x*c+y*d0,
       x*p+y*s).

  The saturated ideal becomes

    J=(x,y) subset V,

  and

    B=V/G,
    T=J/G.

Proof:
  Since r belongs to Q subseteq Qsat=(x,y,q0), write

    r=x*p+y*s+lambda*q0.

  Replacing r by r-lambda*q0 is an invertible change among the four quadratic
  generators and gives the displayed form.  Passing to V kills q0.

  The image of Qsat in V is exactly (x,y).  Since T=Qsat/Q, its image in the
  quotient B is J/G.
Qed.

