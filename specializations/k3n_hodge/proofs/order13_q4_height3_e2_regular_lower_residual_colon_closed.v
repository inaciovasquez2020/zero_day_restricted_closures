Theorem torsion_annihilator_after_the_final_cuts_is_the_residual_colon_quotient:
  The natural map gives

    N_T:=Ann_A(T)
       ~= Ann_B(T)/L.

Proof:
  Because L*T=0, the ideal L is contained in Ann_B(T), so the displayed
  quotient maps naturally into A.

  Conversely let b+L annihilate T in A.  Then

    b*T subseteq L.

  Since T is an ideal of B, b*T is contained in T.  Therefore

    b*T subseteq L intersect T=0.

  Thus b annihilates T already in B, so b belongs to Ann_B(T).  This proves the
  equality.
Qed.

Corollary NT_has_at_most_three_generators:
  One has

    mu_A(N_T)<=3.

  Because T annihilates N_T, the A-action on N_T factors through

    A/T ~= A0,

