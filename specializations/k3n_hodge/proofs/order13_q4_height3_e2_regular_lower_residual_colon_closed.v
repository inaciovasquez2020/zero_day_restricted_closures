ExternalResult ThreeResidualIntersectionOfTwoGeneratedCompleteIntersection:
  Let V be a Cohen--Macaulay ring and let

    J=(x,y)

  be generated by a V-regular sequence.  Let

    G=(g1,g2,g3) subseteq J

  with

    [g1,g2,g3]^T = Psi*[x,y]^T

  for a 3-by-2 matrix Psi.  If

    ht(G:J)>=3,

  then the standard residual-intersection formula gives

    G:J = G + I_2(Psi),

  where I_2(Psi) is the ideal generated by the three 2-by-2 minors of Psi.

  This is the codimension-two, three-residual-intersection specialization of
  the Bruns--Kustin--Miller resolution of residual intersections of complete
  intersections.  The easy inclusion I_2(Psi) subseteq G:J follows directly
  from the 2-by-2 Cramer identities; the height-three hypothesis is the
  residual-intersection condition needed for the reverse inclusion.

