Theorem the_length_three_residual_ring_is_Gorenstein:
  C0 is a one-dimensional standard graded Gorenstein ring.

Proof:
  The preceding theorem gives

    Hilb_C0(t)=(1+t+t^2)/(1-t).

  Choose a general linear nonzerodivisor lambda on C0.  Then

    C0/lambda*C0

  has Hilbert function

    (1,1,1).

  Any standard graded Artin C-algebra with this Hilbert function is generated
  by its one-dimensional degree-one piece.  If z spans degree one, then z^2
  spans degree two and z^3=0.  Thus its socle is exactly the one-dimensional
  degree-two piece, so the Artin reduction is Gorenstein.

  A regular linear reduction preserves Cohen--Macaulay type.  Hence C0 has
  type one and is Gorenstein.
Qed.

