Theorem exact_annihilator_of_the_saturation_torsion_in_B:
  One has

    Ann_B(T)
      =(K+cR)/(u*c*R).

  Consequently

    B/Ann_B(T) ~= R/(K,c),

  and

    length_C(B/Ann_B(T))=3.

Proof:
  Write B=R/(u*c).  An element r modulo u*c annihilates

    T=uR/u*cR

  exactly when

    r*u belongs to u*cR.

  Under the isomorphism

    R/K -> uR,
    x mod K |-> u*x,

  this is equivalent to

    r mod K belongs to c*(R/K),

  namely

    r belongs to K+cR.

  This proves the annihilator formula.  Quotienting B by this annihilator gives

    R/(K,c)=C0/c*C0,

  whose Hilbert function is (1,1,1), hence whose length is three.
Qed.

