Theorem K_is_saturated_and_the_residual_ring_is_CohenMacaulay:
  The ideal K is saturated.  Consequently R/K is one-dimensional
  Cohen--Macaulay.

Proof:
  Suppose x is homogeneous and some power of the irrelevant ideal sends x
  into K.  Choose a linear nonzerodivisor lambda on the one-dimensional
  Cohen--Macaulay ring R.  Then for sufficiently large n,

    lambda^n*x belongs to K=0:_R U.

  Hence for every u in U,

    lambda^n*x*u=0.

  Since lambda is R-regular, multiplication by lambda^n is injective on R, so

    x*u=0

  for every u in U.  Therefore x belongs to 0:_R U=K.

  Thus K is saturated.  The Hilbert series in the preceding theorem has
  positive eventual value three, so dim(R/K)=1.  Saturation removes H^0_m,
  hence depth(R/K)>=1.  Therefore R/K is Cohen--Macaulay.
Qed.

