Interpretation:
  The five-point h=(1,3,1) core does not require a classification of its full
  multiplication algebra.  The only distinction needed is whether the lower
  quadratic predecessor a meets every minimal component.

  If it does, the degree-two section itself bounds the entire connecting
  excess by eleven.

