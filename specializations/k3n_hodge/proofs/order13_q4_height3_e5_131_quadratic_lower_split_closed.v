Theorem every_layer_from_two_on_has_nonpositive_Bockstein_defect:
  For every i>=2,

    Delta_i<=0.

Proof:
  The exact layer-annihilator formula gives

    Ann_Cbar(V_i)=(G:ell^(i-1),ell).

  For i>=2, the one-step saturation theorem gives

    G:ell^(i-1)=Gsat.

  Hence every such layer is the same stable cyclic module

    V_i ~= Cbar/(Gsat,ell)

  up to grading shift.

  The stable cyclic connecting-map argument proved in the preceding quadratic
  reduction now applies verbatim with stabilization index two instead of
  three.  Put

    N_G:=0:_X Gsat.

  For y in N_G, the map K_i->X which sends

    a |-> 0,
    ell^i*b |-> y

  is well defined because every coefficient relation on ell^i*b lies in
  G:ell^i=Gsat.  Its connecting class is represented by the cyclic relation
  ell |-> y and Gsat |-> 0.  This class vanishes exactly for

    y in ell*N_G.

  Therefore the explicit connecting classes have rank

    dim_C(N_G/ell*N_G)
      =dim_C(0:_N_G ell)
      =dim_C Hom_Cbar(Cbar/(Gsat,ell),X)
      =dim_C Hom_Cbar(V_i,X),

  where the middle equality is rank-nullity for multiplication by ell on the
  finite-dimensional module N_G.

  Applying Hom(-,X) to

    0 -> K_i -> K_(i-1) -> V_i -> 0

  therefore gives Delta_i<=0.
Qed.

