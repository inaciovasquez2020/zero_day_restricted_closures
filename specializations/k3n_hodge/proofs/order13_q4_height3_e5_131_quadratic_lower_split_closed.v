SECTION ZERODIVISOR_QUADRATIC_LOWER.

Assume a is a zerodivisor on Cbar.

Theorem the_saturated_colon_is_proper:
  The ideal

    Gsat=(a:b):ell^infinity

  is a proper homogeneous ideal of Cbar.

Proof:
  Because Cbar is one-dimensional Cohen--Macaulay, it has no embedded
  associated primes.  Since a is a zerodivisor, there is a minimal prime P of
  Cbar with

    a in P.

  Since K_0=(a,b) is m-primary, b cannot belong to P.  Thus b is a unit after
  localizing at P, and

    G_P=(a:b)_P=(a)_P.

  This is a proper ideal of the zero-dimensional local ring Cbar_P because
  a belongs to its maximal ideal.

  The parameter ell is a nonzerodivisor on Cbar, so ell is not in P and becomes
  a unit in Cbar_P.  Saturating by powers of ell therefore does not change this
  localization:

    (Gsat)_P=G_P.

  Since the latter is proper, Gsat itself is proper.
Qed.

Corollary the_quadratic_colon_has_no_degree_zero_saturation_defect:
  One has

    (Gsat/G)_0=0.

Proof:
  A proper homogeneous ideal of the standard graded C-algebra Cbar has zero
  degree-zero part.  Thus (Gsat)_0=0, and the same is true of its subideal G.
Qed.

Theorem zerodivisor_quadratic_colon_saturates_after_one_parameter_step:
  One has

    G:ell=Gsat,

  and hence

    G:ell^j=Gsat

  for every j>=1.

Proof:
  The preceding quadratic-core reduction already proves

    (Gsat/G)_n=0

  for every n>=2.  The preceding corollary removes degree zero.  Therefore the
  finite saturation quotient Gsat/G can occur only in degree one.

  Let x be homogeneous in Gsat.

  If deg(x)>=2, then x already belongs to G.

  There is no nonzero degree-zero case because Gsat is proper.

  If deg(x)=1, then ell*x has degree two and lies in Gsat_2=G_2.  Hence

    x belongs to G:ell.

  Thus Gsat subseteq G:ell.  The reverse inclusion is automatic from the
  definition of saturation, proving equality.  All later colons are then equal
  to Gsat as well.
Qed.

For i>=1 put

