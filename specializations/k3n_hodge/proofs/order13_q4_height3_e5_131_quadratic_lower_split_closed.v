Theorem multiplication_maps_give_a_universal_annihilator_bound:
  For every i>=0, multiplication defines a Cbar-linear map

    mu_i:X -> Hom_Cbar(K_i,X),
    mu_i(z)(u):=u*z.

  Its kernel is

    ker(mu_i)=0:_X K_i.

  Consequently

    (N-1)-dim_C Hom_Cbar(K_i,X)
      <=dim_C(0:_X K_i).

Proof:
  Cbar-linearity is immediate from commutativity.  The multiplication map
  mu_i(z) is zero exactly when every element of K_i kills z, namely exactly
  when z belongs to 0:_X K_i.

  Since dim_C X=N-1, rank-nullity gives

    dim im(mu_i)
      =(N-1)-dim_C(0:_X K_i).

  The image is a subspace of Hom_Cbar(K_i,X), so the displayed inequality
  follows.
Qed.

SECTION REGULAR_QUADRATIC_LOWER.

Assume a is a nonzerodivisor on Cbar.

Theorem regular_quadratic_has_only_the_socle_line_as_kernel_in_B:
  One has

    0:_B a=T.

Proof:
  Since a has positive degree and m_B*T=0, one has T subseteq 0:_B a.

  Conversely, if a*x=0 in B, then after projection to Cbar,

    a*xbar=0.

  Regularity of a on Cbar gives xbar=0, hence x belongs to T.
Qed.

Theorem regular_quadratic_section_of_B_has_length_eleven:
  One has

    Hilb_(B/aB)(t)=1+4*t+5*t^2+t^3,

  and therefore

    length_C(B/aB)=11.

Proof:
  The kernel theorem gives the multiplication exact sequence

    0 -> T(-2)
      -> B(-2)
      --a--> B
      -> B/aB
      -> 0.

  Since

    Hilb_B=Hilb_Cbar+t^2,
    Hilb_Cbar=(1+3*t+t^2)/(1-t),
    Hilb_T=t^2,

  one gets

    Hilb_(B/aB)
      =(1-t^2)*Hilb_B+t^2*Hilb_T
      =(1-t^2)*Hilb_Cbar+Hilb_T
      =1+4*t+5*t^2+t^3.
Qed.

Theorem regular_quadratic_lower_forces_epsilon_at_most_eleven:
  One has

    epsilon<=11.

Proof:
  Since K_k contains a,

    0:_X K_k subseteq 0:_A a.

  Multiplication by a on the finite-dimensional algebra A has kernel and
  cokernel of equal dimension, hence

    dim_C(0:_A a)=length_C(A/aA).

  The quotient A/aA is a quotient of B/aB, so

    dim_C(0:_A a)<=11.

  Apply the universal multiplication bound at i=k and use

    epsilon=(N-1)-dim Hom_Cbar(K_k,X).
Qed.

Corollary regular_quadratic_lower_is_closed:
  No candidate with a regular on Cbar can satisfy the necessary tangent gate.

Proof:
  The gate requires epsilon>=19, while the preceding theorem gives
  epsilon<=11.
Qed.

