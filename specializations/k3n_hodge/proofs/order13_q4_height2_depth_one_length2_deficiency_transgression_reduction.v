3. EXACT KOSZUL DEFECT ON THE SATURATED CORE
--------------------------------------------------------------------------

Define

    D1_sat := H_1(f,g;C0).

Theorem length_two_Rao_module_is_exactly_the_saturated_core_Koszul_H1:
  There is a natural graded isomorphism

    D1_sat ~= M(-deg(f)-deg(g)).

  In particular

    dim_C D1_sat=2,
    m^2*D1_sat=0.

Proof:
  Apply the two-element Koszul complex K(f,g;-) to

    0 -> C0 -> D -> M -> 0.

  This gives a short exact sequence of complexes.

  The pair f,g is regular on D, so

    H_2(f,g;D)=0,
    H_1(f,g;D)=0.

  The final high-degree pair annihilates M.  Therefore the Koszul differential
  on K(f,g;M) is zero and

    H_2(f,g;M) ~= M(-deg(f)-deg(g)).

  The relevant long exact homology segment is

    0
      -> H_2(f,g;M)
      -> H_1(f,g;C0)
      -> 0.

  This gives the claimed isomorphism.  The annihilation statement follows from
  m^2*M=0.
Qed.

