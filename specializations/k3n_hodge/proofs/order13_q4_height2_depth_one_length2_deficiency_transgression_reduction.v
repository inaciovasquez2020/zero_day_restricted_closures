2. MACAULAYFICATION OF THE SATURATED DEPTH-ONE CORE
--------------------------------------------------------------------------

ExternalResult dimension_two_ideal_transform_macaulayfication:
  Let C be a finitely generated standard graded C-algebra of dimension two
  with

    H^0_m(C)=0

  and finite-length H^1_m(C).  Its homogeneous ideal transform / section ring

    D := D_m(C)

  is finite over C and fits into a natural graded exact sequence

    0 -> C -> D -> H^1_m(C) -> 0.

  Moreover

    H^0_m(D)=H^1_m(D)=0,

  so depth_m(D)=2.  Thus D is Cohen--Macaulay of dimension two.

Apply this external result to C0 and put

    D := D_m(C0).

Then

    0 -> C0 -> D -> M -> 0

is exact and D is Cohen--Macaulay of dimension two.

Theorem the_final_pair_is_regular_on_the_macaulayfication:
  The images of f,g in D form a regular sequence.

Proof:
  The saturated-core profile proves that the images of f,g form an m-primary
  parameter pair on C0.

  The module D is finite over C0.  Therefore

    D/(f,g)D

  is finite over C0/(f,g)C0 and hence has finite length.  Thus f,g form a
  homogeneous system of parameters on the two-dimensional ring/module D.

  Since D is Cohen--Macaulay of dimension two, that parameter pair is regular.
Qed.

