1. ABSTRACT CLASSIFICATION OF A TWO-DIMENSIONAL GRADED DEFICIENCY MODULE
--------------------------------------------------------------------------

Theorem every_length_two_deficiency_is_annihilated_by_m_squared:
  If

    dim_C M=2,

  then

    m^2*M=0.

Proof:
  Since M has finite length and is nonzero, graded Nakayama gives

    m*M != M.

  Hence dim_C(m*M) is zero or one.

  If m*M=0 there is nothing to prove.

  If dim_C(m*M)=1, apply Nakayama to the nonzero finite module m*M.  One cannot
  have

    m*(m*M)=m*M,

  so the proper submodule m^2*M of the one-dimensional vector space m*M must be
  zero.
Qed.

Corollary exact_two_shape_classification:
  Exactly one of the following module-theoretic shapes occurs.

  SEMISIMPLE SHAPE:
    m*M=0, and for some integers a,b

      M ~= C(-a) direct_sum C(-b).

  CYCLIC LENGTH-TWO SHAPE:
    dim_C(m*M)=1.  Then M/m*M and m*M are each one-dimensional, M is generated
    by one homogeneous element, and after a linear change of coordinates and
    a grading shift one may write

      M ~= S/(x2,x3,x4,x1^2)(-a).

    Equivalently its graded Hilbert support is one copy of C in degree a and
    one copy in degree a+1.

Proof:
  In the first case every homogeneous component is a direct sum of residue
  field modules because m acts trivially.

  In the second case M/m*M is one-dimensional.  Graded Nakayama therefore says
  that M is cyclic.  Choose a homogeneous generator u.  The one-dimensional
  space m*M is generated by a nonzero degree-one multiple of u.  Multiplication
  S_1 -> Hom_C(C*u,m*M) is a nonzero linear functional, so after a linear change
  of coordinates x1 has nonzero action and x2,x3,x4 kill u.  The preceding
  theorem gives x1^2*u=0.  This gives exactly the displayed cyclic module.
Qed.

Corollary the_final_high_degree_pair_annihilates_M:
  One has

    f*M=0,
    g*M=0.

Proof:
  The standing degree hypothesis gives f,g in m^3, while m^2*M=0.
Qed.

