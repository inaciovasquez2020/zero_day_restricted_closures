4. THE SATURATION TRANSGRESSION IS THE EXACT REMAINING OBSTRUCTION
--------------------------------------------------------------------------

Return to the saturation exact sequence

    0 -> T -> B -> C0 -> 0.

Define

    D1_B := H_1(f,g;B).

Theorem exact_saturation_transgression_sequence:
  There is a natural graded exact sequence

    H_1(f,g;T)
      -> D1_B
      -> M(-deg(f)-deg(g))
      --delta-->
         T/(f,g)T.

  Consequently

    image(D1_B -> M(-deg(f)-deg(g))) = ker(delta).

Proof:
  Apply K(f,g;-) to

    0 -> T -> B -> C0 -> 0

  and take the long exact homology sequence.  The degree-zero Koszul homology of
  T is

    H_0(f,g;T)=T/(f,g)T,

  while the preceding theorem identifies

    H_1(f,g;C0)=M(-deg(f)-deg(g)).

  Substitution gives exactly the displayed segment.
Qed.

Corollary exact_rank_trichotomy_for_the_length_two_deficiency:
  Since the source of delta has C-dimension two, exactly one of

    rank(delta)=0,
    rank(delta)=1,
    rank(delta)=2

  occurs.

  RANK ZERO:
    both saturated-core deficiency classes lie in the image of D1_B.

  RANK ONE:
    exactly one C-dimensional deficiency direction survives in the image of
    D1_B.

  RANK TWO:
    delta is injective, and T/(f,g)T contains a graded two-dimensional submodule
    isomorphic to M(-deg(f)-deg(g)).

Proof:
  This is immediate from exactness and dim_C M=2.  In the rank-two case the
  image of delta is isomorphic to its source as a graded module.
Qed.

Corollary a_complete_absorption_of_the_Rao_defect_forces_a_matching_torsion_tail:
  If no nonzero length-two deficiency class survives from the saturated core to
  D1_B, equivalently if delta is injective, then the saturation defect has a
  quotient modulo (f,g) containing exactly the same two-dimensional graded
  module shape as M, shifted upward by deg(f)+deg(g).

  Thus complete cancellation of the Rao contribution is not free: it requires
  a matching graded tail in T/(f,g)T.
Qed.

