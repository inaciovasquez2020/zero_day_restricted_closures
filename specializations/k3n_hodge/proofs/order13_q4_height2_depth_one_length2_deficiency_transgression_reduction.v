5. WHY THE TANGENT CLOSURE STOPS HERE
--------------------------------------------------------------------------

The previous skew-line endpoint had T=0.  There the transgression target
vanished, so delta=0 automatically and the residue-field Koszul class survived
fully in H_1(f,g;B).

In the present length-two stratum T is not known to vanish and no universal
high-degree support bound for T has yet been established.  Therefore delta may
have rank zero, one, or two.

Knowing only that the saturated-core module

    M(-deg(f)-deg(g))

is annihilated by m^2 does NOT by itself imply that the full module

    D1_B=H_1(f,g;B)

is annihilated by m^2.  Hence the two-coordinate Hom-carrier theorem cannot yet
be promoted to a universal tangent lower bound for this stratum.

