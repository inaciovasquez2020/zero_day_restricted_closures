1. NORMALIZE THE TWO r-MULTIPLE QUADRICS
--------------------------------------------------------------------------

Since r lies in the two-dimensional linear prime P, choose p independent of r
with

    P=(r,p).

Choose independent quadrics in Q_2 intersect r*S_1 and write

    q1=r*a,
    q2=r*b

with a,b independent linear forms. Complete them to a basis

    q1,q2,q3,q4

of Q_2.

Put

    W:=Q_2 intersect r*S_1.

The standing LK3-C2 hypothesis gives dim_C W>=2.

--------------------------------------------------------------------------
2. A THIRD r-MULTIPLE IS IMPOSSIBLE BY HILBERT POSITIVITY
--------------------------------------------------------------------------

Assume for contradiction that dim_C W>=3. After a generator basis change,
three independent quadratic generators are divisible by r. Modulo r only one
quadratic generator can remain.

Set

    R:=S/(r) ~= C[y1,y2,y3].

Because Q subset P=(r,p), every surviving quadratic image lies in the principal
linear ideal generated by pbar, the image of p in R. Thus

    (Q+(r))/(r)

is generated by at most one quadratic pbar*u.

If that quadratic is nonzero, then

    Hilb_(S/(Q+(r)))(t)
      = Hilb_(R/(pbar*u))(t)
      = (1+t)/(1-t)^2.

If it vanishes, the quotient is R itself and has even larger Hilbert function.

Let

    K:=(Q:r).

Multiplication by r gives the exact sequence

    0 -> S/K(-1)
      -> B
      -> S/(Q+(r))
      -> 0.

In the nonzero-quadratic case this would force

    Hilb_(S/K)(t)
      = (Hilb_B(t)-Hilb_(S/(Q+(r)))(t))/t
      = (1-t-t^2)/(1-t)^2.

Its coefficient sequence begins

    1, 1, 0, -1, -2, ...,

which is impossible for a graded quotient. The zero-quadratic case gives an
even larger right-hand quotient and is impossible a fortiori.

Therefore

    dim_C(Q_2 intersect r*S_1)=2.

Theorem H01_m2_R2_LK3_C2_r_in_P_exact_r_multiple_dimension:
  In the r-in-P half of LK3-C2,

    dim_C(Q_2 intersect r*S_1)=2.
Qed.

Consequently q3bar,q4bar are nonzero and independent modulo r.

--------------------------------------------------------------------------
3. THE MOD-r PAIR HAS THE FORM pbar*u, pbar*v
--------------------------------------------------------------------------

Because q3,q4 lie in P=(r,p), their images in R satisfy

    q3bar=pbar*u,
    q4bar=pbar*v

for linear forms u,v in R_1.

The independence of q3bar,q4bar implies that u,v are independent. Therefore
there is an exact sequence

    0 -> R/(u,v)(-1)
      -- multiplication by pbar --> R/(pbar*u,pbar*v)
      -> R/(pbar)
      -> 0.

Indeed cancellation by the nonzero element pbar in the domain R shows that the
left map is injective.

Hence

    Hilb_(S/(Q+(r)))(t)
      = 1/(1-t)^2 + t/(1-t).

Theorem H01_m2_R2_LK3_C2_r_in_P_exact_mod_r_Hilbert_series:
  One has

    Hilb_(S/(Q+(r)))(t)
      = 1/(1-t)^2 + t/(1-t).
Qed.

--------------------------------------------------------------------------
4. THE COLON K=(Q:r) IS A (1,1,2) COMPLETE INTERSECTION
--------------------------------------------------------------------------

Use again

    0 -> S/K(-1) -> B -> S/(Q+(r)) -> 0.

The exact Hilbert series now gives

    Hilb_(S/K)(t)
      = (Hilb_B(t)-Hilb_(S/(Q+(r)))(t))/t
      = (1+t)/(1-t).

Since q1=r*a and q2=r*b belong to Q,

    a,b in K_1.

They are independent. The coefficient of t in (1+t)/(1-t) is two, so

    dim_C(S/K)_1=2,
    dim_C K_1=2.

Therefore

    K_1=span_C{a,b}.

Pass to

    T:=S/(a,b) ~= C[s,t].

The image Kbar of K has no linear forms and

    Hilb_(T/Kbar)(t)=(1+t)/(1-t)
                     =(1-t^2)/(1-t)^2.

Thus Kbar has exactly one quadratic generator Fbar and no further Hilbert
defect. Hence

    K=(a,b,F)

for a quadric F whose image modulo (a,b) is nonzero.

The three forms a,b,F are a regular sequence of degrees (1,1,2). Therefore K
is a saturated height-three complete intersection and

    e(S/K)=2.

Theorem H01_m2_R2_LK3_C2_r_in_P_colon_complete_intersection:
  For K=(Q:r),

    K=(a,b,F)

  with a,b independent linear forms and F a quadric nonzero modulo (a,b).
  In particular K is a saturated complete intersection of type (1,1,2), and

    Hilb_(S/K)(t)=(1+t)/(1-t).
Qed.

