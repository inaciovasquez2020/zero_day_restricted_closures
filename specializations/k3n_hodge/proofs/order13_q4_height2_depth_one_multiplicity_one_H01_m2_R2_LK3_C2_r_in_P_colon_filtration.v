5. EXACT TWO-STEP FILTRATION OF THE RESIDUAL MODULE D
--------------------------------------------------------------------------

Multiplication by r lands inside D=P/Q because r belongs to P. By definition
of K=(Q:r), it gives an injective graded map

    S/K(-1) -> D,
    s |-> r*s mod Q.

The cokernel is

    P/(Q+r*S).

Modulo r this becomes

    (pbar)/(pbar*u,pbar*v)
      ~= R/(u,v)(-1).

Choose lifts of u,v to S and put

    J:=(r,u,v).

Because u,v are independent modulo r, J is a height-three linear prime. Thus

    R/(u,v)(-1) ~= S/J(-1).

Therefore there is an exact sequence

    0 -> S/K(-1)
      -> D
      -> S/J(-1)
      -> 0,

where

    K=(a,b,F) is a (1,1,2) complete intersection,
    J=(r,u,v) is a height-three linear prime.

The Hilbert series check is exact:

    t*(1+t)/(1-t) + t/(1-t)
      = (2*t+t^2)/(1-t)
      = Hilb_D(t).

Theorem H01_m2_R2_LK3_C2_r_in_P_exact_residual_filtration:
  D has the exact two-step filtration

    0 -> S/K(-1) -> D -> S/J(-1) -> 0

  with K and J as above.
Qed.

