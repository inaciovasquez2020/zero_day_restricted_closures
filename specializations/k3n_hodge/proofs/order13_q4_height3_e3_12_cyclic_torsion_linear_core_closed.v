The purpose of this file is one structural closure.  The h=(1,2) row has a
unique linear saturation class.  A plane-section analysis shows that the
saturation hull is either generated by that linear class alone or by that
linear class together with one quadratic class.  In the second case the
fourth quadric must use the extra quadratic generator, because otherwise the
saturation quotient would still have positive dimension.  Consequently the
saturation torsion is cyclic in both cases.

That cyclicity identifies an exact length-five annihilator quotient.  The
necessary order-13 tangent gate therefore forces a fifteen-dimensional
conormal deficit.  On the Cohen--Macaulay core, however, every final cut has a
linear predecessor.  A regular lower predecessor gives a section of length at
most eight, while a zerodivisor lower predecessor has already-saturated colon,
so every delayed layer is nonpositive and the same bound eight survives.  The
required deficit fifteen is impossible.

