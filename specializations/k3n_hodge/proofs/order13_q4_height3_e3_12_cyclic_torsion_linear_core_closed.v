Theorem the_plane_ideal_of_the_e3_12_core_is_generated_by_three_quadrics:
  The ideal J has no linear generator and is generated by its three-dimensional
  degree-two piece J_2.

Proof:
  The Hilbert series of C gives

    dim_C C_0=1,
    dim_C C_n=3 for every n>=1.

  Since dim P_1=3, one has J_1=0.  Since dim P_2=6 and dim C_2=3,

    dim_C J_2=3.

  Choose a linear nonzerodivisor ell on C.  The h-vector (1,2) gives the
  C[ell]-module decomposition

    C ~= C[ell] direct_sum C[ell](-1)^2.

  Choose degree-one elements x,y whose classes together with 1 form this free
  C[ell]-basis.  Then every one of

    x^2,
    x*y,
    y^2

  is a C-linear combination of

    ell^2,
    ell*x,
    ell*y.

  Hence there are three quadratic relations whose leading x,y-products are
  respectively x^2, x*y, y^2.  These relations are linearly independent and
  lie in J_2, so they form a basis of J_2.

  Let J0 be the ideal generated by them.  Every monomial containing at least
  two factors from {x,y} reduces, using these relations, to a C[ell]-linear
  combination of 1,x,y.  Therefore P/J0 is generated over C[ell] by

    1,x,y,

  and has Hilbert series at most

    (1+2*t)/(1-t).

  Since J0 is contained in J, P/J0 surjects onto C=P/J, whose Hilbert series is
  exactly (1+2*t)/(1-t).  The Hilbert series must therefore agree in every
  degree and the surjection is an isomorphism.  Hence J=J0 and J is generated
  by its three quadrics.
Qed.

