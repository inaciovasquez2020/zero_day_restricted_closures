Theorem exact_fourth_layer_quotient:
  There is a natural graded R-module identification

    H ~= J^4/(J^5+(Q intersect J^4)).

  Hence H is generated in ordinary degree four by the image of

    Sym^4(V).

Proof:
  Since T=J/Q,

    J^3*T=(J^4+Q)/Q,
    J^4*T=(J^5+Q)/Q.

  Taking the quotient gives the displayed identification.
Qed.

Theorem the_longitudinal_maximal_ideal_annihilates_the_fourth_layer:
  In both first-layer cases r=4 and r=3,

    n*H=0.

Proof:
  FOUR-RELATION CASE r=4.

  The first J-adic initial forms span

    W=U tensor V.

  Let u be in U and let s4 be in Sym^4(V).  Write s4=v*t with

    v in V,
    t in Sym^3(V).

  Since u*v lies in W, choose a constant combination q of the four quadratic
  generators whose first J-adic initial form is u*v.  Write

    q=u*v+h,

  with h in Sym^2(V).  Then

    q*t = u*s4 + h*t belongs to Q,

  while h*t belongs to J^5.  Therefore u*s4 is zero in H.

  THREE-RELATION CASE r=3.

  The second-layer classification proves

    V*W = U tensor Sym^2(V).

  Multiply this equality by Sym^2(V).  One obtains

    Sym^3(V)*W = U tensor Sym^4(V).

  Thus every element of U tensor Sym^4(V) is a sum of first initial forms
  multiplied by cubic pure-transverse forms.  Replacing each first initial form
  by its lifted quadratic generator changes the sum only by J^5, because the
  J^2 correction is then multiplied by J^3.  Hence every longitudinal multiple
  vanishes in H.
Qed.

