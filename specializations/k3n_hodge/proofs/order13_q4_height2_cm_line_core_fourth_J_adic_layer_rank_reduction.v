Theorem fourth_layer_is_generated_by_transverse_multiplication_from_G:
  Multiplication by J induces a surjection

    mu : V tensor_C G_3 -> H_4.

  Consequently

    h <= 2*s.

  Therefore the residual cases satisfy exactly the numerical bounds

    s=1  ==>  h in {0,1,2},
    s=2  ==>  h in {0,1,2,3,4}.

Proof:
  By definition

    J^3*T = J*(J^2*T).

  Passing modulo J^4*T, multiplication by J depends only on the class modulo
  J^3*T, so it factors through G.  In degree four, J contributes only its
  two-dimensional degree-one space V and G contributes only G_3.  Hence the
  displayed map is surjective.

  Since dim V=2 and dim G_3=s,

    h=dim H_4 <= 2*s.
Qed.

Theorem exact_fourth_layer_dimension_from_quadratic_coefficient_syzygies:
  Let

    Syz_2(Q)

  denote the C-vector space of degree-two coefficient syzygies among the four
  minimal quadratic generators of Q, i.e. the kernel of

    S_2 tensor_C Q_2 -> Q_4.

  Put

    a := dim_C Syz_2(Q).

  Then

    h = a-10.

  Equivalently,

    a = 10+h.

Proof:
  The source S_2 tensor Q_2 has dimension

    dim S_2 * dim Q_2 = 10*4 = 40.

  Hence

    dim Q_4 = 40-a.

  Since dim S_4=35,

    dim (S/Q)_4 = 35-(40-a)=a-5.

  The saturated line quotient S/J has degree-four dimension five.  From

    0 -> T -> S/Q -> S/J -> 0

  one gets

    dim T_4=(a-5)-5=a-10.

  The earlier three J-adic quotients are concentrated respectively in degrees
  at most one, two, and three:

    T/J*T has no degree-four part,
    J*T/J^2*T has no degree-four part,
    J^2*T/J^3*T has no degree-four part.

  Therefore

    T_4=(J^3*T)_4.

  Also T begins in degree one, so

    (J^4*T)_4=0.

  Thus

    H_4 ~= T_4,

  and h=a-10.
Qed.

