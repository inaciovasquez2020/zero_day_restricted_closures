Standalone homogeneous quadratic-generator reduction for the order-13 deviation-two local-Artin search.

SCOPE:
  This file applies only to the graded/homogeneous six-generator branch, where I is a homogeneous m-primary ideal and phrases such as I_2, quadratic generator, and degree are literal homogeneous degrees.

  It does NOT prove the analogous statements for an arbitrary nonhomogeneous local Artin ideal whose minimal generators merely have m-adic order two.  In particular, the unrestricted local mu(I)=6 deviation-two frontier remains open outside this homogeneous branch.

Within this stated scope, the file excludes six genuine quadratic generators and identifies the geometry forced when the maximal surviving quadratic count is five.

This is pseudo-formal mathematical documentation.  It is not Coq and does not assert generic F_13 algebraicity.

Homogeneous setup:
  k := C,
  P := k[x1,x2,x3,x4] localized at the homogeneous maximal ideal m (or the equivalent graded calculation before localization),
  I subset P is homogeneous and m-primary,
  A := P/I is graded Artinian,
  embedding dimension(A)=4,
  mu(I)=6,
  length(A)=N>=32.

Notation:
  q := dim_k I_2,
  equivalently the number of minimal homogeneous quadratic generators because embedding dimension four implies I has no linear generators.

ExternalResult GenericQuadraticReduction:
  Let J be an m-primary homogeneous ideal in k[x1,x2,x3,x4] generated in degree two.  Since k is infinite and the polynomial ring is Cohen--Macaulay of dimension four, four sufficiently general k-linear combinations of the quadratic generators form a homogeneous system of parameters, hence a regular sequence of four quadrics.

  Therefore there exists a complete-intersection ideal

    K=(q1,q2,q3,q4) subseteq J

  with deg(qi)=2, and

    length(P/J) <= length(P/K)=2^4=16.

ExternalResult PrincipalIdealHeightBound:
  For a Noetherian ring and an ideal Q,

    ht(Q+(f)) <= ht(Q)+1.

  This is the standard one-generator form of Krull's height theorem.

Theorem homogeneous_six_quadratic_generators_cannot_reach_order13_length_frontier:
  Assume all six minimal homogeneous generators of I are quadrics.

  Then I is generated in degree two.  Since A=P/I is Artinian, I is m-primary.  Apply GenericQuadraticReduction to obtain four quadratic linear combinations q1,...,q4 in I forming a regular sequence.

  Hence

    N=length(P/I) <= length(P/(q1,q2,q3,q4))=16,

  contradicting N>=32.

  Therefore, in this homogeneous branch, not all six minimal generators can be quadratic.
Qed.

Corollary homogeneous_branch_at_most_five_quadratic_generators:
