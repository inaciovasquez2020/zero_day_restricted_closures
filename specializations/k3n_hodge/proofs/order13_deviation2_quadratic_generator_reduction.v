Qed.

Corollary homogeneous_branch_second_Hilbert_value_at_least_five:
  Since dim_k P_2=10 and dim_k I_2=q,

    h_2(A)=dim_k A_2=10-q >= 5.
Qed.

Theorem homogeneous_five_quadratic_core_has_height_three:
  Assume q=5 and let

    Q := (I_2) subset P

  be the homogeneous ideal generated by the five minimal quadrics.  Since mu(I)=6 and no further quadratic generator exists, homogeneity gives

    I = Q + (f)

  for one homogeneous generator f with deg(f)>=3.

  Then

    ht(Q)=3.

Proof:
  Because I is m-primary in the four-dimensional regular local ring P,

    ht(I)=4.

  PrincipalIdealHeightBound applied to I=Q+(f) gives

    4=ht(I) <= ht(Q)+1,

  so

    ht(Q)>=3.

  Suppose ht(Q)=4.  Then Q is m-primary.  It is generated entirely by homogeneous quadrics, so GenericQuadraticReduction gives four quadratic linear combinations inside Q forming a regular sequence K with

    length(P/Q) <= length(P/K)=16.

  Since Q subset I,

    N=length(P/I) <= length(P/Q) <=16,

  contradicting N>=32.

  Hence ht(Q) is not 4.  Combined with ht(Q)>=3, this forces

    ht(Q)=3.
Qed.

Corollary homogeneous_five_quadratic_case_is_one_dimensional_core_plus_final_cut:
  Under q=5,

    dim(P/Q)=1,

  and the sixth homogeneous generator f of degree at least three raises the height from three to four, producing

    A = (P/Q)/(f).

  Thus the maximal-quadratic-count homogeneous branch is a single higher-degree hypersurface cut of a one-dimensional five-quadric core.
Qed.

Corollary classical_H143_elementary_component_cannot_compress_to_homogeneous_mu6:
  A homogeneous Artin algebra with Hilbert function

    (1,4,3)

  has

    dim I_2 = 10-3 = 7.

  Because there are no degree-one generators, all seven independent quadrics are minimal.  Hence every such homogeneous algebra has mu(I)>=7.

  Therefore the classical homogeneous H=(1,4,3) locus cannot remain in that Hilbert stratum while dropping to mu(I)=6.
Qed.

