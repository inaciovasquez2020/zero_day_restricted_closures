Corollary homogeneous_perfect_or_CohenMacaulay_five_quadric_core_is_closed:
  Suppose Q is perfect of grade three.  Since P is regular and ht(Q)=3, this is equivalent here to B=P/Q being Cohen--Macaulay of dimension one.

  Because A=B/(f) has finite length, f is a parameter of the one-dimensional local ring B.  Every parameter of a one-dimensional Cohen--Macaulay local ring is a nonzerodivisor.

  Therefore Q:f=Q, so the general regular-cut theorem gives

    t(A)>=N>N-20.

  Hence no perfect/Cohen--Macaulay core in the homogeneous q=5 branch can be dangerous.
Qed.

Corollary surviving_homogeneous_five_quadratic_core_has_depth_zero:
  Within the homogeneous q=5 branch, any core capable of passing the tangent gate must satisfy

    dim(B)=1,
    depth(B)=0,
    H^0_m(B) != 0.

  Equivalently, Q is not perfect and B has embedded zero-dimensional m-torsion.
Qed.

Refined colon-defect form for any single-cut decomposition:
  Let

    D := (Q:f)/Q = 0:_(P/Q) f.

  The P-linear maps I->A that kill Q identify with

    Hom_{P/Q}((f),A)
      ~= Hom_{P/Q}((P/Q)/D,A)
      ~= Ann_A(D).

  Thus

    dim_k Hom_P(I,A) >= dim_k Ann_A(D).

  In particular, for a dangerous single-cut candidate with D nonzero, the defect must be large/effective enough that

    dim_k Ann_A(D) <= N-20

  is at least possible.  No universal bound of this form is claimed here.

Comparison with grade-three perfect-ideal structure theory:
  There is extensive structure theory for special classes of grade-three perfect ideals with five generators (for example Brown 1987; Kang--Cho--Ko 2009; Celikbas--Laxmi--Kraskiewicz--Weyman 2020).  Those results are not used to assert that every height-three five-quadric ideal is perfect.

  Inside the homogeneous q=5 branch:

    * if Q is perfect/CM, the tangent route closes immediately;
    * the only q=5 homogeneous survivor is the non-perfect depth-zero case.

