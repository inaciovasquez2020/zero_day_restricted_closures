    dim P_5 - 2*dim P_2
      = 6-2*3
      = 0,

  because the first relation between two coprime cubics occurs in degree six.
  Hence every quintic belongs to P_2*K3.

  Therefore

    P_5=P_2*K3 subset Q_5 intersect P_5 subset P_5,

  proving equality.  The exact fifth-layer model gives L_5=0, and since L is
  generated in degree five, L=0.
Qed.

