Theorem r3_s2_saturation_forces_H0_and_C4_coprime:
  In the r=3,s=2 case,

    gcd(H0,C4)=1.

Proof:
  Suppose H0 and C4 had a nonconstant common divisor.  Over C this divisor has
  a projective root

    [a:b] in P^1

  with

    H0(a,b)=0,
    C4(a,b)=0.

  Evaluate q1,q2,q3 at l1=a,l2=b.  Solving q1=q2=q3=0 for z,w gives

    a*z       = -h1(a,b),
    b*z+a*w   = -h2(a,b),
        b*w   = -h3(a,b).

  For every nonzero pair (a,b), the coefficient matrix

    [ a  0 ]
    [ b  a ]
    [ 0  b ]

  has rank two.  Its unique compatibility condition is

    b^2*h1(a,b)-a*b*h2(a,b)+a^2*h3(a,b)=0,

  exactly C4(a,b)=0.

  Hence there exist z0,w0 satisfying q1=q2=q3=0.  Together with
  q4=H0=0, this produces a projective common zero

    [a:b:z0:w0]

  of Q with (a,b) nonzero.

  This lies off the saturated line V(J)={l1=l2=0}, contradicting

    Qsat=J,

  equivalently Proj(S/Q)=Proj(S/J).

  Therefore H0 and C4 are coprime.
Qed.

Theorem r3_s2_h1_fifth_layer_vanishes:
  Assume

    r=3,
    s=2,
    h=1.

  Then

    Q_5 intersect P_5=P_5,

  and therefore

    L=0.

Proof:
  The preceding s=2 cubic-profile file proves that h=1 forces

    Q_4 intersect P_4
      = H0*P_2 + C*C4,

  a four-dimensional subspace of P_4.

  Multiply by P_1.  Since Q is an ideal,

    H0*P_3 + C4*P_1
      subset Q_5 intersect P_5.

  The first summand has dimension four and the second has dimension two.
  Their intersection is zero.

  Indeed, an equality

    H0*A3=C4*L1

  with A3 in P_3 and L1 in P_1, together with gcd(H0,C4)=1, forces H0 to divide
  L1.  This is impossible by degree unless L1=0, and then A3=0.

  Hence

    dim_C(H0*P_3+C4*P_1)=4+2=6.

  Since dim_C P_5=6,

    H0*P_3+C4*P_1=P_5.

  Thus

    P_5 subset Q_5 intersect P_5 subset P_5,

  proving equality.  The exact fifth-layer model gives L=0.
Qed.

