Theorem exact_fifth_layer_degree_five_model:
  There is a natural graded identification

    L_5 ~= P_5/(Q_5 intersect P_5).

  Moreover L is generated in ordinary degree five.

Proof:
  Since T=J/Q,

    J^4*T=(J^5+Q)/Q,
    J^5*T=(J^6+Q)/Q.

  Hence

    L ~= J^5/(J^6+(Q intersect J^5)).

  The degree-five pure-transverse part of J^5/J^6 is P_5.  Since the quotient
  is generated by that degree-five part, the displayed model follows.
Qed.

