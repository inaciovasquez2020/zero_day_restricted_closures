    gcd(Pz,Pw)=1,

  where Pz,Pw are independent cubics.

  It also proves that in the residual h=1 case

    Q_4 intersect P_4=P_1*K3.

  Since Q is an ideal,

    P_1*(Q_4 intersect P_4)
      = P_2*K3
      subset Q_5 intersect P_5.

  We claim

    P_2*K3=P_5.

  Indeed, the ideal (Pz,Pw) is a complete intersection of two coprime cubics in
  the two-variable polynomial ring P.  Its quotient has Hilbert series

    (1-t^3)^2/(1-t)^2.

