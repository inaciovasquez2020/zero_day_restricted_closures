Theorem linear_colon_saturation_defect_has_no_positive_degree_part:
  One has

    (Gsat/G)_n=0

  for every n>=1.

Proof:
  Let x in Gsat be homogeneous of degree n>=1.  Choose m>=0 such that

    ell^m*x*b belongs to (a).

  Write

    ell^m*x*b=a*c

  with c homogeneous of degree n+m.  Since multiplication by ell is an
  isomorphism from degree one onward, multiplication by ell^m gives an
  isomorphism

    Cbar_n -> Cbar_(n+m).

  Hence c=ell^m*c0 for a unique c0 in Cbar_n.  Therefore

    ell^m*(x*b-a*c0)=0.

  Regularity of ell permits cancellation, giving

    x*b=a*c0.

  Thus x belongs to G.
Qed.

Theorem zerodivisor_linear_colon_is_already_saturated:
  One has

    G=Gsat.

Proof:
  Since a is a zerodivisor in the one-dimensional Cohen--Macaulay ring Cbar,
  there is a minimal prime P containing a.  Because K_0=(a,b) is m-primary,
  b is not in P.  Localizing at P gives

    G_P=(a:b)_P=(a)_P,

  a proper ideal.  Since ell is a nonzerodivisor, ell is not in P and becomes
  a unit in Cbar_P, so saturation does not change this localization:

    (Gsat)_P=G_P.

  Hence Gsat is proper.  A proper homogeneous ideal has zero degree-zero part,
  so (Gsat/G)_0=0.  The preceding theorem gives zero in every positive degree.
  Therefore Gsat/G=0.
Qed.

