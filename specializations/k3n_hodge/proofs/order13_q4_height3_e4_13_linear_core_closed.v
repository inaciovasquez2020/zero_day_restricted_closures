Theorem regularized_annihilators_and_exact_extension:
  With

    D0:=0:_B h,
    E0:=0:_B k0,

  one has

    D0=E0=T.

  There is an exact sequence

    0 -> T -> A -> A0 -> 0,

  where A0:=Cbar/Lbar, and

    Ann_A(T)=m_A.

Proof:
  The final cuts annihilate T.  Conversely, if h*x=0 in B, then

    hbar*xbar=0

  in Cbar.  Regularity of hbar gives xbar=0, hence x belongs to T.  Thus
  0:_B h=T; the proof for k0 is identical.

  The exact sequence follows from L intersect T=0.  Since Ann_B(T)=m_B and
  L*T=0, m_A annihilates T.  Conversely, if z+L annihilates T in A, then
  z*T subseteq L.  But z*T is contained in T and L intersect T=0, so z*T=0
  already in B.  Hence z belongs to m_B.  Therefore Ann_A(T)=m_A.
Qed.

