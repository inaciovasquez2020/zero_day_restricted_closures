Lemma exact_delayed_layer_annihilator:
  V_i is cyclic, generated by the class of ell^(i-1)*b, and

    Ann_Cbar(V_i)=(G:ell^(i-1),ell).

Proof:
  The generator statement follows from

    K_(i-1)=(a,ell^(i-1)*b),
    K_i=(a,ell^i*b).

  If c kills the displayed generator modulo K_i, then

    c*ell^(i-1)*b
      =p*a+q*ell^i*b.

  Hence

    (c-q*ell)*ell^(i-1)*b belongs to (a),

  giving c in (G:ell^(i-1),ell).  The reverse inclusion is immediate.
Qed.

Theorem every_delayed_layer_from_two_on_has_nonpositive_defect:
  For every i>=2,

    Delta_i<=0.

Proof:
  For i>=2, the one-step saturation theorem gives

    G:ell^(i-1)=Gsat.

  Thus every V_i is, up to grading shift, the same cyclic module

    Cbar/(Gsat,ell).

  Put

    N_G:=0:_X Gsat.

  For y in N_G define a map K_i->X by

    a |-> 0,
    ell^i*b |-> y.

  It is well defined because every relation coefficient on ell^i*b lies in
  G:ell^i=Gsat.  In the cyclic presentation of V_i, its connecting class is
  represented by

    ell |-> y,
    Gsat |-> 0.

  This class vanishes exactly when y belongs to ell*N_G.  Therefore the
  explicit connecting classes have rank

    dim_C(N_G/ell*N_G)
      =dim_C(0:_N_G ell)
      =dim_C Hom_Cbar(Cbar/(Gsat,ell),X)
      =dim_C Hom_Cbar(V_i,X).

  Applying Hom(-,X) to

    0 -> K_i -> K_(i-1) -> V_i -> 0

  then gives Delta_i<=0.
Qed.

