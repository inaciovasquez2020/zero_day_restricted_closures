Theorem parameter_multiplication_is_iso_from_degree_two:
  For every n>=2,

    ell:Cbar_n -> Cbar_(n+1)

  is a vector-space isomorphism.

Proof:
  From

    Hilb_Cbar(t)=(1+2*t+2*t^2)/(1-t)

  one has

    dim_C Cbar_0=1,
    dim_C Cbar_1=3,
    dim_C Cbar_n=5 for every n>=2.

  Multiplication by ell is injective in every degree because ell is a
  nonzerodivisor.  For n>=2 the source and target both have dimension five,
  hence the injection is an isomorphism.
Qed.

