SECTION ZERODIVISOR_QUADRATIC_LOWER.

Assume a is a zerodivisor on Cbar.

Put

  G:=(a:b),
  Gsat:=G:ell^infinity.

Theorem the_saturated_quadratic_colon_is_proper:
  Gsat is a proper homogeneous ideal of Cbar.

Proof:
  Since Cbar is one-dimensional Cohen--Macaulay, every associated prime is
  minimal.  Choose a minimal prime P containing the zerodivisor a.

  Because K_0=(a,b) is m-primary, b does not belong to P.  Thus b is a unit in
  Cbar_P and

    G_P=(a:b)_P=(a)_P,

  which is proper.

  The parameter ell is a nonzerodivisor, hence ell is not in P and becomes a
  unit after localization.  Saturating by ell does not change the localization,
  so

    (Gsat)_P=G_P.

  Therefore Gsat is proper.
Qed.

Theorem quadratic_colon_saturates_after_one_parameter_step:
  One has

    G:ell=Gsat,

  and hence

    G:ell^j=Gsat

  for every j>=1.

Proof:
  First show that G and Gsat agree in every degree n>=2.  If x in Gsat_n, choose
  m with

    ell^m*x*b in (a).

  Write

    ell^m*x*b=a*c

  with c in Cbar_(n+m).  Since multiplication by ell is an isomorphism from
  degree two onward, write c=ell^m*c0 with c0 in Cbar_n.  Cancellation of the
  nonzerodivisor ell gives

    x*b=a*c0,

  hence x in G.

  The preceding properness theorem removes degree zero, because a proper
  homogeneous ideal has zero degree-zero part.  Thus Gsat/G can occur only in
  degree one.  Multiplying a degree-one class by ell moves it to degree two,
  where Gsat and G agree.  Therefore ell*Gsat subseteq G, proving

    G:ell=Gsat.
Qed.

For i>=1 put

  V_i:=K_(i-1)/K_i

