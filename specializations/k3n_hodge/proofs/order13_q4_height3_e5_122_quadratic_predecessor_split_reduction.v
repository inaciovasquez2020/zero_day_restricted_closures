SECTION REGULAR_QUADRATIC_LOWER.

Assume a is a nonzerodivisor on Cbar.

Choose any homogeneous quadratic lift of a to B, again denoted a.

Theorem regular_quadratic_kernel_is_contained_in_the_three_dimensional_torsion:
  One has

    0:_B a = 0:_T a,

  and therefore

    length_C(0:_B a)<=3.

Proof:
  If a*x=0 in B, then after projection to Cbar one has

    a*xbar=0.

  Regularity of a on Cbar gives xbar=0, hence x belongs to T.  The reverse
  equality is just the definition of the kernel on T.

  The preceding cyclic-torsion reduction gives length(T)=3.
Qed.

Theorem regular_quadratic_section_of_B_has_length_at_most_thirteen:
  One has

    length_C(B/aB)
      =10+length_C(0:_T a)
      <=13.

Proof:
  Multiplication by the quadratic a gives the exact sequence

    0 -> (0:_B a)(-2)
      -> B(-2)
      --a--> B
      -> B/aB
      -> 0.

  The finite kernel does not change the one-dimensional Hilbert polynomial of
  B.  Since e(B)=5, evaluation of the Hilbert-series identity at t=1 gives

    length(B/aB)=2*e(B)+length(0:_B a).

  Use the preceding kernel theorem.
Qed.

