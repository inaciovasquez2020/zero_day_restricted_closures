Theorem ell_annihilator_of_X_has_dimension_at_most_six:
  For the refined general choice of ell,

    dim_C(0:_X ell)<=6.

Proof:
  Since ell is regular on Cbar, every element killed by ell in B lies in T.
  Under

    T ~= C[z]/(z^3)(-1),

  the image of ell in B/J is a nonzero scalar multiple of z.  Hence

    0:_B ell=T_3,

  a one-dimensional space.

  The top line T_3 annihilates T: products with T have degree at least four,
  while T_n=0 for n>=4.  Thus

    T_3 subseteq J=Ann_B(T).

  Therefore the kernel of multiplication by ell on the one-dimensional
  B-module J is exactly T_3 and has length one.  Since B/J has finite length,
  J has the same multiplicity as B, namely five.  The multiplication exact
  sequence on J gives

    length_C(J/ell*J)=5+1=6.

  Finally X=J/L, so

    X/ell*X=J/(L+ell*J)

  is a quotient of J/ell*J.  Hence length(X/ell*X)<=6.  On the finite vector
  space X, kernel and cokernel of multiplication by ell have equal dimension,
  proving the result.
Qed.

