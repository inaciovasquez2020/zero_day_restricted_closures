    K_k ~= Lbar,

  and both K_k and K_0=(a,b) are m-primary in Cbar.

Proof:
  The preceding parameter-isomorphism theorem gives unique degree-two
  predecessors of fbar and gbar.

  The image Lbar is m-primary because Cbar/Lbar is a quotient of the finite
  algebra A.  Since ell avoids every minimal prime, removing the common power
  ell^s does not change the radical, so K_k is m-primary.  Since

    K_k subseteq K_0,

  the larger ideal K_0 is m-primary as well.
Qed.

Theorem core_Hom_space_injects_into_the_actual_two_cut_conormal_space:
  There is a natural injection

    Hom_Cbar(K_k,X) -> Hom_B(L,A).

Proof:
  Projection B->Cbar induces a surjection

    L -> Lbar

  whose kernel is L intersect T.  No assertion that this intersection is zero
  is needed.

  Since X=Ann_A(T), the B-action on X factors through Cbar.  Therefore every
  Cbar-linear map

    Lbar -> X

  composes with L->Lbar and X->A to give a B-linear map L->A.  The construction
  is injective because L->Lbar is surjective.

  Finally multiplication by ell^s identifies K_k with Lbar.
Qed.

