5. WHY THE DISPLAYED QUADRICS ARE THE EXACT DISCRIMINANTS
--------------------------------------------------------------------------

Theorem H00_maximal_minor_discriminant_test:
  For each of the six non-P2 contraction matrices, all 4 by 4 minors vanish
  exactly on the displayed quadric Delta=0 in P(V^*).

Proof:
  Direct determinant expansion gives the following common factors:

    P1P1-R2:  b*e-c*d,
    P1P1-R1:  a*e-b*d,
    P1P1-R0:  a*d-b^2,
    J2-R2:    b*e-c*d,
    J2-R1:    a*d-b*c,
    J2-R0:    a*c-b^2.

  Every maximal minor is the corresponding Delta times a quadratic monomial or
  quadratic expression in a,b,c,d,e.

  Conversely, if Delta!=0, the coordinates entering Delta cannot all vanish in
  the combinations multiplying the maximal minors.  Inspecting the displayed
  matrices yields at least one nonzero 4 by 4 minor.  Hence rank=4.

  If Delta=0, every maximal minor vanishes, so rank<=3.
Qed.

Thus the invalid four-planes form one explicit dual quadric for each of the six
realizable saturated types.

