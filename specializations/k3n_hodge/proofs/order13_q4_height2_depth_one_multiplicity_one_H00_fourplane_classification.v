3. SYZYGY CONTRACTION GIVES THE EXACT DEFECT ANNIHILATOR
--------------------------------------------------------------------------

Write

    lambda(fi)=lambda_i.

Let

    s=(a1,...,a5)

be a first syzygy, so

    a1*f1+...+a5*f5=0.

Define its lambda-contraction by

    c_lambda(s):=lambda_1*a1+...+lambda_5*a5 in S.

Let J_lambda be the ideal generated by the contractions of the six minimal
linear first syzygies.

Theorem exact_H00_hyperplane_defect_presentation:
  One has

    T ~= S/J_lambda(-2).

Equivalently,

    (Q:r)=J_lambda.

Proof:
  Let F0=S(-2)^5 with basis ei mapping to fi.  The covector lambda extends
  S-linearly to

    lambda_S:F0 -> S(-2).

  Its kernel is precisely the free S-submodule generated by the quadratic
  hyperplane W=ker(lambda).

  Modding the presentation

    S(-3)^6 -> F0 -> Qsat -> 0

  by that hyperplane submodule leaves one generator in degree two.  The only
  relations on that surviving generator are the images under lambda_S of the
  full first-syzygy module.  Since the first-syzygy module is generated by the
  six displayed linear syzygies, its image is exactly J_lambda.

  Hence

    Qsat/Q ~= S/J_lambda(-2).
Qed.

Corollary exact_H00_saturation_rank_criterion:
