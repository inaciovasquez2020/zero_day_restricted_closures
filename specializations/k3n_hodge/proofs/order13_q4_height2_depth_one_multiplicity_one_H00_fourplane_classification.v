1. HYPERPLANES AND THE CYCLIC SATURATION DEFECT
--------------------------------------------------------------------------

Let

    V := (Qsat)_2,
    dim_C V = 5.

Every four-dimensional quadratic generator space is a hyperplane

    W=Q_2=ker(lambda)

for a nonzero covector

    lambda in V^*.

Choose any r in V with lambda(r)=1.  Since Qsat is generated by V and Q is
generated by W,

    Qsat = Q + (r).

Hence T=Qsat/Q is cyclic, generated in degree two by the class tau of r.

Theorem H00_fourplane_defect_is_a_cyclic_colon_module:
  One has

    T ~= S/(Q:r)(-2).

Proof:
  The map

    S(-2) -> T,
    1 |-> tau

  is surjective because Qsat=Q+(r).  Its kernel consists exactly of the
  polynomials a with a*r in Q, namely (Q:r).
Qed.

Theorem H00_fourplane_saturates_back_iff_the_defect_is_finite_length:
  One has

    Q^sat=Qsat

  if and only if T has finite length.

Proof:
  Since Qsat is saturated and contains Q, one always has

    Q^sat subseteq Qsat.

  If T=Qsat/Q has finite length, every homogeneous element of Qsat is killed
  modulo Q by a sufficiently high power of m, so Qsat subseteq Q^sat.
  Hence equality holds.

  Conversely, if Q^sat=Qsat, then Qsat/Q is the homogeneous m-torsion removed by
  saturation, hence is finite length.
Qed.

Thus the four-plane problem is exactly a finite-length problem for one cyclic
module.

