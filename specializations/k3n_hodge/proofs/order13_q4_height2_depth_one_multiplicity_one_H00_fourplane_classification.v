  six syzygies; direct substitution gives a complex

    0 -> S(-4)^2 -> S(-3)^6 -> S(-2)^5 -> Qsat -> 0.

  The two columns of the left map are independent over Frac(S), so the left map
  is injective.  The alternating Hilbert series of this complex is

    (5*t^2-6*t^3+2*t^4)/(1-t)^4,

  exactly the already determined Hilbert series of Qsat.  Therefore no further
  homology remains and the complex is exact.
Qed.

