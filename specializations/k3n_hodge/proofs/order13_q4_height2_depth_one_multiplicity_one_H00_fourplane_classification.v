2. THE H00 SATURATED IDEALS HAVE A LINEAR FIRST-SYZYGY PRESENTATION
--------------------------------------------------------------------------

For every one of the seven H00 saturated normal forms, order its five displayed
quadratic generators as

    f1,f2,f3,f4,f5.

