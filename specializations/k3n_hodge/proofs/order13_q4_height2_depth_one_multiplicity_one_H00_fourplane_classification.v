    Hilb_Qsat(t)
      = (5*t^2-6*t^3+2*t^4)/(1-t)^4.

Theorem H00_saturated_ideal_has_pure_linear_resolution:
  For each of the seven normal forms there is an exact minimal graded resolution

    0 -> S(-4)^2
      -> S(-3)^6
      -> S(-2)^5
      -> Qsat
      -> 0.

  In particular the full first-syzygy module of the five quadrics is generated
  by six linear syzygies.

Proof:
  For each normal form the six linear syzygies displayed in Section 4 below are
  direct polynomial identities among f1,...,f5.

  They are C-linearly independent in degree three.  Since

    dim_C S_3 = 20,
    dim_C (S/Qsat)_3 = 6,
    dim_C (Qsat)_3 = 14,

  the kernel of

    S_1 tensor_C V -> (Qsat)_3

  has dimension 20-14=6.  Hence the displayed six syzygies are all minimal
  degree-three first syzygies.

