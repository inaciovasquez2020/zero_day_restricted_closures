    T ~= Z(-1),
    Hilb_Z(t)=1+3*t+t^2,
    length_C(Z)=5.

  Moreover in B=R/(v*c),

    Ann_B(T)=(K+cR)/(v*cR),
    B/Ann_B(T) ~= Z.

Proof:
  The kernel of multiplication by v is 0:_R v=K, so the first isomorphism is
  exact.  Quotienting U=vR by qR=v*cR gives

    T=U/qR ~= (C0/c*C0)(-1).

