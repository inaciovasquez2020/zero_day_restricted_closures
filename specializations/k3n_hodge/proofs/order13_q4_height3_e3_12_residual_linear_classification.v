Theorem exact_Hilbert_balance_for_the_linear_residual_defect:
  Multiplication by v gives

    Hilb_(U/vR)(t)=t*Hilb_(H_v)(t).

Proof:
  Multiplication by v identifies

    R/(0:_R v)(-1) ~= vR.

  Since

    0:_R v / K = H_v,

  one has

    Hilb_(vR)
      =t*(Hilb_R-Hilb_(0:_R v))
      =t*(Hilb_R-Hilb_K-Hilb_Hv).

  Direct substitution of the Hilbert series above gives

    t*(Hilb_R-Hilb_K)=Hilb_U.

  Therefore

    Hilb_(vR)=Hilb_U-t*Hilb_Hv.

  Because vR subseteq U, subtraction yields

    Hilb_(U/vR)=t*Hilb_Hv.
Qed.

