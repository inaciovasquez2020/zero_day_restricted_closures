Theorem the_linear_annihilator_defect_has_dimension_at_most_one:
  One has

    dim_C (H_v)_1 <= 1.

Proof:
  Since K_1=0,

    (H_v)_1=(0:_R v)_1.

  Suppose two independent linear classes w1,w2 in R_1 annihilate v.  Choose
  linear lifts of v,w1,w2 to S.  Then

    v*w1,
    v*w2

  are two linearly independent quadrics in the degree-two span of the defining
  regular sequence q1,q2,q3.  Independence follows because S is a domain and
  w1,w2 are independent.

  Extend these two products to a basis

    v*w1,
    v*w2,
    p3

  of that three-dimensional quadratic span.  Then

    (q1,q2,q3)=(v*w1,v*w2,p3).

  But the right-hand ideal is contained in

    (v,p3),

  an ideal generated by two elements and therefore of height at most two.
  This contradicts ht(q1,q2,q3)=3.

  Hence at most one independent linear annihilator direction exists.
Qed.

