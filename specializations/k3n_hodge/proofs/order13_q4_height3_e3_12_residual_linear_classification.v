Theorem exact_residual_Hilbert_series_for_e3_12:
  One has

    Hilb_K(t)=(2*t^2+t^3)/(1-t),
    Hilb_U(t)=(t+3*t^2+t^3)/(1-t).

  Consequently

    K_0=K_1=0,
    dim_C K_2=2,
    dim_C K_n=3 for n>=3,

    dim_C U_1=1,
    dim_C U_2=4,
    dim_C U_n=5 for n>=3.

Proof:
  The saturated core has

    Hilb_Cbar(t)=(1+2*t)/(1-t).

  Graded canonical-module reciprocity gives

    Hilb_omega_Cbar(t)
      =t*(1+2*t^(-1))/(1-t)
      =(t+2)/(1-t).

  The exact linkage theorem K(2)~=omega_Cbar therefore gives

    Hilb_K(t)=t^2*Hilb_omega_Cbar(t)
             =(2*t^2+t^3)/(1-t).

  Since

    Hilb_R(t)=(1+3*t+3*t^2+t^3)/(1-t)

  and Cbar=R/U,

    Hilb_U=Hilb_R-Hilb_Cbar
          =(t+3*t^2+t^3)/(1-t).

  Reading coefficients gives the displayed dimensions.
Qed.

