Theorem the_unique_linear_annihilator_forms_an_exact_zero_divisor_pair:
  One has

    0:_R v=wR,
    0:_R w=vR.

Proof:
  The quadratic product v*w vanishes in R, hence its nonzero lift belongs to
  the degree-two span of q1,q2,q3.  Rebase that regular sequence as

    v*w,
    p2,
    p3.

  Put D:=S/(p2,p3).  Since p2,p3,v*w is a regular sequence, v*w is a
  nonzerodivisor on D.  Therefore both v and w are nonzerodivisors on D.

  If f*v belongs to (v*w,p2,p3), then modulo (p2,p3)

    f*v=a*v*w

  for some a.  Cancelling the nonzerodivisor v on D gives

    f=a*w mod (p2,p3).

  Thus ((v*w,p2,p3):v)=(w,p2,p3).  The symmetric calculation gives the other
  colon.  Passing to R proves the claim.
Qed.

Corollary the_nonprincipal_residual_has_exact_Hilbert_defect:
  One has

    Hilb_(H_v)(t)=t/(1-t),
    Hilb_(U/vR)(t)=t^2/(1-t).

  In particular U is strictly larger than vR in dimension one.

Proof:
  Since 0:_R w=vR, multiplication by w identifies

    R/vR(-1) ~= wR=0:_R v.

  The quotient R/vR is the complete intersection

    S/(v,p2,p3)

  of degrees (1,2,2), so

    Hilb_(R/vR)=(1+2*t+t^2)/(1-t).

  Hence

    Hilb_(0:_R v)=(t+2*t^2+t^3)/(1-t).

  Subtract

    Hilb_K=(2*t^2+t^3)/(1-t)

  to obtain Hilb_Hv=t/(1-t).  The Hilbert-balance theorem then gives the
  formula for U/vR.
Qed.

Theorem the_fourth_quadric_does_not_factor_through_v_in_the_exact_pair_case:
  One has

    q notin vR.

Proof:
  Suppose q belonged to vR.  Since qR subseteq vR subseteq U and U is the
  saturation of qR, localization at every nonirrelevant homogeneous prime P
  would give

    vR_P subseteq U_P=qR_P subseteq vR_P.

  Thus U/vR would be supported only at the irrelevant maximal ideal and would
  have finite length.

  But the preceding corollary gives

    Hilb_(U/vR)=t^2/(1-t),

  which has infinite length.  Contradiction.
Qed.

