Theorem the_residual_defect_is_finite_length:
  Both

    U/vR

  and

    H_v

  have finite length.

Proof:
  Since q=v*c, one has qR subseteq vR subseteq U.

  Let P be any nonirrelevant homogeneous prime.  Saturation does not change the
  localization of qR, so

    U_P=qR_P.

  Localizing the displayed inclusions gives

    vR_P subseteq U_P=qR_P subseteq vR_P,

  hence equality.  Thus U/vR is supported only at the irrelevant maximal ideal
  and has finite length.

  The Hilbert-balance identity

    Hilb_(U/vR)=t*Hilb_Hv

  then makes H_v finite length as well.
Qed.

Lemma annihilator_ideals_are_saturated_in_the_one_dimensional_CI:
  Both ideals

    K=0:_R U

  and

    0:_R v

  are saturated with respect to the irrelevant maximal ideal.

Proof:
  Choose a linear nonzerodivisor ell_R on the one-dimensional Cohen--Macaulay
  ring R.

  If x belongs to the saturation of K, then for some n

    ell_R^n*x belongs to K.

  Hence for every u in U,

    ell_R^n*x*u=0.

  Regularity of ell_R on R gives x*u=0, so x belongs to K.

  The same argument with U replaced by the single element v proves that
  0:_R v is saturated.
Qed.

Theorem no_linear_defect_forces_the_principal_residual:
  One has

    H_v=0,
    0:_R v=K,
    U=vR.

Proof:
  The preceding theorem makes H_v=(0:_R v)/K finite length.  Hence every class
  of 0:_R v modulo K is killed by a power of the irrelevant maximal ideal.
  Therefore every element of 0:_R v lies in the saturation of K.  Since K is
  saturated, 0:_R v subseteq K.  The reverse inclusion was already known, so

    0:_R v=K.

  Thus H_v=0.  The Hilbert-balance identity then gives U/vR=0.
Qed.

