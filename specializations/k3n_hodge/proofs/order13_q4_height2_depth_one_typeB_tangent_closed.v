1. EXACT COLON AND ONE-DIMENSIONAL SUBMODULE
--------------------------------------------------------------------------

Theorem typeB_exact_colon_by_x:
  One has

    (Q:x)=Jlin.

Proof:
  Certainly Jlin subset (Q:x), because x*Jlin subset Q.

  Conversely suppose r*x belongs to Q.  Write

    r*x = x*j + q*b

  with j in Jlin.  Then

    x*(r-j)=q*b.

  Since q is not in the principal prime (x), x does not divide q.  The
  polynomial ring S is a UFD, so gcd(x,q)=1 and x divides b.  Write b=x*c.
  Cancelling x gives

    r-j=q*c.

  Since q belongs to Jlin, the right side belongs to Jlin, so r belongs to
  Jlin.  Hence (Q:x)=Jlin.
Qed.

Put

    K:=S/Jlin.

Because Jlin is generated by three independent linear forms in a polynomial
ring in four variables,

    K ~= C[t]

as a standard graded C-algebra.

Corollary multiplication_by_x_gives_an_exact_TypeB_extension:
  There is a graded exact sequence

    0 -> K(-1)
      --times x-->
      B
      -> R
      -> 0,

  where

    R:=S/(x,q).

Proof:
  The standard multiplication-by-x exact sequence for S/Q is

    0 -> S/(Q:x)(-1)
      --times x-->
      S/Q
      -> S/(Q,x)
      -> 0.

  The colon theorem identifies the left term with K(-1).  Also

    Q+(x)=(x,q),

  because the three generators x*a_i already lie in (x).  Thus the right term
  is R.
Qed.

Theorem the_TypeB_curve_quotient_is_a_multiplicity_two_CM_conic_ring:
  The ring

    R=S/(x,q)

  is a two-dimensional Cohen--Macaulay complete intersection of multiplicity
  two.

Proof:
  The linear form x is a nonzerodivisor in S.  Modulo x, the quadric q remains
  nonzero because q is not in (x).  Since S/(x) is a polynomial domain, q mod x
  is a nonzerodivisor.  Hence x,q form a regular sequence.

  Therefore dim R=2 and R is Cohen--Macaulay.  Its multiplicity is

    1*2=2.
Qed.

