Theorem square_of_the_Koszul_annihilator_is_a_two_cut_Hom_carrier:
  There is a natural C-linear injection

    E direct_sum E -> Hom_B(L,A).

Proof:
  The presentation

    B^2 -> L,
    (u,v) |-> u*f+v*g

  has kernel Syz.  Hence Hom_B(L,A) is the set of pairs (alpha,beta) in A^2
  satisfying

    u*alpha+v*beta=0

  for every (u,v) in Syz.

  Because f=g=0 in A, every coordinate functional on B^2 with values in A kills
  the Koszul submodule B*(-g,f), so its restriction to Syz factors through D1.

  The coordinate reductions

    rho_1,rho_2:D1->A

  are A-linear.  If alpha,beta belong to E=Ann_A(D1), then

    alpha*rho_i(xi)=0,
    beta*rho_i(xi)=0

  for every xi in D1 and i=1,2.  Thus each pair in E^2 kills all syzygies and
  defines a map L->A.  Distinct pairs remain distinct in A^2, proving the
  injection.
Qed.

