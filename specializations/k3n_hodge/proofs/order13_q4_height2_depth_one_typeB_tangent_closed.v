3. EXACT REDUCTION OF TYPE-B KOSZUL H1 TO ONE VARIABLE
--------------------------------------------------------------------------

Define

    D1:=H_1(f,g;B).

Theorem TypeB_Koszul_H1_is_exactly_the_one_variable_Koszul_H1:
  There is a natural graded B-module isomorphism

    D1 ~= H_1(f,g;K)(-1).

Proof:
  Apply the two-element Koszul complex K(f,g;-) to

    0 -> K(-1) -> B -> R -> 0.

  This gives a short exact sequence of complexes.  The relevant part of the
  long exact homology sequence is

    H_2(f,g;R)
      -> H_1(f,g;K)(-1)
      -> H_1(f,g;B)
      -> H_1(f,g;R).

  Both outside terms vanish by regularity on R.  Therefore the middle map is an
  isomorphism.
Qed.

Corollary at_least_one_final_generator_is_nonzero_on_K:
  At least one of the restrictions

    f_K,g_K in K=C[t]

  is nonzero.

Proof:
  The module D1 is a finitely generated B-module annihilated by f and g, hence
  it is a finitely generated A-module.  Since A has finite C-length, D1 has
  finite C-dimension.

  If f_K=g_K=0, then the Koszul differential on K(f,g;K) is zero and

    H_1(f,g;K) ~= K direct_sum K

  up to grading shifts, which has infinite C-dimension.  This contradicts the
  preceding isomorphism with D1.
Qed.

Because K=C[t] and f,g are homogeneous, each nonzero restriction is a scalar
multiple of the corresponding pure power:

    f_K !=0  =>  f_K=lambda*t^d,
    g_K !=0  =>  g_K=mu*t^e.

Define

    r:=min { degree of a nonzero member among f_K,g_K }.

Then r is a positive integer and

    (f_K,g_K)=(t^r) subset K.

Theorem exact_one_variable_Koszul_H1_shape:
  Up to a grading shift,

    H_1(f,g;K) ~= K/(t^r).

  In particular

    dim_C D1=r.

Proof:
  If both restrictions are nonzero, write

    f_K=t^r*f',
    g_K=t^r*g'

  with gcd(f',g')=1 in the PID K.  The first syzygy module is generated by

    (-g',f'),

  while the Koszul syzygy is t^r times that generator.  Therefore first Koszul
  homology is K/(t^r), up to the grading of the generator.

  If exactly one restriction is nonzero, say g_K=0 and f_K is a scalar multiple
  of t^r, then the syzygy module is generated by the coordinate corresponding
  to the zero element and the Koszul submodule is t^r times that generator.
  The same quotient K/(t^r) results.

  The previous theorem transfers this shape to D1, with the additional (-1)
  shift from K(-1).
Qed.

