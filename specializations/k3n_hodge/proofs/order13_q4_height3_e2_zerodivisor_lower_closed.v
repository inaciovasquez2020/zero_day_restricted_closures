Theorem doubled_line_core_cubic_tail_has_nonpositive_delta:
  Put

    U0:=m_A0^3.

  Then

    delta_s(U0)<=0.

  More precisely:

  if d=3, then

    dim(U0/J_s*U0)=s-1,
    dim(0:_U0 J_s)=s-1,
    delta_s(U0)=0;

  if d>=4, then

    dim(U0/J_s*U0)=s+1,

    dim(0:_U0 J_s)
      =s+min(s,d-3),

    delta_s(U0)
      =1-min(s,d-3)
      <=0.

Proof:
  A vector-space basis of A0 is

    1,ell,...,ell^(D-1),
    v,ell*v,...,ell^(d-2)*v.

  Therefore U0=m_A0^3 has basis

    ell^3,...,ell^(D-1)

  together with

    ell^2*v,...,ell^(d-2)*v

  when the latter range is nonempty.

  Quotient by J_s=(v,ell^s).

  If d=3 there is no v-tail in U0, and the surviving pure powers are

    ell^3,...,ell^(D-1),

  modulo ell^s*U0.  Since D=s+2, exactly s-1 survive.

  If d>=4, the pure quotient contributes

    ell^3,...,ell^(s+2),

  namely s dimensions, while the single class ell^2*v is not in v*U0 and
  contributes one more.  Thus the quotient dimension is s+1.

  For the common annihilator of v and ell^s, a pure monomial ell^n is killed by
  both exactly when

    n>=d-1.

  In the d=3 case every pure basis element of U0 satisfies this and there are
  s-1 of them.

  For d>=4, the pure annihilator therefore has basis

    ell^(d-1),...,ell^(D-1),

  of dimension s.

  Every v-monomial is killed by v.  The monomial ell^j*v in U0 is additionally
  killed by ell^s exactly when

    j+s>=d-1.

  Among

    j=2,...,d-2,

  this contributes exactly min(s,d-3) dimensions.  Summing proves the formulas.
Qed.

Corollary full_cubic_tail_has_nonpositive_delta:
