Theorem homogeneous_triangular_normal_form_for_zerodivisor_lower:
  After a homogeneous triangular change preserving L=(f,g)B, the saturated
  images have one of the forms

    REDUCED_SPLIT:
      fbar=x^d,
      gbar=y^D,

    DOUBLE_LINE:
      fbar=ell^(d-1)*v,
      gbar=ell^D.

Proof:
  In the reduced split core the preceding rank-two classification gives

    fbar=x^d,
    gbar=c*x^D+b*y^D,

  with b nonzero.  Since D>=d,

    x^D=x^(D-d)*fbar.

  Replace g by

    g-c_tilde*f,

  where c_tilde is a homogeneous lift of c*x^(D-d).  This is an invertible
  triangular change of the two-generator ideal.  Rescale the new second
  generator to obtain gbar=y^D.

  In the double-line core one similarly has

    fbar=ell^(d-1)*v,
    gbar=b*ell^D+c*ell^(D-1)*v,

  with b nonzero.  The second summand equals

    c*ell^(D-d)*fbar.

  Apply the same homogeneous triangular replacement and rescale.
Qed.

Corollary final_cuts_annihilate_T_and_do_not_meet_T:
  One has

    f*T=0,
