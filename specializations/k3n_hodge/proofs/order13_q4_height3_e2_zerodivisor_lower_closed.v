Theorem doubled_line_core_colon_is_v_ell_s:
  Modulo T,

    Kbar:=(hbar:kbar)=(v,ell^s).

Proof:
  Since ell is a nonzerodivisor, cancel the common factor ell^(d-1).  It is
  enough to compute

    (v+ell^s : ell^s).

  Modulo the regular element v+ell^s one has

    v=-ell^s,
    v^2=0,

  hence

    ell^(2*s)=0.

  The annihilator of ell^s in

    C[ell]/(ell^(2*s))

  is generated by ell^s.  Pulling back gives

    (v+ell^s,ell^s)=(v,ell^s).
Qed.

Theorem doubled_line_full_colon_is_the_inverse_image_of_v_ell_s:
  Let v and ell also denote fixed homogeneous degree-one lifts to B.  Then

    K:=(h:k)=T+(v,ell^s)B.

Proof:
  The inclusion K -> Kbar after quotienting by T is automatic.

  Conversely the two core transport identities are

    v*kbar=v*hbar,

    ell^s*kbar=(ell^s-v)*hbar.

  After lifting to B, any discrepancy lies in T.  Every term in either
  discrepancy has degree at least d+1>=4, while T_n=0 for n>=4.  Thus both
  identities lift exactly.  Hence v and ell^s belong to K.

  Also T belongs to K because k*T=0.  Therefore the full inverse image

    T+(v,ell^s)B

  lies in K.  The reverse inclusion follows by reducing modulo T and using the
  core-colon theorem.
Qed.

