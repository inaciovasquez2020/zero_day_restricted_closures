  Restrict

    0 -> T -> A -> A0 -> 0

  to degrees at least three.  Since

    T_3 has dimension two,
    T_n=0 for n>=4,

  one gets

    0 -> T_3 -> m_A^3 -> m_A0^3 -> 0.

  In the doubled-line normal form

    A0=C[ell,v]/(v^2,ell^(d-1)*v,ell^D),

  the ideal m_A0^3 is generated in degree three by ell^3 and, when nonzero,
  ell^2*v.  Choose degree-three lifts of these generators in A.

  Every defining relation among those lifts has total degree at least four.
  Its image in A0 is zero, so the relation in A lies in T in degree at least
  four and is therefore zero.  Hence the chosen lifts generate a submodule
  isomorphic to m_A0^3.

  This submodule meets T_3 trivially in degree three and there is no torsion in
  higher degree.  Therefore the displayed exact sequence splits as graded
  A0-modules.

  Finally every positive-degree element sends T_3 into T_n for n>=4, which is
  zero.  Thus T_3 is a two-dimensional residue-field module.
Qed.

