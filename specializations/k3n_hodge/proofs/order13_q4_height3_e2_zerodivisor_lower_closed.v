    v*w=ell^s*v*a=qbar(v)*z,

    ell^s*w=(ell^s-v)*ell^s*a=qbar(ell^s)*z.

  In both cases w belongs to N_T, so multiplication by w also vanishes on T,
  exactly as the cyclic representative does.  By linearity every element of
  J_s*N_T lies in the kernel.
Qed.

