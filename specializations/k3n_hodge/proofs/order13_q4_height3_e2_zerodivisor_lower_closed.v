Theorem split_core_colon_is_the_maximal_ideal:
  Put

    K:=(h:k).

  Then

    K=m_B.

Proof:
  Modulo T one has

    hbar=x^d+y^D,
    kbar=a*x^d+b*y^D.

  Since x*y=0,

    x*kbar=a*x*hbar,
    y*kbar=b*y*hbar.

  Thus the core maximal ideal (x,y) lies in

    Kbar:=(hbar:kbar).

  The element 1 is not in Kbar because hbar and kbar are not scalar multiples.
  Hence

    Kbar=(x,y)=m_Cbar.

  Now lift x and y homogeneously to B.  The two displayed colon relations can
  fail after lifting only by elements of T in degrees at least

    d+1>=4.

  But T_n=0 for n>=4, so the relations lift exactly.  Thus every positive-
  degree lift lies in K.  Also T lies in K because k*T=0.  Therefore

    m_B subseteq K.

  Conversely 1 is not in K because its image is not in Kbar.  Hence K=m_B.
Qed.

