Qed.

Theorem extension_by_at_most_three_quadratic_generators_adds_at_most_three_to_delta:
  One has

    delta_s(N_T)<=delta_s(U)+dim_C W<=3.

Proof:
  Apply quotient by J_s to

    0 -> U -> N_T -> W -> 0.

  Right exactness gives

    dim_C(N_T/J_s*N_T)
      <= dim_C(U/J_s*U)+dim_C(W/J_s*W).

  Since J_s is contained in m_A0 and m_A0 kills W,

    W/J_s*W=W.

  On the annihilator side, the inclusion U->N_T gives an injection

    0:_U J_s -> 0:_(N_T) J_s,

  so

    dim_C(0:_(N_T)J_s)>=dim_C(0:_U J_s).

  Subtracting yields

    delta_s(N_T)
      <=delta_s(U)+dim_C W.

  Now use

    delta_s(U)<=0,
    dim W<=3.
Qed.

