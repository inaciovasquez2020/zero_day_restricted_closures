Theorem quadratic_colon_saturation_is_reached_after_two_steps:
  One has

    (Gsat/G)_n=0

  for every n>=2.  Consequently

    ell^2*(Gsat/G)=0,
    G:ell^2=Gsat,

  and

    G:ell^j=Gsat

  for every j>=2.

Proof:
  Let x in Gsat be homogeneous of degree n>=2.  Choose m>=0 such that

    ell^m*x*b belongs to (a).

  Write

    ell^m*x*b=a*c

  with c homogeneous of degree n+m.  By the first theorem, multiplication by
  ell^m gives an isomorphism

    Cbar_n -> Cbar_(n+m).

  Hence c=ell^m*c0 for a unique c0 in Cbar_n.  Therefore

    ell^m*(x*b-a*c0)=0.

  Since ell is a nonzerodivisor, cancellation gives

    x*b=a*c0,

  so x belongs to G.  Thus G and Gsat agree in every degree at least two.

  If x in Gsat has degree below two, ell^2*x has degree at least two and still
  belongs to Gsat, hence lies in G.  Therefore ell^2*Gsat subseteq G, which is
  equivalent to Gsat subseteq G:ell^2.  The reverse inclusion is automatic
  from the definition of saturation.  Hence G:ell^2=Gsat, and all later
  colons are equal as well.
Qed.

