    V_i ~= Cbar/(Gsat,ell)

  up to grading shift.

Proof:
  The generator statement is immediate.  If c*u_i=0, then

    c*ell^(i-1)*b
      =p*a+q*ell^i*b

  for some p,q.  Thus

    (c-q*ell)*ell^(i-1)*b belongs to (a),

  so

    c-q*ell belongs to G:ell^(i-1).

  This gives one containment in the annihilator formula; the reverse
  containment is immediate.  For i>=3 one has i-1>=2, so the preceding theorem
  identifies G:ell^(i-1) with Gsat.
Qed.

