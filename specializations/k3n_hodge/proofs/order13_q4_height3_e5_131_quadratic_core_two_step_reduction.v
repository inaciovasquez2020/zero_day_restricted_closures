Theorem quadratic_baseline_deficit_is_at_most_eleven:
  One has

    eta_0<=11.

Proof:
  Since K_0=(a,b) is m-primary in the one-dimensional Cohen--Macaulay ring
  Cbar, a general constant linear combination

    q=lambda*a+mu*b

  is a quadratic nonzerodivisor on Cbar.

  Choose its homogeneous quadratic lift to B, still denoted q.  Because
  m_B*T=0, q kills T.  Since q is regular on Cbar, the multiplication kernel
  on B is exactly T.

  Put

    F:=0:_X K_0.

  Then F subseteq 0:_X q.  Multiplication by q on finite-dimensional X has
  kernel and cokernel of the same dimension, so

    length(F)<=length(X/qX).

  The element q is nonzero in A_2 because the final cut ideal starts in degree
  at least three.  Since X=m_A and q has degree two, the graded decomposition
  shows

    length(X/qX)=length(A/qA).

  The latter is a quotient of B/qB.

  The exact sequence

    0 -> T(-2) -> B(-2) --q--> B -> B/qB -> 0

  gives

    Hilb_(B/qB)
      =(1-t^2)*Hilb_B+t^2*Hilb_T
      =(1-t^2)*Hilb_Cbar+t^2
      =1+4*t+5*t^2+t^3.

  Therefore

    length(B/qB)=11,

  and hence length(F)<=11.

  Multiplication gives a natural map

    X -> Hom_Cbar(K_0,X)

  with kernel F.  Consequently

    dim Hom_Cbar(K_0,X)
      >=(N-1)-length(F)
      >=(N-1)-11,

  which is exactly eta_0<=11.
Qed.

