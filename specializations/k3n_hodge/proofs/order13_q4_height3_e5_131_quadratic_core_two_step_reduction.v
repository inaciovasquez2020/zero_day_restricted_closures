Theorem ell_annihilator_of_the_target_has_dimension_six:
  One has

    dim_C(0:_X ell)=6.

Proof:
  Since X=m_A and ell has positive degree, every element of 0:_A ell has zero
  scalar part.  Hence

    0:_X ell=0:_A ell.

  Multiplication by ell on finite-dimensional A has kernel and cokernel of the
  same dimension, so

    dim_C(0:_A ell)=length_C(A/ell*A).

  The quadratic factorization gives s>=1 and Lbar=ell^s*K_k.  Because T is
  concentrated in degree two while the final cuts have degree at least three,
  the divisibility by ell lifts from Cbar to B.  Thus L subseteq ell*B and

    A/ell*A ~= B/ell*B.

  Since ell is regular on Cbar and m_B*T=0,

    0:_B ell=T.

  From

    Hilb_Cbar(t)=(1+3*t+t^2)/(1-t),
    Hilb_T(t)=t^2,

  the multiplication-by-ell exact sequence gives

    Hilb_(B/ell*B)(t)
      =(1-t)*Hilb_B(t)+t*Hilb_T(t)
      =1+3*t+2*t^2.

  Its length is six.
Qed.

