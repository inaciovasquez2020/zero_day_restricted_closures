  The active-parameter theorem makes

    ell:T_2 -> T_3

  surjective, so this discrepancy is itself an ell-multiple.  Thus f belongs
  to ell*B also in the cubic case.

  The same argument applies to g.  Hence L subseteq ell*B.
Qed.

Corollary exact_parameter_annihilator_in_A_has_dimension_six:
  One has

    A/ell*A ~= B/ell*B,

