Theorem saturated_core_maps_inject_into_actual_conormal_maps:
  Put

    X:=Ann_A(T).

  Then

    dim_C X=N-3

  and there is a natural injection

    Hom_Cbar(K_k,X) -> Hom_B(L,A).

Proof:
  The preceding cyclic-torsion reduction proves dim_C X=N-3 and L*T=0.
  Hence L is naturally a Cbar-module.

  If phi:L->A is B-linear and t belongs to T, then

    t*phi(x)=phi(t*x)=0

  for every x in L.  Therefore the image of phi lies in X.  Conversely T acts
  trivially on both L and X, so every Cbar-linear map L->X is B-linear.  Thus

    Hom_B(L,A)=Hom_Cbar(L,X).

  Projection B->Cbar gives a surjection of Cbar-modules

    L -> Lbar

  with kernel L intersect T.  Precomposition therefore injects

    Hom_Cbar(Lbar,X) -> Hom_Cbar(L,X).

  Finally multiplication by ell^s is a Cbar-module isomorphism

    K_k -> ell^s*K_k=Lbar

  because ell is a nonzerodivisor on Cbar.  Combining these maps gives the
  required injection.
Qed.

