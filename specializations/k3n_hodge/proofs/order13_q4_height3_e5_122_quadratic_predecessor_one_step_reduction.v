Theorem every_regular_quadratic_core_section_has_length_at_most_thirteen:
  Let qbar in Cbar_2 be a nonzerodivisor and let q in B_2 be any homogeneous
  lift.  Then

    length_C(B/qB)<=13.

  Consequently

    dim_C(0:_A q)<=13.

Proof:
  Since qbar is regular on Cbar, projection through

    0 -> T -> B -> Cbar -> 0

  gives

    0:_B q=0:_T q.

  The torsion module is the shifted cubic string

    T ~= C[z]/(z^3)(-1).

  A degree-two element can act on T only from T_1 to T_3; it kills T_2 and
  T_3 for degree reasons.  Hence

    length_C(0:_T q)<=3.

