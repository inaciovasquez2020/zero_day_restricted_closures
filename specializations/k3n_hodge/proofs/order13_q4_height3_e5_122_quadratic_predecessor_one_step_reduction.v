Lemma exact_quadratic_layer_annihilator:
  The class

    v_i:=ell^(i-1)*b mod K_i

  generates V_i and has annihilator

    Ann_Cbar(v_i)=(G:ell^(i-1),ell).

  In particular, for every i>=2,

    V_i ~= Cbar/(Gsat,ell)

  up to grading shift.

Proof:
  If c*v_i=0, then

    c*ell^(i-1)*b
      =p*a+q*ell^i*b

  for suitable p,q.  Therefore

    (c-q*ell)*ell^(i-1)*b in (a),

  so

    c-q*ell in G:ell^(i-1).

  This proves one containment in the annihilator formula; the reverse is
  immediate.  For i>=2, the preceding one-step saturation theorem gives

    G:ell^(i-1)=Gsat.
Qed.

