Qed.

Theorem the_h122_core_has_quadratic_predecessors:
  Order the final degrees as

    d:=deg(f)<=D:=deg(g),

  and put

    r:=d-3>=0,
    k:=D-d>=0.

  Then there are unique alpha,beta in Cbar_3 with

    fbar=ell^r*alpha,
    gbar=ell^(r+k)*beta.

  Moreover there are unique a,b in Cbar_2 such that

    alpha=ell*a,
    beta=ell*b.

  Put

    K_i:=(a,ell^i*b)

  for i>=0 and

    s:=r+1=d-2>=1.

  Then

    J_i:=(alpha,ell^i*beta)=ell*K_i,
    Lbar=(fbar,gbar)=ell^s*K_k,

  and K_0=(a,b) is m-primary in Cbar.

Proof:
  The low-multiplicity core profile gives the first degree-three factorization.

  Since

    Hilb_Cbar(t)=(1+2*t+2*t^2)/(1-t),

  one has

    dim_C Cbar_n=5

  for every n>=2.  Multiplication by the regular parameter ell is injective in
  every degree, hence

    ell:Cbar_n -> Cbar_(n+1)

  is an isomorphism for every n>=2.  In particular alpha and beta have unique
  quadratic predecessors a and b.

  The displayed ideal identities follow immediately.  The preceding core
  profile proves J_k is m-primary.  Since J_k is contained in J_0=ell*K_0, any
  homogeneous prime containing K_0 also contains J_0 and hence J_k.  Therefore
  K_0 is m-primary.
Qed.

Theorem the_actual_final_cut_ideal_is_divisible_by_the_active_parameter:
  For

    L:=(f,g)B,

  one has

    L subseteq ell*B.

Proof:
  On Cbar the preceding theorem gives

    fbar=ell^s*a,
    gbar=ell^(s+k)*b,

  with s>=1.

  Choose homogeneous lifts of a and b to B.  If d>=4, the difference between
  f and ell^s*a lies in T_d=0, so f is divisible by ell in B.  If d=3, then
  s=1 and

