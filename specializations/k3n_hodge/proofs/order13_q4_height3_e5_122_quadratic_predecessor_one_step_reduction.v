Theorem every_layer_after_the_first_has_nonpositive_Bockstein_defect:
  For every i>=2,

    Delta_i<=0.

Proof:
  For i>=2 the layer theorem gives, up to grading shift,

    V_i ~= Cbar/(Gsat,ell).

  Put

    N_G:=0:_X Gsat.

  For y in N_G define a map K_i->X by

    a |-> 0,
    ell^i*b |-> y.

  It is well defined because every coefficient relation on ell^i*b belongs to

    G:ell^i=Gsat.

  In the cyclic presentation of

    0 -> K_i -> K_(i-1) -> V_i -> 0,

  the connecting class of this map is represented by

    ell |-> y,
    Gsat |-> 0.

  The class vanishes exactly when y belongs to ell*N_G.  Hence these explicit
  connecting classes have rank

    dim_C(N_G/ell*N_G)
      =dim_C(0:_N_G ell)
      =dim_C Hom_Cbar(V_i,X),

  where the middle equality is rank-nullity for multiplication by ell on the
  finite-dimensional module N_G.

  Applying Hom_Cbar(-,X) to

    0 -> K_i -> K_(i-1) -> V_i -> 0

  gives

    Delta_i
      =dim Hom_Cbar(V_i,X)-rank(connecting)
      <=0.
Qed.

