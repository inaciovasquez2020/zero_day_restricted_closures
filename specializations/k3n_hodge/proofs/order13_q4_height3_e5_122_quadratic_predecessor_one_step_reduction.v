Theorem choose_parameter_active_on_the_cyclic_torsion:
  One may choose the Noether parameter ell so that

    ell is a nonzerodivisor on Cbar,

  and simultaneously the degree-one class of ell is not contained in

    Ann_B(T)_1.

  For such a choice, multiplication by ell gives isomorphisms

    T_1 -> T_2,
    T_2 -> T_3,

  and

    0:_T ell = T_3,
    0:_B ell = T_3.

Proof:
  The set of linear zerodivisors on the one-dimensional Cohen--Macaulay ring
  Cbar is the finite union of the degree-one parts of its associated, hence
  minimal, primes.  Its complement is a nonempty Zariski-open subset of
  Cbar_1.

  The preceding cyclic-torsion file identifies

    B/Ann_B(T) ~= C[z]/(z^3)

  as a standard graded Artin algebra.  Its degree-one part is one-dimensional,
  so Ann_B(T)_1 is a proper linear subspace of B_1.  Avoiding that subspace is
  one further nonempty open condition.  Choose ell satisfying both conditions.

  Under

    T ~= C[z]/(z^3)(-1),

  the image of ell in B/Ann_B(T) is a nonzero scalar multiple of z.  Hence its
  action is nonzero between the one-dimensional successive pieces

    T_1 -> T_2 -> T_3,

  and therefore both maps are isomorphisms.  It kills T_3 for degree reasons,
  so 0:_T ell=T_3.

  Finally project

    0 -> T -> B -> Cbar -> 0

  through multiplication by ell.  Since ell is regular on Cbar, every element
  killed by ell in B lies in T.  Therefore

    0:_B ell=0:_T ell=T_3.
Qed.

Theorem exact_active_parameter_section_has_length_six:
  One has

