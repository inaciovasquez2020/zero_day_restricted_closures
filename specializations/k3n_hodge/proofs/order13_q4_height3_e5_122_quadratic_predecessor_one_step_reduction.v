Assume a is a zerodivisor on Cbar.

Put

  G:=(a:b),
  Gsat:=G:ell^infinity.

Theorem the_zerodivisor_quadratic_colon_saturation_is_proper:
  Gsat is a proper homogeneous ideal of Cbar.

Proof:
  Since Cbar is one-dimensional Cohen--Macaulay, its associated primes are its
  minimal primes.  Because a is a zerodivisor, choose a minimal prime P with

    a in P.

  Since K_0=(a,b) is m-primary, b is not in P.  Thus b becomes a unit after
  localizing at P and

    G_P=(a:b)_P=(a)_P,

  which is proper in the local ring Cbar_P.

  The parameter ell is a nonzerodivisor, hence ell is not in P and becomes a
  unit in Cbar_P.  Saturating by powers of ell therefore does not change this
  localization:

    (Gsat)_P=G_P.

  Thus Gsat is proper.
Qed.

Theorem the_quadratic_colon_saturates_after_one_parameter_step:
  One has

    (Gsat/G)_n=0

  for every n>=2, and consequently

    G:ell=Gsat,
    G:ell^j=Gsat

  for every j>=1.

Proof:
  Let x in Gsat be homogeneous of degree n>=2.  Choose m>=0 with

    ell^m*x*b in (a),

  say

    ell^m*x*b=a*c.

  Here c has degree n+m.  Since multiplication by ell is an isomorphism on
  Cbar in every degree starting with degree two, there is c0 in Cbar_n with

    c=ell^m*c0.

  Hence

    ell^m*(x*b-a*c0)=0.

  Regularity of ell permits cancellation, giving x*b=a*c0 and therefore x in
  G.  This proves equality of G and Gsat in all degrees at least two.

  Properness of the homogeneous ideal Gsat gives (Gsat)_0=0, so the finite
  quotient Gsat/G can occur only in degree one.  Multiplication by ell sends
  that degree into degree two, where Gsat and G agree.  Thus

    ell*Gsat subseteq G,

  equivalently Gsat subseteq G:ell.  The reverse inclusion follows from the
  definition of saturation.  Hence G:ell=Gsat, and all later ell-colons agree
  with Gsat as well.
Qed.

