  B/qB has length

    2*e(Cbar)+length_C(0:_B q)
      <=2*5+3
      =13.

  Since A/qA is a quotient of B/qB,

    length_C(A/qA)<=13.

  Multiplication by q on finite-dimensional A has kernel and cokernel of equal
  dimension, so

    dim_C(0:_A q)=length_C(A/qA)<=13.
Qed.

