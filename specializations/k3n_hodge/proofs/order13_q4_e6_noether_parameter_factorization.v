Theorem noether_parameter_free_module_normal_form:
  Let ell in B_1 be a general linear nonzerodivisor.  Then, as a graded C[ell]-module,

    B ~= C[ell]
         direct_sum C[ell](-1)^3
         direct_sum C[ell](-2)^2.

Proof:
  The Artin reduction H=B/(ell) has Hilbert function (1,3,2).  Choose homogeneous lifts in B of a basis consisting of one element in degree zero, three in degree one, and two in degree two.  They define a graded C[ell]-linear map

    C[ell] direct_sum C[ell](-1)^3 direct_sum C[ell](-2)^2 -> B.

  Modulo ell this map is an isomorphism onto H, hence graded Nakayama gives surjectivity.  The source has Hilbert series

    (1+3*t+2*t^2)/(1-t),

  equal to Hilb_B(t).  Therefore the graded kernel has zero Hilbert series and is zero.
Qed.

Corollary degree_compression_to_B2:
  For every n>=2, multiplication by ell^(n-2) is a C-vector-space isomorphism

    B_2 --ell^(n-2)--> B_n.

  Consequently every homogeneous h in B_n has a unique expression

    h = ell^(n-2) * h_2

  with h_2 in B_2.
Qed.

Theorem two_higher_degree_cuts_factor_through_quadratic_core:
  There are unique a,b in B_2 such that

    f = ell^(d-2) * a,
    g = ell^(e-2) * b.

  Put

    k := e-d >=0,
    J := (a, ell^k*b) subset B.

  Then

    L:=(f,g)B = ell^(d-2) * J.

  Since L is m-primary, J is m-primary as well.
Qed.

Theorem exact_length_peeling_formula:
  With J as above there is a short exact sequence

    0 -> B/J
      --ell^(d-2)-->
      B/L
      -> B/(ell^(d-2))
      -> 0.

  Hence, writing N=length_C(B/L),

    N = length_C(B/J) + 6*(d-2).

Proof:
  The displayed map sends x mod J to ell^(d-2)*x mod L.  It is injective because ell is a nonzerodivisor on B.  Its image is ell^(d-2)B/L, so the cokernel is B/(ell^(d-2)).

  Since ell is a degree-one parameter on the one-dimensional Cohen--Macaulay ring B of multiplicity six,

    length B/(ell^r)=6*r

  for every r>=1.  Taking r=d-2 gives the formula.
Qed.

Corollary arbitrary_degree_endpoint_reduces_to_one_quadratic_and_one_shifted_quadratic:
  The homogeneous e=6 endpoint contains no genuinely new high-degree shape before the quadratic core.  After removing the common Noether-parameter factor ell^(d-2), the residual m-primary ideal is always

    J=(a, ell^(e-d)*b)

  with a,b in the fixed six-dimensional vector space B_2.

  Thus the degree dependence is separated into the single integer e-d and the additive length term 6*(d-2).
Qed.

