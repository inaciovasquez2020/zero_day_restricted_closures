Theorem equal_degree_quadratic_core_has_length_nine_or_ten:
  After a constant GL_2(C) change of the pair (a,b), assume a is a nonzerodivisor on B.  Put

    C:=B/(a).

  Then C is an Artin graded level algebra of type two with Hilbert function

    (1,4,5,2).

  Let

    r := rank_C( C_1 --times b--> C_3 ).

  Then

    r in {1,2},

  and

    Hilb_(B/(a,b)) =
      (1,4,4,1) if r=1,
      (1,4,4)   if r=2.

  In particular

    length B/(a,b) in {10,9}.

Proof:
  Because J is m-primary in the one-dimensional Cohen--Macaulay ring B over the infinite field C, a general constant linear combination of a,b avoids Ass(B), so it is a homogeneous quadratic nonzerodivisor.

  The Hilbert series of C is

    Hilb_C(t)=(1-t^2)Hilb_B(t)
             =(1+t)(1+3*t+2*t^2)
             =1+4*t+5*t^2+2*t^3.

  The forced last free module S(-5)^2 in the resolution of B shows that B is level of type two.  Quotient by the homogeneous nonzerodivisor a preserves levelness and type, so Soc(C)=C_3 and dim C_3=2.

  The class of b in C_2 is nonzero because a,b are independent.  If r=0, then C_1*b=0.  Since C is standard graded and C_i*b=0 automatically for i>=2 by degree, b would be a nonzero socle element in degree two, contradicting Soc(C)=C_3.  Thus r>=1.  Since dim C_3=2, r<=2.

  The principal ideal (b) in C has one-dimensional degree-two part C_0*b and degree-three part C_1*b of dimension r; there are no higher pieces.  Therefore quotienting C by b changes the Hilbert function from

    (1,4,5,2)

  to

    (1,4,4,2-r),

  giving exactly the two displayed possibilities and lengths 10 or 9.
Qed.

