Theorem annihilator_dual_is_exactly_two_generated:
  One has

    mu_A(D^vee)=2.

Proof:
  Suppose instead that D^vee were cyclic.  Since

    length(D^vee)=length(D)=N=length(A),

  a cyclic surjection A -> D^vee would be an isomorphism.  Dualizing over C would give

    D ~= Hom_C(A,C)=omega_A.

  For every Artin local C-algebra A, the canonical module omega_A has one-dimensional socle: its socle is dual to A/m_A.  Hence dim Soc_A(D)=1, contradicting the already proved value two.

  Thus mu_A(D^vee)>=2, and the preceding upper bound mu_A(D^vee)<=2 forces equality.
Qed.

