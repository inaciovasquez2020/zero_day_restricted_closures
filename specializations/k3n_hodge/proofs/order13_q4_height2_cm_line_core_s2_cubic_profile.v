Theorem r3_s2_canonical_quartic_is_not_an_H0_multiple:
  Normalize the r=3 generators as

    q1 = z*l1 + h1,
    q2 = w*l1 + z*l2 + h2,
    q3 = w*l2 + h3,
    q4 = H0,

  with h1,h2,h3,H0 in P_2, and define

    C4 := l2^2*h1-l1*l2*h2+l1^2*h3.

  Then

    C4 in Q_4 intersect P_4

  but

    C4 notin H0*P_2.

Proof:
  The canonical compatibility identity

    l2^2*q1-l1*l2*q2+l1^2*q3=C4

  proves C4 belongs to Q_4 intersect P_4.

  Suppose for contradiction that H0 divides C4.  Choose a projective root

    [a:b] in P^1

  of the nonzero quadratic H0.  Such a root exists over C.  Then

    H0(a,b)=0,
    C4(a,b)=0.

  Evaluate q1,q2,q3 at l1=a,l2=b.  Solving them for z,w gives the linear system

    a*z       = -h1(a,b),
    b*z+a*w   = -h2(a,b),
        b*w   = -h3(a,b).

  For every nonzero pair (a,b), its 3 by 2 coefficient matrix has rank two and
  its unique compatibility condition is

    b^2*h1(a,b)-a*b*h2(a,b)+a^2*h3(a,b)=0,

  exactly C4(a,b)=0.  Therefore there exist z0,w0 satisfying q1=q2=q3=0.
  Together with q4=H0=0 this produces a projective common zero

    [a:b:z0:w0]

  of Q with (a,b) nonzero.

  This point is off the line V(J)={l1=l2=0}, contradicting Qsat=J, equivalently
  Proj(S/Q)=Proj(S/J).  Hence C4 is not divisible by H0.
Qed.

