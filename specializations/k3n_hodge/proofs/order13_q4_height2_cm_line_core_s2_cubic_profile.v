Theorem r4_s2_cubic_space_is_exactly_the_basepoint_free_canonical_pair:
  Assume r=4 and s=2.  In the normalized r=4 quadratic form

    q1 = z*l1 + h1,
    q2 = w*l1 + h2,
    q3 = z*l2 + h3,
    q4 = w*l2 + h4,

  define the canonical pure cubics

    Pz := l2*h1-l1*h3,
    Pw := l2*h2-l1*h4.

  Then

    K3 = Span_C{Pz,Pw},

  and

    gcd(Pz,Pw)=1.

Proof:
  The third-layer classification proves that Pz and Pw are independent elements
  of Q intersect P_3 and have no common projective zero in P(V)=P^1.

  Since the present s=2 hypothesis gives dim_C K3=2, these two independent
  cubics already form a basis of K3.

  Two homogeneous forms in two variables have a nonconstant common divisor if
  and only if they have a common projective zero over C.  Therefore the absence
  of a common projective zero gives gcd(Pz,Pw)=1.
Qed.

Corollary r4_s2_quartic_span_has_codimension_one:
  In the r=4,s=2 case,

    dim_C(P_1*K3)=4,

  hence

    codim_{P_4}(P_1*K3)=1.

Proof:
  The multiplication map

    P_1 tensor K3 -> P_4

  has four-dimensional source.  A nonzero kernel vector would be a linear
  syzygy

    A*Pz+B*Pw=0

  with A,B linear.  Since gcd(Pz,Pw)=1, Pz divides B and Pw divides A, which is
  impossible by degree unless A=B=0.  Thus the map is injective and its image
  has dimension four.  Since dim_C P_4=5, the codimension is one.
Qed.

