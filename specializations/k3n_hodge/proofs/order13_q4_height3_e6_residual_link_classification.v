Theorem residual_link_is_complete_intersection_112:
  There exists a quadric q such that

    J=(l1,l2,q),

  and l1,l2,q form a regular sequence.  Equivalently, the residual Gorenstein link is a complete intersection of degrees

    (1,1,2).

Proof:
  Modulo the two independent linear forms l1,l2, write

    S/(l1,l2) ~= C[u,v].

  Let Jbar be the image of J.  Since ht(J)=3 and l1,l2 are part of a homogeneous system cutting the two linear directions, Jbar has height one in C[u,v], while

    C[u,v]/Jbar ~= S/J

  remains Cohen--Macaulay of dimension one.

  A height-one Cohen--Macaulay homogeneous ideal in the regular UFD C[u,v] is principal.  Write

    Jbar=(qbar)

  for a homogeneous form qbar.

  The multiplicity of the hypersurface C[u,v]/(qbar) equals deg(qbar).  Since e(S/J)=2, deg(qbar)=2.

  Lifting qbar gives a quadric q with

    J=(l1,l2,q).

  Height three then implies l1,l2,q is a regular sequence.
Qed.

