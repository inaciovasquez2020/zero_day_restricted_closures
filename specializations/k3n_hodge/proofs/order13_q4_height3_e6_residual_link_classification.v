ExternalResult GradeThreeACIResidualIsGorenstein:
  Let R be a Gorenstein ring and I a grade-three perfect almost-complete-intersection ideal.  If K subset I is generated by a regular sequence of length three and J:=K:I, then I and J are directly linked by K and J is grade-three Gorenstein.

ExternalResult MultiplicityAdditionUnderDirectLinkage:
  If homogeneous unmixed ideals I,J of the same codimension are directly linked by a homogeneous complete intersection K, then

    e(S/I)+e(S/J)=e(S/K).

