Theorem residual_link_has_multiplicity_two:
  One has

    e(S/J)=2.

Proof:
  K is a complete intersection of three quadrics, hence

    e(S/K)=2*2*2=8.

  Direct linkage gives

    e(S/Q)+e(S/J)=e(S/K).

  Since e(S/Q)=6,

    e(S/J)=8-6=2.
Qed.

Theorem residual_link_has_h_vector_11:
  The one-dimensional Cohen--Macaulay Gorenstein algebra R:=S/J has Hilbert series

    Hilb_R(t)=(1+t)/(1-t).

Proof:
  Let ell be a general linear nonzerodivisor on R.  Then H:=R/(ell) is an Artin standard graded Gorenstein algebra of length

    length(H)=e(R)=2.

  Since H_0=C and H is not the zero ring, its only possible standard graded Hilbert function of total length two is

    (1,1).

  Therefore the h-polynomial of R is 1+t, giving the displayed Hilbert series.
Qed.

