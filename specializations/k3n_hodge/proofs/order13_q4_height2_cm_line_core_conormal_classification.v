Theorem exact_syzygy_degrees_in_the_two_cases:
  The minimal R-resolution of M is exactly one of the following.

  FOUR-RELATION CASE:

    0 -> R(-2)^2 -> R(-1)^4 -> R^2 -> M -> 0.

  THREE-RELATION CASE:

    0 -> R(-3) -> R(-1)^3 -> R^2 -> M -> 0.

Proof:
  If r=4, then F2 has rank two and the sum of its two generator degrees is
  four.  Since each degree is at least two, both degrees are exactly two.

  If r=3, then F2 has rank one and its unique generator degree has sum three,
  hence is exactly three.
Qed.

Theorem exact_first_conormal_Hilbert_dichotomy:
  The Hilbert series of M is exactly

    Hilb_M(t)=2

  in the four-relation case, and

    Hilb_M(t)=2+t

  in the three-relation case.

Equivalently, before the shift,

    Hilb_E(t)=2*t

  or

    Hilb_E(t)=2*t+t^2.

In particular

    length_C(E) in {2,3},

and in every case

    n^2*E=0.

In the four-relation case the stronger statement

    n*E=0

holds.

Proof:
  For r=4 the resolution gives

    Hilb_M(t)
      =(2-4*t+2*t^2)/(1-t)^2
      =2.

  For r=3 it gives

    Hilb_M(t)
      =(2-3*t+t^3)/(1-t)^2
      =2+t.

  The annihilation statements follow immediately from these graded Hilbert
  functions because M is generated in degree zero.  Shifting does not change
  module length or the action of n.
Qed.

