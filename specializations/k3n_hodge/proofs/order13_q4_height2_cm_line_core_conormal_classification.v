Theorem finite_length_forces_maximal_minor_support_at_the_line_origin:
  In either presentation, the ideal of maximal 2 by 2 minors of A is
  n-primary in R.

Proof:
  The support of the cokernel M is the vanishing set of its zeroth Fitting
  ideal, which is generated by the maximal minors of A.  Since M is finite
  length, its support is only the homogeneous maximal ideal n.  Hence the
  radical of the maximal-minor ideal is n.
Qed.

