Because ht(Q)=3, B has dimension one.  The surviving homogeneous q=5 branch from the regular-cut obstruction has depth(B)=0, so T is nonzero and finite length.

Theorem saturation_quotient_is_one_dimensional_CohenMacaulay:
  Cbar=S/Qsat has dimension one and H^0_m(Cbar)=0.

  Therefore depth_m(Cbar)>=1.  Since dim(Cbar)=1,

    depth_m(Cbar)=dim(Cbar)=1,

  so Cbar is Cohen--Macaulay at m.
Qed.

Theorem final_cut_is_regular_on_saturated_quotient:
  The image of f in Cbar is a nonzerodivisor.

Proof:
  A=B/fB has finite length.  Its quotient Cbar/f Cbar therefore also has finite length.  Hence f is a parameter on the one-dimensional local Cohen--Macaulay ring Cbar_m.

  A parameter on a one-dimensional Cohen--Macaulay local ring is a nonzerodivisor.
Qed.

Theorem colon_defect_lives_entirely_in_finite_torsion:
  D=0:_B f equals 0:_T f.  In particular

    D subseteq T.

Proof:
  Apply multiplication by f to the short exact sequence

    0 -> T -> B -> Cbar -> 0.

  The kernel on Cbar is zero by the preceding theorem.  The kernel on B is D.  Exactness therefore identifies

    D = ker(f:T->T) = 0:_T f.
Qed.

Theorem final_cut_length_exact_sequence:
  There is a short exact sequence

    0 -> T/fT -> A -> Cbar/f Cbar -> 0.

Proof:
  Again apply multiplication by f to

    0 -> T -> B -> Cbar -> 0.

  Since multiplication by f is injective on Cbar, the snake sequence gives the stated cokernel sequence.
Qed.

Theorem colon_defect_length_equals_torsion_cut_length:
  Since T is finite-dimensional over C, multiplication by f is an endomorphism of the finite-dimensional vector space T.  Hence

    dim ker(f:T->T) = dim coker(f:T->T).

  Using the preceding identifications,

    length(D) = length(T/fT).
Qed.

