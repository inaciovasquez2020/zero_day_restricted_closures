IMPORTANT_NONCONCLUSION:
  The full unequal-degree e(B)=6 endpoint is not closed here.

  The unresolved subbranch is precisely the case in which the lower-degree
  homogeneous generator f, equivalently its quadratic factor a, is a
  zerodivisor on B.  A general local constant combination of f and g can be
  made regular, but when deg(f)<deg(g) that combination is not homogeneous and
  does not preserve the graded Noether-parameter factorization used above.

  No conclusion is drawn for that zerodivisor lower-cut subbranch, for the
  height-three e(B)<=5 cases, for the height-two q=4 core, for homogeneous
  q<=3, or for the unrestricted nonhomogeneous local frontier.

