Define the multiplication-kernel module

  E:=0:_A J
    =(ell^r*J :_B J)/(ell^r*J).

Theorem annihilator_vanishes_below_common_parameter_order:
  For every n<r,

    E_n=0.

Proof:
  Let x in B_n represent a class in E_n.  Then

    x*a in L_(n+2).

  The first generator of L has degree r+2 and the second has degree r+3.
  Since n<r,

    L_(n+2)=0.

  Thus x*a=0.  Regularity of a gives x=0.
Qed.

Theorem first_middle_degree_has_dimension_one:
  One has

    dim_C E_r=1.

Proof:
  In degree r+2,

    L_(r+2)=C*(ell^r*a).

  If x in B_r represents a class in E_r, then

    x*a=lambda*ell^r*a

  for some scalar lambda.  Since a is a nonzerodivisor,

    x=lambda*ell^r.

  Conversely ell^r annihilates both generators of J modulo L:

    ell^r*a in L,
    ell^r*(ell*b) in L.

  Since L_r=0, the degree-r part of E is exactly C*ell^r.
Qed.

Theorem second_middle_degree_has_dimension_at_most_six:
  One has

    dim_C E_(r+1)<=6.

Proof:
  The degree-(r+1) part of E is a subquotient of B_(r+1).  Because r+1>=2,
  the fixed Hilbert series of B gives

    dim_C B_(r+1)=6.

  Therefore dim_C E_(r+1)<=6.
Qed.

Theorem annihilator_tail_is_the_shifted_residual_core_tail:
  For every n>=r+2 there is a natural vector-space isomorphism

    E_n ~= (B/J)_(n-r).

Proof:
  Put m:=n-r>=2.  Multiplication by ell^r is a vector-space isomorphism

    B_m --times ell^r--> B_n.

  Thus every x in B_n has a unique expression

    x=ell^r*y,
    y in B_m.

  Then

    x*J=ell^r*(yJ) subseteq ell^r*J=L,

  so the whole degree B_n lies in the colon (L:J)_n.  Dividing the quotient

    B_n/L_n

  through the displayed multiplication isomorphism identifies it with

    B_m/J_m=(B/J)_m.
Qed.

Corollary annihilator_length_is_at_most_thirteen:
  One has

    length_C(E)<=13.

Proof:
  Degrees below r contribute zero.  Degree r contributes exactly one.
  Degree r+1 contributes at most six.

  The tail theorem identifies all degrees n>=r+2 with the part of B/J in
  degrees at least two.  Since

    Hilb_(B/J)=(1,4,5,1),

  that tail has length

    5+1=6.

  Hence

    length(E)<=1+6+6=13.
Qed.

