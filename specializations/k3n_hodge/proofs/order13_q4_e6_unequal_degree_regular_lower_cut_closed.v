Theorem regular_quadratic_cut_has_fixed_Artin_Hilbert_function:
  Assume a is a nonzerodivisor on B and put

    C0:=B/(a).

  Then

    Hilb_C0(t)
      =(1-t^2)Hilb_B(t)
      =1+4*t+5*t^2+2*t^3.

  Hence C0_n=0 for every n>=4.
Qed.

Theorem regular_lower_cut_forces_degree_gap_one:
  Under the hypotheses above,

    k=1.

Proof:
  Suppose k>=2.  The image of ell^k*b in C0 has degree

    k+2>=4,

  so the preceding Hilbert-function computation gives

    ell^k*b in (a)B.

  Multiplying by ell^r yields

    g=ell^r*(ell^k*b) in ell^r*(a)B=(f)B.

  Therefore Q+(f,g)=Q+(f), contradicting the assumption that I is minimally
  generated by the four quadratic generators of Q together with both f and g.

  Since k>0, the only remaining value is k=1.
Qed.

