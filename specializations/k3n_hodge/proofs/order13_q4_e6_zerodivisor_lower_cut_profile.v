Theorem support_module_is_generated_over_Cellell_in_degrees_at_most_four:
  As a C[ell]-module, M is generated in degrees 2,3,4.

Proof:
  The ring B is generated as a C[ell]-module by one element in degree zero,
  three in degree one, and two in degree two.  Since M=b*C_a is the image of
  multiplication by the quadratic element b, the corresponding images
  generate M over C[ell] in degrees 2,3,4.
Qed.

Let

  T:=H^0_((ell))(M)

be the C[ell]-torsion submodule of M.

Theorem support_module_torsion_is_confined_to_degrees_two_and_three:
  The C[ell]-module M has rank s, and

    T_n=0

  unless n=2 or n=3.  In particular

    ell^2*T=0.

Proof:
  The Hilbert function of M is constant equal to s for every n>=4, so its
  C[ell]-rank is s.

  By the preceding generation theorem, every minimal homogeneous
  C[ell]-generator of M occurs in degree at most four.  Apply the graded
  structure theorem over the PID C[ell]:

    M = F direct_sum T

  with F free of rank s and T finite ell-primary torsion.

  Every free summand of F begins in degree at most four, so all s free
  summands already contribute to M_4.  But dim M_4=s.  Therefore T_4=0.

  A homogeneous cyclic ell-primary torsion summand occupies consecutive
  degrees starting at the degree of its generator.  Since no minimal
  generator begins after degree four and T_4=0, no torsion can occur in any
  degree >=4.  Since M vanishes below degree two, T is confined to degrees two
  and three.  Hence ell^2*T=0.
Qed.

Corollary support_module_torsion_has_uniform_length_bound:
  One has

    length_C(T)
      <= dim M_2 + dim M_3
      = 3+t-epsilon
      <= 8.
Qed.

Theorem delayed_pair_quotient_is_exactly_a_parameter_delay_of_M:
  There is a natural isomorphism

    J_0/J_k ~= M/ell^k*M.

Proof:
  Modulo the common subideal (a), the ideal J_0 is b*C_a=M while J_k is
  ell^k*b*C_a=ell^k*M.  Taking the quotient gives the result.
Qed.

Define

  tau_k:=length_C(0:_M ell^k).

Theorem exact_delayed_core_length_formula:
  One has

    length_C(B/J_k)
      = 9 + epsilon + k*s + tau_k,

  where

    0 <= tau_k <= 3+t-epsilon <= 8,

  and for every k>=2,

    tau_k=length_C(T).

Proof:
  The exact sequence

    0 -> J_0/J_k
      -> B/J_k
      -> B/J_0
      -> 0

  reduces the problem to length(M/ell^k M).

  Write M=F direct_sum T as above.  The free rank-s part contributes exactly

    k*s

  to the quotient by ell^k.  On the finite torsion part, kernel and cokernel
  of multiplication by ell^k have equal length, hence the torsion contribution
  is

    length(0:_T ell^k)=length(0:_M ell^k)=tau_k.

  The torsion-length bound was proved above.  Since ell^2*T=0, every k>=2
  kills all of T, giving tau_k=length(T).

  Finally length(B/J_0)=9+epsilon.
Qed.

Corollary original_unequal_degree_length_is_quantized:
