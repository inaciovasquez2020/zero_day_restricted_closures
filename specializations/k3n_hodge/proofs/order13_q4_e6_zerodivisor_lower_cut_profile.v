Proof:
  Combine the exact length-peeling formula

    N=6*r+length(B/J_k)

  with exact_delayed_core_length_formula.
Qed.

Interpretation:
  The unequal-degree zerodivisor branch no longer contains an uncontrolled
  high-degree parameter.  Its dependence on the degree gap k is exactly

    k*s

  plus a torsion correction of size at most eight, where s is the stable
  annihilator/support rank of the lower quadratic factor.

  Geometrically, s is the multiplicity carried by the one-dimensional part
  left after the zerodivisor cut a; the delayed second cut pays k copies of
  that support rank.

