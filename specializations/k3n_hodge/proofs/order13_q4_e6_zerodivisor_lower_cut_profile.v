Define

  K_a := 0:_B a,
  s := dim_C (K_a)_2,
  t := dim_C (K_a)_1.

Theorem quadratic_zerodivisor_annihilator_stabilizes_in_degree_two:
  One has

    dim_C (K_a)_n = s

  for every n>=2.

Proof:
  For n>=2, every x in B_n has a unique expression

    x=ell^(n-2)*x_2,
    x_2 in B_2.

  Since ell is a nonzerodivisor on B,

    a*x=0

  if and only if

    a*x_2=0.

  Thus multiplication by ell^(n-2) identifies (K_a)_2 with (K_a)_n.
Qed.

Theorem zerodivisor_support_rank_bounds:
  One has

    1 <= s <= 5,
    0 <= t <= s.

Proof:
  Because a is a nonzero zerodivisor, K_a is nonzero.  If a nonzero homogeneous
  annihilator first occurs in degree at least two, the preceding stabilization
  transports it to degree two; if it occurs in degree one, multiplication by
  ell injects it into degree two.  Hence s>=1.

  Multiplication by a on B_2 cannot have zero image, because

    ell^2*a != 0:

  otherwise regularity of ell would force a=0.  Since dim B_2=6, its kernel
  therefore has dimension at most five, so s<=5.

  Finally multiplication by ell injects (K_a)_1 into (K_a)_2, giving t<=s.
Qed.

Theorem annihilator_has_exact_Noether_parameter_shape:
  As a graded C[ell]-module,

    K_a ~= C[ell](-1)^t
          direct_sum C[ell](-2)^(s-t).

  Equivalently,

    Hilb_(K_a)(z)
      = (t*z + (s-t)*z^2)/(1-z).

Proof:
  The module K_a is a graded submodule of the C[ell]-free module B.  Since ell
  is B-regular, K_a is torsion-free over the PID C[ell], hence graded free.

  Its degree-zero part is zero because a is nonzero.  Its degree-one dimension
  is t, while the preceding theorem says every degree n>=2 has dimension s.
  For a graded free C[ell]-module this forces exactly t summands beginning in
  degree one and s-t additional summands beginning in degree two.
Qed.

Put

  C_a:=B/(a).

Theorem zerodivisor_quadratic_cut_has_exact_Hilbert_function:
  The graded Hilbert function of C_a is

    dim (C_a)_0 = 1,
    dim (C_a)_1 = 4,
    dim (C_a)_2 = 5,
    dim (C_a)_3 = 2+t,
    dim (C_a)_n = s for every n>=4.

Proof:
  Multiplication by a gives the exact graded sequence

    0 -> K_a(-2)
      -> B(-2)
      --times a--> B
      -> C_a
      -> 0.

  In degree n this gives

    dim (C_a)_n
      = dim B_n - dim B_(n-2) + dim (K_a)_(n-2),

  with the negative-degree terms interpreted as zero.

  Insert

    dim B_0=1,
    dim B_1=4,
    dim B_n=6 for n>=2,

  together with the annihilator dimensions above.  The displayed values
  follow immediately.
Qed.

Define the ordinary quadratic pair

  J_0:=(a,b).

Theorem delayed_mprimary_pair_forces_ordinary_pair_mprimary:
  The ideal J_0 is m-primary, and a,b are linearly independent in B_2.

Proof:
  Since

    J_k=(a,ell^k*b) subseteq (a,b)=J_0,

  one has

    rad(J_k) subseteq rad(J_0).

  The left side is the homogeneous maximal ideal m because J_k is m-primary,
  while J_0 is proper and homogeneous, so rad(J_0) is contained in m.  Hence

    rad(J_0)=m.

  If b were a scalar multiple of a, then J_k would be contained in (a), and
  the zerodivisor principal ideal (a) cannot be m-primary in the
  one-dimensional Cohen--Macaulay ring B.  Thus a,b are independent.
Qed.

