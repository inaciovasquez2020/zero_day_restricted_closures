Interpretation:
  The multiplication-map argument used only

    dim Hom_B(J_k,A) >= N-h_k.

  The exact formula shows that every dimension in Ext^1_B(C_k,A) is genuine
  compensation.  Therefore a dangerous candidate needs not merely a large
