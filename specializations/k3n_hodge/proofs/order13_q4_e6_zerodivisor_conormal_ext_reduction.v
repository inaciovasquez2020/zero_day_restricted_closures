Theorem ordinary_pair_annihilator_vanishes_below_common_factor_order:
  For every n<r,

    (E_0)_n=0.

Proof:
  Let z in B_n represent a class in (E_0)_n.  Since J_0 is generated by the
  two quadrics a,b,

    z*a in L_(n+2),
    z*b in L_(n+2).

  But L=ell^r J_k starts in degree r+2, while n+2<r+2.  Therefore

    z*a=0,
    z*b=0

  already in B.

  The ideal J_0=(a,b) is m-primary in the one-dimensional Cohen--Macaulay ring
  B, so it contains a nonzerodivisor q.  Since z annihilates J_0, it annihilates
  q, and regularity of q forces z=0.
Qed.

