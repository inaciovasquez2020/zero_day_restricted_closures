Theorem exact_conormal_Ext_sequence_for_Jk:
  There is a natural exact sequence of finite-dimensional C-vector spaces

    0 -> Hom_B(C_k,A)
      -> A
      -> Hom_B(J_k,A)
      -> Ext^1_B(C_k,A)
      -> 0.

Proof:
  Apply Hom_B(-,A) to

    0 -> J_k -> B -> C_k -> 0.

  Since B is free over itself,

    Ext^1_B(B,A)=0.

  The map A=Hom_B(B,A) -> Hom_B(J_k,A) is restriction, equivalently
  multiplication by the chosen element of A.  Exactness gives the displayed
  sequence.
Qed.

Define

  h_k := dim_C Hom_B(C_k,A)
       = length_C(0:_A J_k),

  x_k := dim_C Ext^1_B(C_k,A).

Corollary exact_conormal_dimension_identity:
  One has

    dim_C Hom_B(J_k,A)=N-h_k+x_k.
Qed.

Theorem full_tangent_gate_forces_Ext_deficit_twenty:
  If the order-13 necessary tangent gate holds,

    dim_C Hom_S(I,A) <= N-20,

  then

    h_k-x_k >= 20.

Proof:
  Multiplication by ell^r is a B-module isomorphism

    J_k ~= L,

  because ell is a nonzerodivisor.  The previously established maps-killing-Q
  injection gives

    Hom_B(L,A) -> Hom_S(I,A).

  Hence

    dim Hom_S(I,A)
      >= dim Hom_B(J_k,A)
      = N-h_k+x_k.

  Combining this with the assumed upper bound N-20 gives

    h_k-x_k>=20.
