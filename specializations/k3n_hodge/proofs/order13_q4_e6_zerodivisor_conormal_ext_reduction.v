Theorem delayed_support_Hom_Ext_sequence:
  Applying Hom_B(-,A) gives an exact sequence

    0 -> Hom_B(D_k,A)
      -> Hom_B(J_0,A)
      -> Hom_B(J_k,A)
      -> Ext^1_B(D_k,A)
      -> Ext^1_B(J_0,A).
Qed.

Define

  rho_k := dim_C ker(
             Ext^1_B(D_k,A)
               -> Ext^1_B(J_0,A)).

Corollary exact_delayed_support_conormal_identity:
  One has

    dim_C Hom_B(J_k,A)
      = dim_C Hom_B(J_0,A)
        - dim_C Hom_B(D_k,A)
        + rho_k.

Proof:
  In the preceding exact sequence, the kernel of

    Hom_B(J_0,A) -> Hom_B(J_k,A)

  is Hom_B(D_k,A), while the cokernel of that map is exactly the displayed
  kernel in Ext^1.  Taking dimensions gives the identity.
Qed.

Define the delayed-support conormal defect

  delta_k := dim_C Hom_B(D_k,A)-rho_k.

Then

  dim_C Hom_B(J_k,A)
    = dim_C Hom_B(J_0,A)-delta_k.

Thus the growing length

  length(D_k)=k*s+tau_k

cannot be charged directly against the tangent dimension: only the part of
Hom_B(D_k,A) which is not recovered by the connecting Ext^1 kernel contributes
to delta_k.

Define the ordinary-pair annihilator

