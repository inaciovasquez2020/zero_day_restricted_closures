    epsilon
      <= dim Hom_A(P,A)-dim(0:_A K).

  Combining the inequalities gives the claim.
Qed.

Interpretation:
  The first genuinely new obstruction is no longer an arbitrary Ext^1 rank.
  Positive connecting-rank excess can only be carried by the finite A-module

    P=K/(E+hB),

  equivalently by the symmetric colon quotient

    (k:h)/(D+kB).

  This module is a quotient of first Koszul homology and is unchanged at the
  level of K and M by the regularizing triangular change k->k+lambda*h.

  Therefore a dangerous low-multiplicity q=4 height-three candidate must
  produce at least six dimensions of A-dual Hom excess on this finite
  Koszul-colon carrier.

