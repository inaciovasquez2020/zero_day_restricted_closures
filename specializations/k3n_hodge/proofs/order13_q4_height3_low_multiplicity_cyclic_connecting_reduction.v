Theorem second_cut_can_also_be_chosen_regular_without_changing_the_frontier:
  Keeping h fixed, one may replace k by

    k' := k + lambda*h

  for a suitable constant lambda in C so that k' is also a nonzerodivisor on
  Cbar.

  This replacement preserves

    L=(h,k),
    D=0:_B h,
    (h:k),
    M=L/hB,

  and the connecting map

    Ann_A(D) -> Ext^1_B(M,A).

Proof:
  The associated primes of the one-dimensional Cohen--Macaulay ring Cbar are
  its finitely many minimal primes.  Since h is a nonzerodivisor, h lies in none
  of them.

  For a fixed associated prime P, the condition

    k+lambda*h in P

  excludes at most one scalar lambda.  Avoid the finite union of these bad
  scalars.  Then k' avoids every associated prime and is regular on Cbar.

  The triangular change

    (h,k) -> (h,k+lambda*h)

  is invertible and preserves L and hB, hence preserves M=L/hB and D.

  Also

    c*(k+lambda*h) in hB

  if and only if c*k in hB, so

    (h:k')=(h:k).

  Finally the short exact sequence

    0 -> hB -> L -> M -> 0

  is unchanged as an inclusion and quotient, so its connecting homomorphism is
  unchanged.
Qed.

