Theorem connecting_rank_is_bounded_by_the_colon_carrier_dual:
  One has

    sigma <= dim_C Hom_A(P,A),

  and therefore

    epsilon
      <= dim_C Hom_A(P,A)
         - dim_C(0:_A K).

Proof:
  Every connecting representative f_z factors through P.  Hence the image of
  partial inside Ext^1_B(B/K,A) is contained in the image of

    Hom_A(P,A) -> Hom_B(K,A) -> Ext^1_B(B/K,A).

  Its rank is therefore at most dim Hom_A(P,A).

  The cyclic presentation gives

    Hom_B(M,A)~=0:_A K.

  Subtract this dimension from the rank bound.
Qed.

Corollary dangerous_candidate_forces_finite_Koszul_colon_Hom_excess_six:
  If the order-13 tangent gate holds, then necessarily

    dim_C Hom_A(P,A)
      - dim_C(0:_A K)
      >= 6,

  where

    K=(h:k),
    E=0:_B k,
    P=K/(E+hB)
      ~= (k:h)/(D+kB),
    D=0:_B h,

  and both D and E lie in the finite saturation torsion T.

Proof:
  The preceding conormal-rank reduction proves that the tangent gate forces

    epsilon>=6.

