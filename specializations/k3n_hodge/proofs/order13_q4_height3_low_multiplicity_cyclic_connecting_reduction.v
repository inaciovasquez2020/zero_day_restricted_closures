Define the colon ideals

  K := (h:k) = { c in B : c*k in hB },
  J := (k:h) = { q in B : q*h in kB }.

Theorem cyclic_presentation_of_the_two_generator_quotient:
  The map

    pi : B -> M,
    pi(c) := c*k mod hB,

  is surjective with kernel K.  Hence

    M ~= B/K.

  Consequently

    Hom_B(M,A) ~= 0:_A K.

Proof:
  The class of k generates M=L/hB, so pi is surjective.  Its kernel is exactly
  the defining colon ideal K=(h:k).  This gives M~=B/K.

  A B-linear map B/K->A is determined by the image of 1, and that image must be
  killed by K.  Hence Hom_B(M,A)~=0:_A K.
Qed.

Theorem canonical_colon_transport_map:
  There is a canonical B-linear map

    q : K -> B/D

  characterized by

    c*k = q(c)*h

  in B.

  It satisfies

    ker(q)=E,
    im(q)=J/D,

  and therefore induces an isomorphism

    K/E ~= J/D.

Proof:
  If c belongs to K, then c*k lies in hB, so choose q0 in B with

    c*k=q0*h.

  Any two such q0 differ by an element of D=0:_B h.  Thus q(c):=q0 mod D is
  well defined.  B-linearity is immediate.

  If q(c)=0 in B/D, choose q0 in D.  Then

    c*k=q0*h=0,

  so c belongs to E.  Conversely c in E maps to zero.  Hence ker(q)=E.

  For c in K, the relation q0*h=c*k shows q0 in J, so im(q) is contained in
  J/D.

  Conversely if q0 belongs to J, write

    q0*h=c*k

  for some c in B.  Then c belongs to K and q(c)=q0 mod D.  Thus im(q)=J/D.
Qed.

Theorem explicit_connecting_class_from_the_cyclic_presentation:
  Under the identifications

    Hom_B(hB,A) ~= Ann_A(D),
    M ~= B/K,

  the connecting map

    partial : Ann_A(D) -> Ext^1_B(B/K,A)

  sends z in Ann_A(D) to the class represented by the B-linear map

    f_z : K -> A,
    f_z(c) := q(c)*z.

Proof:
  Multiplication by h identifies hB with B/D.  A map hB->A corresponding to z
  sends

    a*h -> a*z.

  The extension

    0 -> hB -> L -> B/K -> 0

  is the pushout of

    0 -> K -> B -> B/K -> 0

  along the map

    sigma : K -> hB,
    sigma(c)=c*k.

  Writing c*k=q(c)*h, the composite K->hB->A is exactly

    c -> q(c)*z.

  Applying Hom_B(-,A) to

    0 -> K -> B -> B/K -> 0

  identifies Ext^1_B(B/K,A) with the cokernel of

    A=Hom_B(B,A) -> Hom_B(K,A).

  Therefore the connecting class is represented by f_z as claimed.
Qed.

Define the finite colon carrier

  P := K/(E+hB).

Theorem connecting_cocycle_factors_through_the_finite_colon_carrier:
  For every z in Ann_A(D), the representative f_z vanishes on E+hB.
  Hence it factors through a B-linear map

    P -> A.

Proof:
  It vanishes on E because E=ker(q).

  For c=h*b one has

    c*k = b*h*k,

  so q(c)=b*k mod D.  Since k=0 in A=B/(h,k),

    f_z(c)=b*k*z=0.

  Thus f_z vanishes on E+hB.
Qed.

Theorem P_is_an_A_module:
  The ideal L=(h,k) annihilates P.  Hence P is naturally an A=B/L module and

    Hom_B(P,A)=Hom_A(P,A).

Proof:
  Multiplication by h sends K into hB, so h kills P.

  If c belongs to K, then c*k belongs to hB by definition of K.  Thus k also
  kills the class of c in P.  Therefore L kills P.
Qed.

Theorem symmetric_colon_description_of_P:
  The transport map q induces an A-linear isomorphism

    P ~= J/(D+kB).

Proof:
  The map q already induces K/E ~= J/D.

  Under this isomorphism the image of hB is

    (kB+D)/D,

  because

    q(h*b)=b*k mod D.

  Therefore quotienting K/E by the image of hB gives

    K/(E+hB)
      ~= (J/D)/((kB+D)/D)
      ~= J/(D+kB).

  Both sides are killed by h and k, so the isomorphism is A-linear.
Qed.

Let

  H1 := H_1(h,k;B)

be first Koszul homology.

Theorem colon_carrier_is_a_quotient_of_first_Koszul_homology:
  There is an exact sequence

    0 -> D/kD
      -> H1
      -> K/hB
      -> 0.

  Consequently P is a quotient of H1.

Proof:
  A Koszul one-cycle is a pair (a,b) with

    a*h+b*k=0.

  Its second coordinate b lies in K.  Sending its homology class to

    b mod hB

  is well defined because a Koszul boundary changes b by a multiple of h.
  Every b in K lifts to a cycle by choosing q with b*k=q*h and taking

    (-q,b), so the map is surjective.

  If b lies in hB, write b=c*h.  Then

    (a+c*k)*h=0,

  so d:=a+c*k lies in D.  Modulo the Koszul boundary determined by c, the cycle
  is represented by (d,0).

  Two such representatives differ by a boundary with second coordinate zero
  exactly when the boundary parameter lies in D; the first coordinate then
  changes by an element of kD.  Thus the kernel is D/kD.

  Finally P is the further quotient of K/hB by the image of E, so P is a
  quotient of H1.
Qed.

