Theorem quadratic_colon_saturates_after_one_parameter_step:
  One has

    G:ell=Gsat,

  and therefore

    G:ell^j=Gsat

  for every j>=1.

Proof:
  First Gsat is proper.  Choose a minimal prime P containing a.  Since
  K_0=(a,b) is m-primary, b is not in P, so

    G_P=(a:b)_P=(a)_P

  is proper.  The parameter ell is a unit after localization at P, hence
  saturation does not change this localization and Gsat is proper.

  Now let x in (Gsat)_n with n>=2.  Choose m such that

    ell^m*x*b=a*c.

  Here c has degree n+m.  Multiplication by ell^m is an isomorphism from C_n
  to C_(n+m), so c=ell^m*c0 for a unique c0 in C_n.  Cancel ell^m to obtain

    x*b=a*c0,

  hence x belongs to G.  Thus Gsat/G is concentrated in degree one; degree zero
  is absent because Gsat is proper.  Multiplying a degree-one saturation class
  by ell lands in degree two, where Gsat and G agree.  Therefore

    ell*Gsat subseteq G,

  which is equivalent to G:ell=Gsat.
Qed.

