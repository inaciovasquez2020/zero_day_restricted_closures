Theorem quadratic_baseline_deficit_is_at_most_twelve:
  One has

    eta_0<=12.

Proof:
  Since K_0=(a,b) is m-primary in the one-dimensional Cohen--Macaulay ring C,
  a general constant combination

    q0:=a+lambda*b

  is a quadratic nonzerodivisor on C.  Choose a homogeneous lift to B.

  Any element killed by q0 in B maps to an element killed by q0 in C, hence
  lies in T.  Therefore

    length_C(0:_B q0)<=length_C(T)=4.

  Multiplication by the quadratic q0 on the one-dimensional ring B gives

    length_C(B/q0*B)
      =2*e(B)+length_C(0:_B q0)
      <=8+4
      =12.

  Since q0 belongs to K_0,

    0:_X K_0 subseteq 0:_A q0.

  On the finite-dimensional algebra A, kernel and cokernel of multiplication
  by q0 have equal dimension.  Hence

    dim_C(0:_A q0)=length_C(A/q0*A)<=length_C(B/q0*B)<=12.

  Apply the multiplication bound at i=0.
Qed.

