    c*ell^(i-1)*b=p*a+q*ell^i*b

  for some p,q.  Hence

    (c-q*ell)*ell^(i-1)*b belongs to (a),

  which gives c in (G:ell^(i-1),ell).  The reverse inclusion is immediate.
Qed.

