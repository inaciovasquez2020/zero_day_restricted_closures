Theorem natural_torsion_to_action_quotient_has_only_two_forms:
  Let

    pi:T -> Z=B/J

  be the map obtained by including T in B and then quotienting by J.

  Under graded B-module identifications

    T ~= Z(-1),
    Z ~= C[z]/(z^3),

  exactly one of the following holds:

    ZERO_SELF_ACTION:
      pi=0,
      ker(pi)=T;

    NONZERO_SELF_ACTION:
      pi is multiplication by a nonzero scalar multiple of z,
      ker(pi)=T_3.

Proof:
  By definition J=Ann_B(T), so the B-action on T factors through Z.  The target
  Z is also a Z-module in the evident way.  Hence pi is a graded Z-linear map

    Z(-1) -> Z

  of degree zero.

  Such a map is determined by the image of the degree-one generator of Z(-1),
  and that image must lie in

    Z_1=C*z.

  Therefore pi is either zero or multiplication by lambda*z for some nonzero
  lambda in C.

  In the nonzero case, multiplication by z on

    Z=C[z]/(z^3)

  has kernel the top line C*z^2.  Under the shift T~=Z(-1), this is exactly the
  degree-three line T_3.
Qed.

