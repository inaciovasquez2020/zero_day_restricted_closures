Theorem choose_a_regular_quadratic_combination_inside_the_first_delayed_cubic:
  There exists lambda in C such that

    q0:=a+lambda*b

  is a nonzerodivisor on Cbar.

  For such a choice put

    q:=ell*q0.

  Then q is a homogeneous degree-three nonzerodivisor on Cbar and

    q belongs to K_1=(a,ell*b).

Proof:
  Since K_0=(a,b) is m-primary in the one-dimensional Cohen--Macaulay ring
  Cbar, its two-dimensional C-linear span is not contained in any associated
  prime.  The associated primes are the finitely many minimal primes of Cbar.
  Over C, a general constant combination a+lambda*b therefore avoids all of
  them and is a nonzerodivisor.

  The parameter ell is also a nonzerodivisor, so their product q is regular on
  Cbar.

  Finally

    q=ell*a+lambda*ell*b

  lies in the ideal generated by a and ell*b, namely K_1.
Qed.

