Theorem exact_regular_cubic_section_of_J_has_length_sixteen:
  One has

    length_C(J/qJ)=16.

Proof:
  The quotient B/J has finite length three.  Therefore J and B have the same
  one-dimensional multiplicity,

    e(J)=e(B)=5.

  Multiplication by the degree-three element q on J gives an exact sequence

    0 -> (0:_J q)(-3)
      -> J(-3)
      --q--> J
      -> J/qJ
      -> 0.

  The cokernel has finite length because q is regular on the saturated core.
  Taking the value at t=1 of the Hilbert-series identity gives

    length_C(J/qJ)
      =3*e(J)+length_C(0:_J q)
      =3*5+1
      =16.
Qed.

