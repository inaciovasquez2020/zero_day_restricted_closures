2. HILBERT NUMERATOR FROM A REGULAR LINEAR FORM
--------------------------------------------------------------------------

Choose a linear nonzerodivisor h on the one-dimensional Cohen--Macaulay module
D and put

  E:=D/hD.

Then E has finite length and, because D is generated in degree one, E is also
generated in degree one.

Theorem residual_Hilbert_series_is_the_Artinian_reduction_numerator:
  One has

    Hilb_D(t)=Hilb_E(t)/(1-t).

  Moreover

    dim E_1 = dim D_1 = 2-u1,

    dim E_2 = dim D_2-dim D_1
            = (5-u2)-(2-u1)
            = 3+u1-u2.

Proof:
  Since h is D-regular there is an exact sequence

    0 -> D(-1) --times h--> D -> E -> 0.

  Taking Hilbert series gives

    Hilb_E(t)=(1-t)Hilb_D(t).

  Because D_0=0, the degree-one identity is immediate.  The degree-two identity
  is the first difference of the Hilbert function.
Qed.

Corollary the_second_numerator_coefficient_is_small:
  The exact possibilities are

    u1=0:
      u2 in {2,3},
      dim E_2 in {1,0};

    u1=1:
      u2 in {2,3,4},
      dim E_2 in {2,1,0}.

Proof:
  The lower bound u2>=2 follows from Q_2 subset (Qsat)_2 and the four-dimensional
  space Q_2 of independent quadrics.  Combine this with u2<=3+u1 and the formula
  dim E_2=3+u1-u2.
Qed.

