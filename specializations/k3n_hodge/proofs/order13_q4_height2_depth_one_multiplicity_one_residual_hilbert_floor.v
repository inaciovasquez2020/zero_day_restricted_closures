3. ONCE THE ARTIAN REDUCTION VANISHES, IT STAYS ZERO
--------------------------------------------------------------------------

Theorem zero_in_one_degree_forces_zero_in_all_later_degrees:
  If E_n=0 for some n>=1, then E_m=0 for every m>=n.

Proof:
  The module E is generated in degree one.  Therefore every degree m>1 is
  obtained by multiplying lower-degree elements by positive-degree elements of
  S.  If E_n=0, then

    E_(n+1)=S_1 E_n=0,

  and induction gives all later vanishing.
Qed.

This elementary point makes the cases with dim E_2=0 exact rather than merely
lower bounds.

