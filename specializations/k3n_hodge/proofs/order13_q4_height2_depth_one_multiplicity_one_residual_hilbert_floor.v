5. LOWER ENVELOPE FOR L0 WITH u2=2
--------------------------------------------------------------------------

Theorem L0_u2_2_Hilbert_floor:
  If

    u1=0,
    u2=2,

  then

    Hilb_E(t)=2*t+t^2+sum_{n>=3} a_n t^n

  with every a_n>=0.  Hence coefficientwise

    Hilb_D(t) >= (2*t+t^2)/(1-t).

Proof:
  The exact low-degree formulas give

    dim E_1=2,
    dim E_2=1.

  All later Artinian-reduction dimensions are nonnegative.  Dividing by 1-t
  gives the coefficientwise Hilbert-series floor.
Qed.

IMPORTANT_NONCONCLUSION_L0_u2_2:
  No claim is made here that all higher a_n vanish.  Thus the displayed floor
  is the smallest Hilbert numerator allowed by the current information, not an
  existence or classification theorem.

