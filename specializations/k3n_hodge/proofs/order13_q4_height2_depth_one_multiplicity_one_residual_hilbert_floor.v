1. THE RESIDUAL MODULE IS GENERATED IN DEGREE ONE
--------------------------------------------------------------------------

Theorem residual_module_is_generated_in_degree_one:
  The graded S-module D=P/Qsat is generated by D_1.

Proof:
  The linear prime P=(l1,l2) is generated by its degree-one part.  Since D is a
  quotient of P, the images of l1,l2 generate D.  Any linear member of Qsat
  simply removes the corresponding degree-one generator.  Hence D is generated
  by D_1.
Qed.

Corollary minimal_number_of_residual_generators:
  The minimal number of degree-one generators is

    dim_C D_1 = 2-u1.

  Thus

    u1=0  =>  D has two degree-one generators,
    u1=1  =>  D has one degree-one generator.
Qed.

