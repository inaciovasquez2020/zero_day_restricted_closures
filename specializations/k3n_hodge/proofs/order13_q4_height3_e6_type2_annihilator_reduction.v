Theorem artin_reduction_has_socle_exactly_degree_two:
  The socle of H is exactly H_2, hence

    dim_C Soc(H)=2.

Proof:
  Since H_n=0 for n>=3,

    H_2 subseteq Soc(H).

  It remains to rule out a nonzero degree-one socle element.

  Write H=P/J with P=C[u,v,w].  The four quadratic generators of Q descend to four independent quadrics generating J, because

    dim P_2=6,
    dim H_2=2,

  so dim J_2=4.

  Suppose 0 != x in H_1 lies in Soc(H).  After a linear coordinate change take x to be the image of u.  Then

    u^2, u*v, u*w in J_2.

  Since J_2 has dimension four, modulo (u) the image of J is generated by at most one quadratic form in C[v,w].  Therefore

    C[v,w]/(J+(u))/(u)

  is a quotient of a two-variable polynomial ring by at most one nonzero equation and cannot be Artinian.

  But H/(u) is a quotient of the Artin algebra H, hence must be Artinian.  Contradiction.

  Thus Soc(H)_1=0, while H_2 is entirely socle.  Therefore Soc(H)=H_2 and has dimension two.
Qed.

