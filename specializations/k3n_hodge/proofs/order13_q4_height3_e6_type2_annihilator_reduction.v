Theorem multiplicity_six_core_has_forced_h_vector_132:
  Let ell in B_1 be a general linear nonzerodivisor and set

    H := B/(ell).

  Then H is an Artin standard graded C-algebra with Hilbert function

    (1,3,2)

  and zero in every degree >=3.

Proof:
  Since Q has no linear forms and has exactly four independent quadratic generators,

    dim B_0 = 1,
    dim B_1 = 4,
    dim B_2 = dim S_2 - 4 = 10-4 = 6.

  Because ell is B-regular of degree one,

    Hilb_H(n)=Hilb_B(n)-Hilb_B(n-1).

  Hence

    dim H_0=1,
    dim H_1=4-1=3,
    dim H_2=6-4=2.

  For a one-dimensional standard graded Cohen--Macaulay algebra, the multiplicity equals the total length of a linear Artin reduction.  Here

    length(H)=e(B)=6.

  The already determined pieces have total dimension

    1+3+2=6.

  Therefore all higher graded pieces vanish.
Qed.

Corollary multiplicity_six_core_has_forced_Hilbert_series:
