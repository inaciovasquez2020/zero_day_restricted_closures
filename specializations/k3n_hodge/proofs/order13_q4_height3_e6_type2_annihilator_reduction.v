Theorem multiplicity_six_core_has_forced_minimal_resolution:
  The minimal graded S-free resolution of B is

    0 -> S(-5)^2
      -> S(-3)^2 + S(-4)^3
      -> S(-2)^4
      -> S
      -> B
      -> 0.

Proof:
  From the forced Hilbert series,

    Hilb_B(t)
      = (1+3*t+2*t^2)/(1-t)
      = P(t)/(1-t)^4,

  where

    P(t)
      = (1-t)^3*(1+3*t+2*t^2)
      = 1 - 4*t^2 + 2*t^3 + 3*t^4 - 2*t^5.

  The first free module is S(-2)^4 because Q is minimally generated by four quadrics.

  Since B is one-dimensional Cohen--Macaulay in a four-variable polynomial ring, its projective dimension is three.  Its type is two, so the last free module has total rank two.

  The h-polynomial has degree two, hence reg(B)=2.  Therefore a summand S(-j) in homological degree i satisfies j-i<=2.

  Comparing the alternating Betti numerator degree by degree gives

    beta_(2,3)=2.

  The coefficient -2 at degree five, together with reg(B)=2, forces

    beta_(3,5)=2.

  Since the total third Betti number is already two, there are no other third-syzygy summands.  The degree-four coefficient then forces

    beta_(2,4)=3.

  This gives exactly the displayed resolution.
Qed.

