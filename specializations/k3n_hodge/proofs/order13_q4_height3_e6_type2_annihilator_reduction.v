Theorem regular_parameter_cut_preserves_type_two:
  C0 is an Artin local Cohen--Macaulay ring of type two:

    dim_C Soc(C0)=2.

Proof:
  Quotient by a nonzerodivisor preserves Cohen--Macaulay type.  Since type(B_m)=2, one has type(C0)=2.  For an Artin local ring, type equals socle dimension.
Qed.

Theorem annihilator_module_has_socle_dimension_two:
  As an A-module,

    Soc_A(D)=Soc(C0).

  Consequently

    dim_C Soc_A(D)=2.

Proof:
  Because g lies in the maximal ideal of C0, every element of Soc(C0) is killed by g, so

    Soc(C0) subseteq D.

  The maximal ideal of A is m_(C0)/(g).  For d in D, the condition

    m_A*d=0

  is equivalent to

    m_(C0)*d=0,

  because g*d=0 already holds by definition of D.  Thus the A-socle of D is exactly the C0-socle.
Qed.

Theorem dual_annihilator_module_is_at_most_two_generated:
  Let

    omega_C0 := Hom_C(C0,C)

  be the canonical module of the Artin local ring C0, and let D^vee:=Hom_C(D,C).

  Then

    D^vee ~= omega_C0 / g*omega_C0.

  In particular

    mu_A(D^vee) <= 2.

Proof:
  Dualize the exact multiplication sequence

    0 -> D -> C0 --g--> C0 -> A -> 0

  over C.  Since vector-space duality is exact, one obtains

    0 -> A^vee -> omega_C0 --g--> omega_C0 -> D^vee -> 0.

  Hence D^vee is the stated cokernel.

  The minimal number of generators of omega_C0 equals type(C0)=2.  Passing to the quotient by g cannot increase the number of generators, so D^vee is at most two-generated over A.
Qed.

Theorem cyclic_annihilator_module_cannot_be_dangerous:
  If D is cyclic as an A-module, then

    D ~= A

  and therefore

    dim_C Hom_A(D,A)=N.

  Hence a cyclic D cannot satisfy the necessary dangerous inequality

    dim_C Hom_A(D,A) >= N+20.

Proof:
  A cyclic A-module D is a quotient of A.  Since

    length(D)=length(A)=N,

  the quotient map has zero-length kernel and is therefore an isomorphism.

  Thus

    Hom_A(D,A) ~= Hom_A(A,A) ~= A,

  whose C-dimension is N.
Qed.

