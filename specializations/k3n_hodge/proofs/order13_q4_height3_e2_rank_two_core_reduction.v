The purpose of this file is to classify that rank-two core, sharpen its finite
saturation-torsion budget, close the subcase in which only one final generator
is active on the saturated core, and reduce the two-core-active case to two
explicit normal forms.  It does NOT close the whole e=2 branch.

Theorem multiplicity_two_saturated_core_is_a_quadratic_rank_two_algebra:
  Choose a homogeneous degree-one lift u in Cbar_1 of the nontrivial basis
  element of Cbar/ell*Cbar.  Then Cbar is generated as a graded C-algebra by
  ell and u, and there are constants a,b in C such that

    Cbar ~= C[ell,u]/(u^2-b*ell*u-a*ell^2).

Proof:
  The C[ell]-module profile gives

    Cbar_n = C*ell^n direct_sum C*ell^(n-1)*u

  for every n>=1.  In particular ell and u generate Cbar as an algebra.

  Since u^2 has degree two, there are unique constants a,b with

    u^2=a*ell^2+b*ell*u.

  This gives a graded surjection

    C[ell,u]/(u^2-b*ell*u-a*ell^2) -> Cbar.

  The source is free of rank two over C[ell] with basis 1,u, exactly as Cbar is.
  The surjection therefore has zero kernel and is an isomorphism.
Qed.

Corollary only_split_or_double_line_core_occurs:
  After replacing

    v:=u-(b/2)*ell,

  there is a constant Delta in C with

    Cbar ~= C[ell,v]/(v^2-Delta*ell^2).

  Because C is algebraically closed, exactly the following two algebra types
  occur:

    REDUCED_SPLIT:
      Cbar ~= C[x,y]/(x*y).

    DOUBLE_LINE:
      Cbar ~= C[ell,v]/(v^2).

Proof:
  Completing the square gives the displayed relation.

  If Delta=0 this is the double-line algebra.

  If Delta is nonzero, choose c in C with c^2=Delta and put

    x:=v-c*ell,
    y:=v+c*ell.

  Then x*y=0, while ell and v are C-linear combinations of x and y.  Hence the
  algebra is C[x,y]/(xy).
Qed.

