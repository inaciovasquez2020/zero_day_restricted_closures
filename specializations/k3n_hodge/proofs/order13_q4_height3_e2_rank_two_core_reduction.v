Theorem multiplicity_two_degree_three_torsion_has_dimension_at_most_four:
  One has

    dim_C T_3<=4.

Proof:
  Since dim Cbar_3=2 and dim R_3=8,

    dim Jsat_3=6.

  The ordinary degree-three piece is

    J_3=a*R_1.

  On X, multiplication by the quadratic section a gives a map

    H^0(X,O_X(1)) -> H^0(X,O_X(3)).

  Its cokernel is H^0(Y,O_Y(3)), where

    Y:=Proj(Cbar)

  has length two.  Source and target both have dimension eight, so the kernel
  has dimension two.

  The natural map R_1->H^0(X,O_X(1)) is injective because R is
  one-dimensional Cohen--Macaulay.  Hence the kernel of

    a:R_1->R_3

  has dimension at most two.  Since dim R_1=4,

    dim J_3>=2.

  Therefore

    dim T_3=dim(Jsat_3/J_3)<=6-2=4.
Qed.

