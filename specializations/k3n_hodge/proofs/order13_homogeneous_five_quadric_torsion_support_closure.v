ExternalResult GenericQuadraticRegularSequence:
  Over the infinite field C, a homogeneous height-three ideal generated by quadrics contains three C-linear combinations of its quadratic generators forming a regular sequence.

Theorem complete_intersection_section_model:
  After changing the five-dimensional basis Q_2, choose quadrics

    q1,q2,q3,a,b

  generating Q such that

    K := (q1,q2,q3)

  is a regular sequence.

  Set

    R := S/K,
    J := (a,b)R.

  Then

    B = R/J,

  and X:=Proj(R) is a zero-dimensional complete intersection of three quadrics in P^3 of length

    deg(X)=2^3=8.
Qed.

Theorem complete_intersection_sections_stabilize_in_degree_three:
  For every integer n,

    dim_C H^0(X,O_X(n)) = 8.

  The complete-intersection Hilbert series is

    Hilb_R(t)
      = (1-t^2)^3/(1-t)^4
      = (1+t)^3/(1-t).

  Hence

    dim R_0=1,
    dim R_1=4,
    dim R_2=7,
    dim R_n=8 for every n>=3.

  Since R is one-dimensional Cohen--Macaulay, H^0_m(R)=0, so the natural maps

    R_n -> H^0(X,O_X(n))

  are injective.  Dimension equality therefore makes them isomorphisms for all n>=3.
Qed.

Theorem five_quadric_saturation_defect_vanishes_from_degree_five:
  Let

    Jsat := saturation of J in R,

  so that

    T = Jsat/J = Qsat/Q.

  Then

    T_n = 0

  for every n>=5.

Proof:
  Let F be the kernel of the sheaf surjection on X

    O_X(-2)^2 -> J~ -> 0

  induced by the two quadratic generators a,b.

  Because X is zero-dimensional, every coherent sheaf on X has vanishing H^1.  Thus after twisting by n and taking global sections,

    H^0(X,O_X(n-2))^2 -> H^0(X,J~(n))

  is surjective for every n.

  Fix n>=5.  Then both n and n-2 are at least three.  By the preceding theorem,

    R_n ~= H^0(X,O_X(n)),
    R_(n-2) ~= H^0(X,O_X(n-2)).

  Under these identifications, the degree-n part

    J_n = a R_(n-2) + b R_(n-2)

  is exactly the full section space H^0(X,J~(n)), which is the degree-n component of Jsat inside R_n.

  Therefore

    J_n = Jsat_n,

  so

    T_n=(Jsat/J)_n=0

  for every n>=5.
Qed.

Corollary saturation_torsion_has_Loewy_length_at_most_four:
  Since Qsat is proper, T_0=0.  Together with T_n=0 for n>=5, every homogeneous element of T has degree in {1,2,3,4}.

  Hence multiplication by any degree-four element sends T into degrees at least five, where T vanishes.  Therefore

    m^4 T = 0.
Qed.

Corollary colon_defect_is_annihilated_by_m4:
  From the preceding saturation reduction, f is regular on B/T, hence

    D=0:_B f = 0:_T f subseteq T.

  Therefore

    m^4 D = 0.

  Because fD=0 by definition, D is naturally an A=B/(f)-module, and

    m_A^4 subseteq Ann_A(D).
Qed.

Theorem maps_killing_Q_contain_AnnD:
  The S-linear maps I->A that vanish on Q identify with

    Hom_B((f),A).

  Since multiplication by f gives

    (f) ~= B/D,

  one has

    Hom_B((f),A)
      ~= Hom_B(B/D,A)
      ~= Ann_A(D).

  Consequently

    dim Hom_S(I,A) >= dim Ann_A(D).
Qed.

ExternalResult MacaulayGrowthAtFive:
  If H is the Hilbert function of a standard graded algebra and H(2)=5, then Macaulay's growth theorem gives

    H(3) <= 5^{<2>} = 7,

  because

    5 = binom(3,2)+binom(2,1)

  and therefore

    5^{<2>} = binom(4,3)+binom(3,2)=7.

Theorem fourth_power_annihilator_has_codimension_at_most_seventeen:
  In the homogeneous q=5 branch,

    dim A_0 = 1,
    dim A_1 = 4,
    dim A_2 = 10-5 = 5.

  MacaulayGrowthAtFive gives

    dim A_3 <= 7.

  Hence

    length(A/m_A^4)
      = dim A_0 + dim A_1 + dim A_2 + dim A_3
      <= 1+4+5+7
      = 17.

  Since m_A^4 subseteq Ann_A(D), there is a quotient map

    A/m_A^4 -> A/Ann_A(D).

  Therefore

    length(A/Ann_A(D)) <=17,

  and hence

    dim Ann_A(D)
      = N - length(A/Ann_A(D))
      >= N-17.
Qed.

