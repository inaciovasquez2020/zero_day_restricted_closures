5. TYPE B CANNOT HAVE FINITE RAO MODULE
--------------------------------------------------------------------------

Assume

    Q=x*A+(q),
    A:=(a1,a2,a3),
    q in A \ (x).

Theorem type_B_has_a_projective_embedded_associated_prime:
  The height-three linear prime A is associated to S/Q and remains visible
  after saturation.

Proof:
  Since q is not divisible by x, gcd(x,q)=1 in the polynomial ring S.

  We claim

    (Q:x)=A.

  Certainly A subset (Q:x).  Conversely, if r*x belongs to x*A+(q), write

    r*x=x*a+q*b

  with a in A.  Then

    x*(r-a)=q*b.

  Coprimality of x and q forces x to divide b, say b=x*c.  Therefore

    r-a=q*c belongs to A

  because q belongs to A.  Hence r belongs to A, proving the colon equality.

  Thus A is the annihilator of the nonzero class of x in S/Q and is an
  associated prime.

  The prime A has height three and is not the irrelevant maximal ideal m.
  Saturation changes Q only at m, so localization at A is unchanged:

    (Qsat)_A=Q_A.

  Hence A remains an associated prime of S/Qsat on the punctured spectrum.
Qed.

Corollary type_B_has_nonfinite_H1:
  Type B is incompatible with finite length of

    H^1_m(S/Qsat).

Proof:
  The saturated ring C0=S/Qsat has dimension two and has a nonmaximal
  associated prime A at which depth is zero.  Therefore C0 is not
  Cohen--Macaulay on the punctured spectrum.

  But if H^0_m(C0)=0 and H^1_m(C0) had finite length, the external generalized
  Cohen--Macaulay result would force Cohen--Macaulayness at every homogeneous
  nonmaximal localization.  Contradiction.
Qed.

Thus Type B cannot occur in any finite Rao stratum, in particular not when

    dim_C M=2.

