4. TYPE A2 ALSO HAS RAO LENGTH ONE
--------------------------------------------------------------------------

Assume now

    Q=(x^2,xy,y^2,xz+yw)

with x,y,z,w independent linear forms.

Put

    R:=C[z,w].

Theorem type_A2_is_saturated_depth_one_with_Rao_length_one:
  The ideal Q is saturated, S/Q has depth one, and

    H^1_m(S/Q) ~= C

  concentrated in degree zero.

Proof:
  The multiplicity-two classification identifies this ideal with its unmixed
  part.  Hence it has no embedded maximal-ideal associated component and is
  saturated.

  Because x^2=xy=y^2=0 in S/Q, every class has a unique expression consisting
  of an R-part plus an R-linear x,y-part, subject only to

    z*x+w*y=0.

  Therefore as a graded R-module

    S/Q ~= R direct_sum N,

  where N has presentation

    0 -> R(-2)
      --(z,w)^T-->
      R(-1)^2
      -> N
      -> 0.

  The R-linear map

    R(-1)^2 -> R,
    (a,b) |-> -w*a+z*b

  has image (z,w) and kernel generated by (z,w).  Hence

    N ~= (z,w) subset R.

  Thus

    S/Q ~= R direct_sum (z,w)

  as graded R-modules.

  From

    0 -> (z,w) -> R -> C -> 0

  and depth(R)=2, local cohomology gives

    H^1_(z,w)((z,w)) ~= C

  in degree zero, while H^1_(z,w)(R)=0.  Since S/Q is finite over R, this is
  the same irrelevant-support local cohomology calculation for S/Q.  Hence

    H^1_m(S/Q) ~= C.

  In particular depth(S/Q)=1 and the Rao module has C-dimension one.
Qed.

Corollary type_A2_is_not_length_two_deficiency:
  Type A2 cannot occur when dim_C M=2.
Qed.

