Theorem final_high_degree_pair_kills_and_does_not_intersect_T:
  Put

    L:=(f,g)B.

  Then

    L*T=0,
    L intersect T=0.

Proof:
  The torsion T is supported only in degrees one and two, while f and g have
  degree at least three.  Thus multiplication by either generator sends every
  homogeneous component of T beyond its support, so L*T=0.

  Also every nonzero homogeneous element of L has degree at least three,
  whereas T has no component in degree at least three.  Hence L intersect T=0.
Qed.

Corollary exact_conic_annihilator_inside_A:
  The torsion T embeds into A=B/L, and

    dim_C Ann_A(T)=N-2.

Proof:
