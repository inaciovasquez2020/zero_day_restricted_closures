Theorem the_CM_core_has_a_linear_saturation_equation:
  One has

    (Qsat)_1 != 0.

Proof:
  Suppose (Qsat)_1=0.  Then

    dim C_0=1,
    dim C_1=4.

  Choose a general linear regular sequence ell1,ell2 on C and put

    H:=C/(ell1,ell2).

  Hilbert-series multiplication by (1-t)^2 gives

    dim H_0=1,
    dim H_1=dim C_1-2*dim C_0=2.

  Hence length(H)>=3.  Since length(H)=e(C)<=3, equality holds and

    Hilb_H(t)=1+2*t.

  Therefore

    Hilb_C(t)=(1+2*t)/(1-t)^2,

  whose degree-two coefficient is seven.  Thus dim C_2=7.

  But C is a quotient of B and the established initial height-two profile gives

    dim B_2=6.

  This is impossible.  Hence (Qsat)_1 is nonzero.
Qed.

Corollary the_CM_core_is_line_or_plane_hypersurface:
  Put

    u1:=dim_C (Qsat)_1.

  Then u1 is either one or two.

  If u1=2, then

    C ~= C[s,t]

  and e(C)=1.

  If u1=1, then after a linear change of coordinates

    Qsat=(l,F)

  with l linear and F homogeneous of degree r in S/(l), where

    r=e(C) in {2,3}.

Proof:
  The preceding profile already proves u1<=2 and proves that u1=2 forces the
  line core C~=C[s,t].

  Now assume u1=1 and choose a generator l.  Modulo l, write

    P:=S/(l) ~= C[y1,y2,y3].

  The image H of Qsat in P has height one, and

    P/H ~= C

  is Cohen--Macaulay of dimension two.  By the external grade-one result,

    H=(F)

  is principal.  Since u1 is exactly one, deg(F)>=2.  The multiplicity of the
  plane hypersurface P/(F) is deg(F), and the previous profile gives e(C)<=3.
  Hence deg(F) is two or three.
Qed.

Theorem the_plane_cubic_CM_core_is_incompatible_with_htQ_two:
  The case

    Qsat=(l,F_3)

  with F_3 cubic cannot occur.

Proof:
  In degree two the cubic contributes nothing, so

    (Qsat)_2=l*S_1.

  This space has dimension four.  Since Q_2 is also four-dimensional and

    Q_2 subseteq (Qsat)_2,

  one has

    Q_2=l*S_1.

  Because Q is generated by Q_2,

    Q=l*m.

  The prime (l) contains Q, so ht(Q)<=1, contradicting ht(Q)=2.
Qed.

