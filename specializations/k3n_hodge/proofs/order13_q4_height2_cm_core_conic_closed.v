Theorem plane_conic_CM_core_violates_the_order13_tangent_gate:
  One has

    dim_C Hom_S(I,A) >= N-2.

  Hence the necessary order-13 tangent condition

    dim_C Hom_S(I,A) <= N-20

  is impossible.

Proof:
  From

    0 -> fB -> L -> M -> 0,

  applying Hom_B(-,A) gives an injection

    Hom_B(M,A) -> Hom_B(L,A).

  Maps L->A define maps I->A vanishing on Q, so Hom_B(L,A) is a natural
  subspace of Hom_S(I,A).  Therefore

    dim Hom_S(I,A)
      >= dim Hom_B(L,A)
      >= dim Hom_B(M,A)
      = N-2.

  Since N-2>N-20, the tangent gate fails.
Qed.

