Theorem exact_four_quadric_normal_form_for_the_conic_core:
  There is a three-dimensional subspace W subset S_1 and a quadratic

    q' = q + l*r

  defining the same saturated ideal (l,q')=(l,q), such that

    Q=(q', l*W).

Proof:
  The degree-two space of Qsat is

    (Qsat)_2=l*S_1 direct_sum C*q

  and has dimension five.

  The four-dimensional subspace Q_2 cannot equal l*S_1, because that would
  again give Q=l*m of height at most one.  Therefore

    dim(Q_2 intersect l*S_1)=3.

  Write this intersection as l*W with dim W=3.  Choose any element of Q_2
  outside l*S_1 and scale it to have q-coefficient one; it has the form

    q'=q+l*r.

  Then q' together with l*W is a basis of Q_2.  Since Q is generated by Q_2,

    Q=(q',l*W).
Qed.

Theorem exact_conic_saturation_torsion:
  One has

    T ~= S/(W,q')(-1),

  and

    Hilb_T(t)=t+t^2,
    length_C(T)=2,
    m^2*T=0.

Proof:
  Since q' already belongs to Q, the quotient

    T=Qsat/Q=(l,q')/(q',l*W)

  is cyclic, generated by the class of l.

  Its annihilator in S is Q:l.  Because q' is not divisible by l,

    (q',l*W):l=(q',W).

  Hence

    T ~= S/(W,q')(-1).

  The subspace W consists of three independent linear forms, so S/W is a
  polynomial ring C[z] in one variable.  The module T is finite length because
  Qsat/Q is a saturation defect.  Therefore q' has nonzero image modulo W.
  Being quadratic, that image is a nonzero scalar multiple of z^2.  Thus

    S/(W,q') ~= C[z]/(z^2),

  proving all assertions.
Qed.

