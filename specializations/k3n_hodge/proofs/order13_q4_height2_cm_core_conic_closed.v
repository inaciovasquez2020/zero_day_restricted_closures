Theorem exact_conic_colon_for_the_final_parameter_pair:
  In B,

    (fB : g)=fB+T.

Proof:
  Modulo T the ring is the Cohen--Macaulay conic core C, and fbar,gbar form a
  parameter pair.  Hence they are a regular sequence and

    (fbar : gbar)=(fbar)

  in C.

  If x*g belongs to fB, then modulo T one has

    xbar*gbar in fbar*C,

  so xbar belongs to fbar*C.  Thus x=f*y+t for some t in T.  Conversely every
  such element belongs to the colon because g*T=0.  Therefore

    (fB:g)=fB+T.
Qed.

