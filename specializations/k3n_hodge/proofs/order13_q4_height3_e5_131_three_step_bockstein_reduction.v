Lemma exact_layer_annihilator:
  The class

    t_i:=ell^(i-1)*beta mod J_i

  generates W_i and has annihilator

    Ann_Cbar(t_i)=(H:ell^(i-1),ell).

  In particular, for every i>=4,

    W_i ~= Cbar/(Hsat,ell)

  up to grading shift.

Proof:
  The generator statement is immediate from

    J_(i-1)=(alpha,ell^(i-1)*beta).

  If c*t_i=0, then

    c*ell^(i-1)*beta
      =u*alpha+v*ell^i*beta

  for some u,v.  Therefore

    (c-v*ell)*ell^(i-1)*beta belongs to (alpha),

  so

    c-v*ell belongs to
      (alpha:ell^(i-1)*beta)
      =H:ell^(i-1).

  This proves one containment in the annihilator formula; the reverse
  containment is immediate.  For i>=4, the preceding theorem gives

    H:ell^(i-1)=Hsat.
Qed.

