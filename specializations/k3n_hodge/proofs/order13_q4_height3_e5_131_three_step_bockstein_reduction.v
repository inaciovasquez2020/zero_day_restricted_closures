Theorem socle_line_torsion_does_not_meet_the_final_cut_ideal:
  Put

    L:=(f,g)B.

  Then

    L*T=0,
    L intersect T=0.

Proof:
  Both final generators have degree at least three, while m_B*T=0, so L*T=0.

  The ideal L is homogeneous and has no component in degrees below three.
  The module T is concentrated entirely in degree two.  Hence their
  intersection is zero.
Qed.

Corollary both_final_generators_are_core_active:
  The images fbar and gbar in Cbar are both nonzero.

Proof:
  If, for example, fbar=0, then f belongs to T.  But deg(f)>=3 while T has only
  degree two, forcing f=0, contradicting minimality of the final generator.
  The argument for g is identical.
Qed.

