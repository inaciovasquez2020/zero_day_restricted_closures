Theorem every_layer_from_four_on_has_nonpositive_Bockstein_defect:
  For every i>=4,

    Delta_i<=0.

Proof:
  Fix i>=4.  The exact layer-annihilator theorem gives

    W_i~=Cbar/I,
    I:=(Hsat,ell),

  up to grading shift.  Put

    N_H:=0:_X Hsat.

  For y in N_H define

    phi_y:J_i->X

  by

    phi_y(alpha)=0,
    phi_y(ell^i*beta)=y.

  This is well defined: a relation

    u*alpha+v*ell^i*beta=0

  forces

    v in (alpha:ell^i*beta)
      =H:ell^i
      =Hsat,

  and therefore v*y=0.

  The extension

    0 -> J_i -> J_(i-1) -> W_i -> 0

  is the pushout of

    0 -> I -> Cbar -> Cbar/I -> 0

  along c |-> c*ell^(i-1)*beta.  Under the resulting cyclic presentation, the
  connecting class of phi_y is represented on I by a map satisfying

    ell |-> y,
    Hsat |-> 0.

  This class vanishes exactly when there is z in X with

    Hsat*z=0,
    ell*z=y,

  namely exactly when y belongs to ell*N_H.  Thus these explicit classes have
  rank

    dim_C(N_H/ell*N_H).

  Since N_H is finite-dimensional and stable under ell, rank-nullity gives

    dim_C(N_H/ell*N_H)
      =dim_C(0:_N_H ell)
      =dim_C Hom_Cbar(Cbar/(Hsat,ell),X)
      =dim_C Hom_Cbar(W_i,X).

  Hence the connecting map has rank at least dim Hom(W_i,X).  Applying Hom(-,X)
  to the layer sequence gives

    Delta_i
      =dim Hom(W_i,X)-rank(connecting)
      <=0.
Qed.

Theorem each_of_the_first_three_layers_has_defect_at_most_six:
  For i in {1,2,3},

    Delta_i<=6.

Proof:
  Applying Hom_Cbar(-,X) to

    0 -> J_i -> J_(i-1) -> W_i -> 0

  gives

    Delta_i<=dim_C Hom_Cbar(W_i,X).

  Every W_i is killed by ell, so the image of every map W_i->X lies in

    0:_X ell.

  Therefore

    dim Hom_Cbar(W_i,X)
      <=dim_C(0:_X ell)
      <=dim_C(0:_A ell).

  Since A is finite-dimensional,

    dim_C(0:_A ell)=dim_C(A/ell*A).

  The quotient A/ell*A is a quotient of B/ell*B, so it remains to compute the
  latter dimension.

  Here

    Hilb_Cbar(t)=(1+3*t+t^2)/(1-t),
    Hilb_T(t)=t^2,
    Hilb_B=Hilb_Cbar+t^2.

  Moreover 0:_B ell=T because ell is regular on Cbar and kills the socle line
  T.  The multiplication-by-ell exact sequence therefore gives

    Hilb_(B/ell*B)
      =(1-t)*Hilb_B+t*Hilb_T
      =1+3*t+2*t^2.

  Hence

    dim_C(B/ell*B)=6,

  proving the claim.
Qed.

