Theorem conormal_maps_factor_exactly_through_the_saturated_core:
  One has natural vector-space isomorphisms

    Hom_B(L,A)
      ~= Hom_Cbar(Lbar,m_A)
      ~= Hom_Cbar(J_k,m_A).

  Therefore

    epsilon
      =(N-1)-dim_C Hom_Cbar(J_k,m_A).

Proof:
  Because T*L=0 and L intersect T=0, projection B->Cbar identifies L with
  Lbar as a Cbar-module.

  If phi:L->A is B-linear and t belongs to T, then for every x in L,

    t*phi(x)=phi(t*x)=0.

  Hence im(phi) lies in Ann_A(T)=m_A.  Conversely every Cbar-linear map
  Lbar->m_A defines a B-linear map L->A because T acts trivially on both
  modules.  This proves the first isomorphism.

  The core profile gives Lbar=ell^r*J_k.  Since ell is a nonzerodivisor on
  Cbar, multiplication by ell^r gives a Cbar-module isomorphism

    J_k -> ell^r*J_k=Lbar.

  This proves the second isomorphism.  Compare with the preceding exact
  conormal dimension formula to obtain the displayed identity for epsilon.
Qed.

Define the homogeneous colon

  H:=(alpha:beta),
  Hsat:=H:ell^infinity.

Theorem colon_saturation_is_reached_after_three_parameter_steps:
  One has

    (Hsat/H)_n=0

  for every n>=3.  Consequently

    ell^3*(Hsat/H)=0,
    H:ell^3=Hsat,

  and therefore

    H:ell^j=Hsat

  for every j>=3.

Proof:
  Let x in Hsat be homogeneous of degree n>=3.  Choose m>=0 such that

    ell^m*x*beta belongs to (alpha).

  Thus

    ell^m*x*beta=alpha*c

  for some homogeneous c of degree n+m.  Since multiplication by ell is an
  isomorphism in every degree starting at degree three, multiplication by
  ell^m gives an isomorphism

    Cbar_n -> Cbar_(n+m).

  Hence c=ell^m*c0 for some c0 in Cbar_n.  Substitution gives

    ell^m*(x*beta-alpha*c0)=0.

  The element ell is a nonzerodivisor on Cbar, so cancellation yields

    x*beta=alpha*c0.

  Thus x belongs to H.  This proves equality of H and Hsat in every degree at
  least three.

  For any homogeneous x in Hsat of degree below three, ell^3*x has degree at
  least three and remains in Hsat, hence lies in H.  Therefore

    ell^3*Hsat subseteq H,

  which is equivalent to Hsat subseteq H:ell^3.  The reverse inclusion follows
  from the definition of saturation.  Thus H:ell^3=Hsat, and all higher colons
  are the same.
Qed.

