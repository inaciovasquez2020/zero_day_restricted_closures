ExternalResult multiplicity_additivity_for_equal_dimension_modules:
  If

    0 -> M' -> M -> M'' -> 0

  is exact and all nonzero modules involved have the same Krull dimension d,
  then their d-dimensional Hilbert-Samuel multiplicities satisfy

    e(M)=e(M')+e(M'').

Theorem height_two_two_quadric_section_model:
  After a constant change of basis in Q_2, choose

    q1,q2,q3,q4

  so that q1,q2 is a regular sequence.  Put

    R:=S/(q1,q2),
    a:=image(q3) in R_2,
    b:=image(q4) in R_2,
    J:=(a,b) subset R.

  Then

    B:=S/Q ~= R/J,
    dim R=2,
    dim B=2,
    ht_R(J)=0.

  Moreover a,b are linearly independent in R_2.

Proof:
  The external generic-selection result gives q1,q2 regular.  Since S has
  dimension four,

    dim R=4-2=2.

  Also

    R/J ~= S/(q1,q2,q3,q4)=S/Q=B.

  The standing height-two hypothesis gives dim B=2, so J has height zero in R.

  If alpha*a+beta*b=0 in R_2, then

    alpha*q3+beta*q4 belongs to (q1,q2)_2.

  Because q1,q2 are homogeneous quadrics, the degree-two part of their ideal is
  exactly span_C(q1,q2).  Thus a nontrivial relation between a,b would give a
  constant linear dependence among q1,q2,q3,q4, contrary to the standing
  four-dimensionality of Q_2.  Hence a,b are independent.
Qed.

Theorem ambient_two_quadric_curve_has_exact_Hilbert_series:
  One has

    Hilb_R(t)
      =(1-t^2)^2/(1-t)^4
      =(1+t)^2/(1-t)^2.

  Consequently

    dim_C R_0=1,
    dim_C R_n=4*n for every n>=1.

  In particular

    dim_C R_1=4,
    dim_C R_2=8.

Proof:
  This is the Hilbert series of a complete intersection of two quadrics in four
  variables.  Expanding

    (1+2*t+t^2)/(1-t)^2

  gives coefficient one in degree zero and 4*n in every positive degree.
Qed.

