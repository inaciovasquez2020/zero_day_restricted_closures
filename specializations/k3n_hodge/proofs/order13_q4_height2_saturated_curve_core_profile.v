Theorem saturation_exact_sequence_and_dimension:
  There is a graded exact sequence

    0 -> T -> B -> C -> 0,

  with T finite length.  Moreover

    U != 0,
    U != R,
    ht_R(U)=0,
    dim C=2.

Proof:
  By definition of saturation, U/J is precisely the irrelevant-maximal torsion
  of R/J=B, hence has finite length and gives the displayed exact sequence.

  The ideal J is nonzero because its degree-two generators a,b are independent,
  so U, which contains J, is nonzero.

  If U=R, then 1 belongs to J:m^infinity, so some power of the irrelevant
  maximal ideal lies in J.  This would make R/J finite length, contradicting

    dim(R/J)=dim B=2.

  Thus U is proper.

  Since quotienting B by the finite-length module T does not change its Krull
  dimension,

    dim C=dim B=2.

  As dim R=2, this says ht_R(U)=0.
Qed.

Theorem saturated_core_has_depth_at_least_one_but_not_yet_two:
  One has

    H^0_m(C)=0,

  and therefore

    depth_m(C)>=1.

  No conclusion

    depth_m(C)=2

  is available from saturation alone.

Proof:
  The quotient C=R/U is saturated by construction, so it has no irrelevant
  maximal torsion.  For a positive-dimensional finitely generated graded
  module this is equivalent to depth at the irrelevant maximal ideal being at
  least one.

  Since dim C=2, Cohen--Macaulayness would require depth two.  Saturation only
  removes H^0_m and does not in general force H^1_m to vanish, so no such
  promotion is made here.
Qed.

This is the first structural difference from the height-three branch: there,
a saturated one-dimensional quotient with H^0_m=0 was automatically
Cohen--Macaulay.  Here the saturated quotient has dimension two, so depth one
is a genuine surviving possibility.

Theorem the_height_two_curve_core_has_multiplicity_at_most_three:
  One has

    e(R)=4,

  and

    e(B)=e(C) in {1,2,3}.

Proof:
  The complete intersection R of two quadrics has multiplicity

    e(R)=2*2=4.

  The nonzero ideal J is an R-module of dimension two.  Indeed R is
  Cohen--Macaulay and therefore unmixed; every associated prime of R is
  minimal of dimension two, and every nonzero submodule of R has support
  containing at least one such minimal prime.

  Apply multiplicity additivity to

    0 -> J -> R -> B -> 0.

  Since J is nonzero of dimension two,

    e(J)>0.

  Since B has dimension two,

    e(B)>0.

  Therefore

    4=e(R)=e(J)+e(B)

  forces

    e(B) in {1,2,3}.

  Finally T has finite length in

    0 -> T -> B -> C -> 0,

  so it contributes no two-dimensional multiplicity.  Hence

    e(C)=e(B).
Qed.

