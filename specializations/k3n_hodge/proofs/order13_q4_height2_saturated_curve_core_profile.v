Theorem two_linear_saturation_classes_force_a_line_core:
  If

    dim_C U_1=2,

  then

    C ~= C[s,t]

  as a standard graded C-algebra after a linear change of coordinates, and

    e(C)=1.

Proof:
  Lift a basis of U_1 to two independent linear forms l1,l2 in S_1.  Then

    C=S/Uhat

  is a quotient of

    S/(l1,l2) ~= C[s,t].

  Both rings have Krull dimension two.  The polynomial ring C[s,t] is a domain,
  so every nonzero proper ideal has height at least one and would make the
  quotient have dimension at most one.  Therefore the induced ideal must be
  zero, giving C~=C[s,t].  Its multiplicity is one.
Qed.

