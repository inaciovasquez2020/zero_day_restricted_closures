  Do NOT import the height-three conclusion that the saturated core is
  Cohen--Macaulay.

  In the present height-two branch we know only

    dim C=2,
    depth C>=1,
    e(C) in {1,2,3},
    (fbar,gbar) is a parameter pair.

  If depth C=2, then the parameter pair is a regular sequence and a
  two-dimensional complete-intersection/parameter-ideal analysis becomes
  available.

  If depth C=1, that regular-sequence reduction is invalid.  The obstruction is
  H^1_m(C), equivalently the one-dimensional depth defect / projective embedded
  or deficiency structure of the saturated curve core.

  Also, unlike the height-three section model, no uniform bound such as

    T_n=0 for n>=5

  has been proved here.  The previous argument used vanishing of H^1 on a
  zero-dimensional projective complete intersection.  The present ambient
  scheme X is a projective curve, so that vanishing does not transfer
  automatically.

  Therefore no m^k*T bound, no exact Ann_B(T), and no conormal tangent lower
  bound is claimed in this file.

