Theorem final_pair_is_a_parameter_pair_on_the_saturated_curve_core:
  The ideal

    (fbar,gbar) subset C

  is m_C-primary.  Thus fbar,gbar form a homogeneous system of parameters of
  the two-dimensional ring C.

Proof:
  Since I=Q+(f,g) is m-primary, the quotient

    S/(Qsat,f,g)

  is a quotient of S/(Q,f,g)=A and is therefore finite-dimensional.  But this
