Theorem ordinary_quadratic_pair_contains_regular_quadric:
  There exists a constant C-linear combination

    q = alpha*a + beta*b

  which is a homogeneous quadratic nonzerodivisor on B.

Proof:
  Because B is one-dimensional Cohen--Macaulay, every associated prime of B is
  minimal.

  The ideal J_0=(a,b) is m-primary.  Hence no minimal prime of B contains both
  a and b.  For each minimal prime P, the set

    { (alpha,beta) in C^2 : alpha*a+beta*b belongs to P }

  is therefore a proper C-linear subspace of C^2.

  There are only finitely many associated primes.  Since C is infinite, their
  finite union cannot fill C^2.  Choose (alpha,beta) outside that union.

  Then q avoids every associated prime of B and is therefore a
  nonzerodivisor.  Since a and b both have degree two, q is homogeneous of
  degree two.
Qed.

Theorem regular_quadric_section_has_length_twelve:
  For q as above,

    length_C(B/q*B)=12.

Proof:
  Since q is B-regular of degree two,

    Hilb_(B/qB)(z)
      = (1-z^2) Hilb_B(z)
      = (1+z)(1+3*z+2*z^2)
      = 1+4*z+5*z^2+2*z^3.

  Summing the Hilbert function gives

    1+4+5+2=12.
Qed.

Theorem ordinary_pair_annihilator_has_uniform_length_twelve_bound:
  One has

    length_C(E_0) <= 12.

Proof:
  The regular quadric q belongs to J_0.  Therefore every class annihilated by
  J_0 is annihilated by q, so

    E_0 subseteq 0:_A q.

  Since A is finite-dimensional, kernel and cokernel of multiplication by q
  on A have equal C-dimension.  Hence

    length_C(0:_A q)=length_C(A/qA).

  The quotient A/qA is a quotient of B/qB.  Therefore

    length_C(E_0)
      <= length_C(A/qA)
      <= length_C(B/qB)
      =12.
Qed.

