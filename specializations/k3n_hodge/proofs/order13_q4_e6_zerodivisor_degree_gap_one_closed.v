  One has

    dim_C Hom_B(W_1,A) <= 6.

Proof:
  A B-linear map W_1 -> A is determined by the image of the cyclic generator.
  Because ell kills W_1, that image must lie in 0:_A ell.  Evaluation at the
  generator therefore injects

    Hom_B(W_1,A) -> 0:_A ell.

  The preceding theorem gives length(0:_A ell)=6.
