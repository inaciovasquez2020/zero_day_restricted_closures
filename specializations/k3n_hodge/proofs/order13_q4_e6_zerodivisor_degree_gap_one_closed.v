Theorem first_delayed_layer_is_cyclic_and_killed_by_ell:
  The B-module W_1 is cyclic, generated by the class of b, and

    ell*W_1=0.

Proof:
  Modulo J_1=(a,ell*b), the class of a vanishes, so the quotient J_0/J_1 is
  generated by the class of b.

  Multiplication by ell sends that generator to ell*b, which belongs to J_1.
  Hence ell kills W_1.
Qed.

Theorem ell_annihilator_of_A_has_length_six:
  One has

    length_C(0:_A ell)=6.

Proof:
  Multiplication by ell on the finite-dimensional vector space A has kernel
  and cokernel of equal dimension.  Thus

    length_C(0:_A ell)=length_C(A/ell*A).

  Since

    L=ell^r*J_1 subseteq ell*B

  for r>=1,

    A/ell*A
      ~= B/(L,ell)
      ~= B/(ell).

  The established multiplicity-six Artin reduction has Hilbert function

    (1,3,2),

  hence length six.
Qed.

