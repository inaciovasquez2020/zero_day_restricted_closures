Theorem multiplication_intersects_the_socle_map_space_weakly:
  If

    L intersect T=0,

  then

    dim_C(P intersect im(mu))<=1.

  If

    L intersect T=T_3,

  then

    P intersect im(mu)=0.

Proof:
  First assume L intersect T=0.  Then

    S_X=T_3

  lies entirely in degree three and is one-dimensional.

  Suppose a multiplication map mu(x) lies in P.  Its value on ell*b must lie
  in degree three.  Since ell*b has degree three, a degree-three product could
  only come from X_0.  But

    X_0=J_0=0,

  because J is a proper homogeneous ideal.  Every positive-degree component of
  x would produce degree at least four, whereas a map in P has image contained
  in the degree-three line T_3.  Hence

    ell*b*x=0.

  Therefore every map in P intersect im(mu) lies in the one-dimensional line
  of maps

    a |-> T_3,
    ell*b |-> 0,

  proving the first bound.

  Now assume L intersect T=T_3.  Then S_X is the degree-two space

    T_2 mod T_3

  of dimension two.  A product by the quadratic a can land in degree two only
  from X_0, which is zero.  Multiplication by the cubic ell*b cannot produce a
  degree-two output from any nonnegative degree.  Thus every multiplication map
  lying in P is zero.
Qed.

