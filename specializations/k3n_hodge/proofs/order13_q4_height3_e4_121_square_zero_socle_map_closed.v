Theorem arbitrary_socle_values_define_a_two_generator_map_space:
  Every ordered pair (sigma,tau) in S_X direct_sum S_X defines a unique
  C-linear map

    psi_(sigma,tau):K_1 -> T_X subset X

  by

    a |-> sigma,
    ell*b |-> tau.

