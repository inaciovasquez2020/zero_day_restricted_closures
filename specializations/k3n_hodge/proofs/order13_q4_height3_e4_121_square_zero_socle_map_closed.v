Theorem final_cut_intersection_with_torsion_is_zero_or_top_line:
  One has

    L intersect T in {0,T_3}.

Proof:
  The final-cut ideal L is homogeneous and generated in degrees at least three.
  The torsion module is concentrated in degrees one, two, and three, with

    dim_C T_3=1.

  Hence L intersect T has no degree-one or degree-two part and is a graded
  subspace of T_3.  It is therefore either zero or the full top line.
Qed.

