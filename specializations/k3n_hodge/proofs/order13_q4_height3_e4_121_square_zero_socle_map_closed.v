  (C,m_C), every coefficient in every relation

    p*a+r*ell*b=0

  lies in m_C.  The socle S_X is killed by m_C, so arbitrary values sigma and
  tau in S_X satisfy every relation.  Evaluation on the two minimal generators
  identifies this map space with S_X direct_sum S_X.
Qed.

