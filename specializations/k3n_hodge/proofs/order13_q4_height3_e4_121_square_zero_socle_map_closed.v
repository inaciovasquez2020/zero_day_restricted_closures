Theorem exact_socle_dimensions_of_the_surviving_torsion:
  The C-socle of T_X is nonzero and has dimension

    1 if L intersect T=0,
    2 if L intersect T=T_3.

More precisely,

  if L intersect T=0, then
    T_X~=T and Soc_C(T_X)=T_3;

  if L intersect T=T_3, then
    T_X~=T/T_3 and Soc_C(T_X)=T_2 mod T_3.

Proof:
  In ZERO_SELF_ACTION the action on T factors through C, and the exact residual
  reduction identifies

    T~=Z(-1)

  with Z having Hilbert function (1,2,1).  Thus

    dim T_1=1,
    dim T_2=2,
    dim T_3=1.

  If no torsion is removed, the shifted Artin Gorenstein module has top socle
  T_3, which is one-dimensional.

  If T_3 is removed, every positive-degree element sends T_2 into the vanished
  degree-three piece, so all of T_2 becomes socle.  The degree-one generator is
  not socle because multiplication by Z_1 sends it onto the nonzero
  two-dimensional space T_2.  Hence the quotient socle is exactly T_2 mod T_3
  and has dimension two.
Qed.

