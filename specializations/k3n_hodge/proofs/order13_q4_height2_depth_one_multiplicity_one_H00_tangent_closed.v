  onto C[h], contradicting finite length.

  Thus at least one member of {f0,g0} is a homogeneous nonzerodivisor, of degree
  at most M.  Quotienting the multiplicity-two Cohen--Macaulay ring R0 by a
  degree-r homogeneous nonzerodivisor has length 2*r.  Since adding the other
  generator can only decrease length,

    Lcut<=2*r<=2*M.
Qed.

