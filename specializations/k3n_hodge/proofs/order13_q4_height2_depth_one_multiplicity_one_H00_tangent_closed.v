    K0 := (f0,g0) subset R0,
    Lcut := length_C(R0/K0).

Theorem H00_R0_cut_has_finite_length:
  Lcut is finite.

Proof:
  Since D~=m0, the quotient D/(f,g)D is the graded module

    m0/K0*m0.

  The exact sequence in the preceding section embeds this module into the finite
  length module Ccore/(f,g)Ccore.  Hence m0/K0*m0 has finite length.

  Because K0*m0 subset K0, there is a surjection

    R0/(K0*m0) -> R0/K0.

