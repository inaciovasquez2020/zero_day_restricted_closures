Theorem H00_uniform_multiplicity_two_cut_bound:
  One has

    Lcut <= 2*M.

Proof:
  There are two cases.

  REDUCED P1P1 CASE.
  Here

    R0=C[h,u]/(u*(u-h))

  is the homogeneous coordinate cone over two distinct reduced points.  It
  embeds in the direct sum of the two branch rings C[h] direct_sum C[h].

  On each branch, finite colength of K0 implies that at least one of f0,g0 has
  nonzero restriction.  The induced ideal on that branch is therefore

    (h^r)

  for some r belonging to {d,e,min(d,e)} and in particular r<=M.

  Hence R0/K0 injects into a sum of two one-variable quotients, each of length at
  most M.  Therefore

    Lcut<=2*M.

  JORDAN CASE.
  Here

    R0=C[h,u]/(u^2).

