    y1,y2,y3 in Pbar.

That would force the entire irrelevant ideal (y1,y2,y3) into Pbar, impossible
because Pbar is a proper linear prime of height at most two.

Therefore

    h in Pbar.

Corollary H01_m2_R2_LK3_common_factor_is_plane_direction:
  In coefficient rank three, the common linear factor h of the first three
