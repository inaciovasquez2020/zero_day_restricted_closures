2. THE COEFFICIENT RANK CANNOT BE ONE
--------------------------------------------------------------------------

Put

    rho:=rank_C(C0).

Because the primitive kernel components span all three variables, M is nonzero,
so rho>=1.  Also rho<=3.

Assume rho=1.  A constant invertible row change on the four generators of Q
puts M into the form

    M = [ s ]
        [ 0 ]
        [ 0 ]
        [ 0 ]

for one nonzero linear Koszul syzygy row s.

Since L has linear entries and reduces to M modulo r, the corresponding lift has
rows

    s+r*v1,
    r*v2,
    r*v3,
    r*v4

with constant rows vi in C^3.

Every 3-by-3 maximal minor of L is then divisible by r^2: the minor omitting the
first row is in fact divisible by r^3, while each other maximal minor contains
two rows divisible by r.

Using

    Delta_i(L)=r*q_i,

one gets

    r | q_i

for every i.  Hence

    Q subset (r),

so

    ht(Q)<=1,

contrary to the standing height-two hypothesis.

Theorem H01_m2_R2_LK3_coefficient_rank_one_impossible:
