1. THE LINEAR SYZYGY SPACE OF (y1,y2,y3)
--------------------------------------------------------------------------

Use the standard skew Koszul matrix

        [  0  -y3   y2 ]
    K = [ y3    0  -y1 ]
        [-y2   y1    0 ].

Then

    K*y=0.

A row vector

    u=(u1,u2,u3)

of linear forms satisfies

    u*y=0

if and only if u is a constant C-linear combination of the three rows of K.
Indeed, the degree-two relation

    u1*y1+u2*y2+u3*y3=0

is precisely a degree-one first syzygy of the regular sequence y1,y2,y3, and
the degree-one syzygy space is generated over C by the three Koszul syzygies.

Therefore there is a constant matrix

    C0 in Mat_(4x3)(C)

such that

    M=C0*K.

Theorem H01_m2_R2_LK3_koszul_factorization:
  After the stated LK3 normalization,

    M=C0*K

  for a constant 4-by-3 matrix C0.
Qed.

