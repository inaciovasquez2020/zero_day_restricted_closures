5. THREE QUADRICS ACQUIRE THE COMMON LINEAR FACTOR h MODULO r
--------------------------------------------------------------------------

The adjugate of the skew Koszul matrix is

    adj(K)=y*y^T.

Equivalently, the signed 2-by-2 cofactors of K are the pairwise products y_i*y_j.

For i=1,2,3, the maximal minor Delta_i(L) is obtained by deleting one of the
first three rows.  It contains the last row r*v^T.  After dividing by r and
reducing modulo r, its value is the corresponding cofactor contraction of K
with v.  With compatible harmless signs on the generators q1,q2,q3, this gives

    q1 mod r = h*y1,
    q2 mod r = h*y2,
    q3 mod r = h*y3.

For the fourth maximal minor,

    Delta_4(L)=det(K+rV).

Since det(K)=0, the coefficient of r is

    trace(adj(K)*V)
      = trace(y*y^T*V)
      = y^T*V*y.

Thus, after dividing by r and reducing modulo r,

    q4 mod r = phi,

where

    phi:=y^T*V*y

is a quadratic form in Sbar_2.

Theorem H01_m2_R2_LK3_rank_three_quadric_shadow:
  In coefficient rank three, after compatible generator signs,

    Q mod r

  is generated by the four quadratic shadows

    h*y1,
    h*y2,
    h*y3,
    phi,

  with h!=0 and phi=y^T*V*y.
Qed.

