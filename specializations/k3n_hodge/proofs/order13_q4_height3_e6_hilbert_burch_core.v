Theorem three_nonsection_quadrics_are_Hilbert_Burch_minors:
  Let

    H := (x*a+y*b,
          x*c+y*d,
          a*d-b*c).

  Then

    H=I_2(Phi).

Proof:
  The three maximal minors of Phi are, up to the harmless ordering/sign
  convention,

    a*d-b*c,
    a*x+b*y,
    c*x+d*y.

  These are exactly the displayed generators of H.
Qed.

Theorem determinantal_core_has_height_two:
  One has

    ht(H)=2.

Proof:
  Since Q=H+(q0) has height three, Krull's principal ideal theorem gives

    ht(H)>=2.

  On the other hand, the ideal of maximal minors of a 2-by-3 matrix has height
  at most

    (2-2+1)*(3-2+1)=2.

  Hence ht(H)=2.
Qed.

Corollary determinantal_core_is_degree_three_Hilbert_Burch:
  The ideal H is perfect of grade two and has minimal graded resolution

    0 -> S(-3)^2
      -> S(-2)^3
      -> S
      -> C:=S/H
      -> 0.

  Consequently C is a two-dimensional Cohen--Macaulay standard graded ring
  with

    Hilb_C(t)
      = (1-3*t^2+2*t^3)/(1-t)^4
      = (1+2*t)/(1-t)^2,

  and therefore

    e(C)=3.

  Geometrically Proj(C) is a degree-three arithmetically Cohen--Macaulay curve
  in P^3 (possibly a degeneration of the twisted-cubic configuration).
Qed.

Theorem q0_is_regular_on_determinantal_core:
  The quadric q0 is a nonzerodivisor on C=S/H.

Proof:
  C is Cohen--Macaulay and ht(H)=2.  If q0 were a zerodivisor, it would lie in
  an associated prime of C.  In a Cohen--Macaulay ring the associated primes
  here are minimal; a minimal component containing q0 would survive with
  dimension two in C/(q0), contradicting

    ht(H+(q0))=ht(Q)=3.

  Thus q0 is C-regular.
Qed.

Corollary multiplicity_six_core_is_quadric_section_of_degree_three_curve:
  Every homogeneous q=4, ht(Q)=3, e(S/Q)=6 endpoint admits the presentation

    Q=(I_2(Phi),q0)

  with Phi a 2-by-3 matrix of linear forms satisfying ht I_2(Phi)=2, and q0 a
  quadratic nonzerodivisor on S/I_2(Phi).

  Therefore

    B=S/Q ~= (S/I_2(Phi))/(q0)

  is a regular quadric section of a degree-three Hilbert--Burch curve ring.

  The multiplicity identity is transparent:

    e(B)=deg(q0)*e(S/I_2(Phi))=2*3=6.
Qed.

