ExternalResult NorthcottDeterminantColonFormula:
  Let R be a Cohen--Macaulay ring.  Suppose

    J=(u1,u2,u3)

  and

    K=(k1,k2,k3)

  are complete intersections of the same grade three, K subset J, and

    (k1,k2,k3)^T = M * (u1,u2,u3)^T

  for a 3-by-3 matrix M over R.  Then

    K:J = K + (det M).

  This is the standard Northcott determinant/linkage formula for an almost
  complete intersection obtained by linking two complete intersections.

