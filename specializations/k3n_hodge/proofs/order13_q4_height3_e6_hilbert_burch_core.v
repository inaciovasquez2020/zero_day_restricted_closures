Theorem normalize_residual_complete_intersection:
  After a linear change of coordinates and choice of generators, write

    J=(x,y,q)

  with x,y independent linear forms and q a quadric, forming a regular
  sequence of degrees (1,1,2).

  Choose the three quadratic generators k1,k2,k3 of K.  Because K subset J,
  each has a unique homogeneous expression

    ki = x*ai + y*bi + ci*q,

  where ai,bi are linear forms and ci is a scalar.

  At least one ci is nonzero.  Otherwise K subset (x,y), contradicting
  ht(K)=3.

  A GL_3(C) change of the regular-sequence basis of K therefore normalizes

    c1=c2=0,
    c3=1.

  Replacing q by

    q0:=k3=q+x*a3+y*b3

  preserves J=(x,y,q0).  Thus one may write

    k1=x*a+y*b,
    k2=x*c+y*d,
    k3=q0,

  for linear forms a,b,c,d.
Qed.

Theorem northcott_normal_form_for_Q:
  In the preceding normalization,

    Q=(q0,
       x*a+y*b,
       x*c+y*d,
       a*d-b*c).

Proof:
  Relative to the ordered regular sequences

    J=(x,y,q0),
    K=(k1,k2,q0),

  the inclusion matrix is

    M3 = [[a,b,0],
          [c,d,0],
          [0,0,1]].

  Hence

    det(M3)=a*d-b*c.

  The already established linkage identity gives Q=K:J.  Apply the Northcott
  determinant formula to obtain

    Q=K+(det M3),

  which is exactly the displayed ideal.
Qed.

