Lemma tensor_hyperplane_switch_in_dimension_two:
  Let U and V be two-dimensional C-vector spaces and let

    W subset U tensor V

  be a hyperplane.  Suppose

    Sym^2(U) tensor V = U*W,

  where U*W denotes the image of multiplication in the U-factor.
  Then

    U tensor Sym^2(V) = V*W.

Proof:
  A hyperplane W is the kernel of a nonzero bilinear form

    phi in U^* tensor V^*.

  If phi had rank one, choose nonzero u in ker(U -> V^*) and nonzero v with
  phi(-,v)=0.  Then the class of u tensor v would survive the first quotient,
  and multiplication by a suitable nonzero element of U would give a nonzero
  class in

    (Sym^2(U) tensor V)/(U*W),

  contradicting the hypothesis.  Hence phi has rank two.

  After independent basis changes in U and V, W therefore has the normal form

    W = Span_C{
          z tensor l1,
          w tensor l1 + z tensor l2,
          w tensor l2
        }.

  Multiplying these three tensors by l1 and l2 gives

    z tensor l1^2,
    z tensor l1*l2,
    w tensor l1^2 + z tensor l1*l2,
    w tensor l1*l2 + z tensor l2^2,
    w tensor l1*l2,
    w tensor l2^2.

  These span all six basis tensors of

    U tensor Sym^2(V).

  Therefore V*W=U tensor Sym^2(V).
Qed.

