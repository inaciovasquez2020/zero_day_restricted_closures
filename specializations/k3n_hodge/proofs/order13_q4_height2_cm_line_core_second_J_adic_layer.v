    dim_C F_2=dim_C Sym^2(V)=3.

  Because F is generated in degree two and n annihilates it, no higher degree
  survives, proving the result.
Qed.

Theorem three_relation_case_second_layer:
  Assume r=3.  Then

    F ~= C(-2)^2

  as a graded R-module.  Equivalently,

    Hilb_F(t)=2*t^2,
