1. COMMON NORMALIZATION OF THE FOUR-PLANE
--------------------------------------------------------------------------

Put

    A:=C_1=(Q:l1)_1.

The previous quadratic-subspace reduction proves

    dim_C A=2,
    Q_2 intersect l1*S_1 = l1*A.

In either H10 incidence, the quotient

    (Qsat)_2 / l1*S_1

is two-dimensional, and Q_2 surjects onto it.  Therefore one may choose two
quadrics q1,q2 in Q_2 whose images form a basis of that quotient, so that

    Q_2 = l1*A direct_sum C*q1 direct_sum C*q2.

Because Q is generated by Q_2,

    Q=(l1*A,q1,q2).

The precise non-l1 parts of q1,q2 depend on the incidence.

