2. H10-OFF: THE COLON IS GENERATED BY ONE LINEAR PAIR AND THREE QUADRICS
--------------------------------------------------------------------------

In H10-OFF choose coordinates

    S=C[x,y,z,w],
    l1=x,
    l2=y,

with

    Qsat=(x,yz,yw).

Then one may choose linear forms alpha,beta in S_1 such that

    qz := yz + x*alpha,
    qw := yw + x*beta,

and

    Q_2 = x*A direct_sum C*qz direct_sum C*qw.

Define the quadratic syzygy defect

    hoff := w*alpha - z*beta.

Theorem H10_OFF_basic_syzygy_defect_lies_in_C:
  One has

    hoff in C=(Q:x).

Proof:
  The identity

    w*qz-z*qw
      = w*(yz+x*alpha)-z*(yw+x*beta)
      = x*(w*alpha-z*beta)
      = x*hoff

lies in Q.  Hence hoff belongs to (Q:x).
Qed.

Theorem H10_OFF_colon_is_generated_in_degrees_one_and_two:
  One has

    C=(A,qz,qw,hoff).

Proof:
  The inclusion from right to left is immediate:

    A subset C

by definition of A=C_1,

    qz,qw in Q subset C,

and hoff lies in C by the preceding theorem.

  For the reverse inclusion, let h be a homogeneous element of C of degree

    n>=2.

  Since x*h lies in Q and Q is generated by its four quadrics, there exist

    u in A*S_(n-1),
    r,s in S_(n-1)

  such that

    x*h = x*u + r*qz + s*qw.

  Reduce modulo x.  In

    S/(x)=C[y,z,w]

  one obtains

    0 = rbar*(y*z)+sbar*(y*w)
      = y*(z*rbar+w*sbar).

  The ring C[y,z,w] is a domain, so

    z*rbar+w*sbar=0.

  The syzygy module on the pair (z,w) is generated by (w,-z).  Hence there is

    cbar in C[y,z,w]_(n-2)

  such that

    rbar=w*cbar,
    sbar=-z*cbar.

  Lift cbar to c in S_(n-2).  Then

    r=w*c+x*r1,
    s=-z*c+x*s1

  for some r1,s1 in S_(n-2).

  Substitute:

    r*qz+s*qw
      = c*(w*qz-z*qw)+x*r1*qz+x*s1*qw
      = x*(c*hoff+r1*qz+s1*qw).

  Therefore

    x*h=x*(u+c*hoff+r1*qz+s1*qw).

  Since S is a domain, cancel x and obtain

    h=u+c*hoff+r1*qz+s1*qw.

  Thus h lies in (A,qz,qw,hoff).
Qed.

