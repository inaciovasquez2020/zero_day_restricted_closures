3. H10-ON: THE SAME THREE-QUADRIC COLON PATTERN
--------------------------------------------------------------------------

In H10-ON choose coordinates

    S=C[x,y,z,w],
    l1=x,
    l2=y,

with

    Qsat=(x,y^2,yz).

Choose linear forms alpha,beta in S_1 such that

    q0 := y^2 + x*alpha,
    q1 := y*z + x*beta,

and

    Q_2 = x*A direct_sum C*q0 direct_sum C*q1.

Define

    hon := z*alpha-y*beta.

Theorem H10_ON_basic_syzygy_defect_lies_in_C:
  One has

    hon in C=(Q:x).

Proof:
  The identity

    z*q0-y*q1
      = z*(y^2+x*alpha)-y*(yz+x*beta)
      = x*(z*alpha-y*beta)
      = x*hon

lies in Q.
Qed.

Theorem H10_ON_colon_is_generated_in_degrees_one_and_two:
  One has

    C=(A,q0,q1,hon).

Proof:
  As before the displayed generators all lie in C.

  Let h in C be homogeneous of degree n>=2.  Write

    x*h=x*u+r*q0+s*q1

with

    u in A*S_(n-1),
    r,s in S_(n-1).

  Reducing modulo x gives

    0=rbar*y^2+sbar*y*z
     =y*(y*rbar+z*sbar)

in the domain C[y,z,w].  Thus

    y*rbar+z*sbar=0.

  The syzygy module on (y,z) is generated by (z,-y), so for some lift

    c in S_(n-2)

one may write

    r=z*c+x*r1,
    s=-y*c+x*s1.

  Then

    r*q0+s*q1
      =c*(z*q0-y*q1)+x*r1*q0+x*s1*q1
      =x*(c*hon+r1*q0+s1*q1).

  Cancelling x gives

    h=u+c*hon+r1*q0+s1*q1.

  Hence C=(A,q0,q1,hon).
Qed.

