5. ONLY TWO QUADRATIC ARTINIAN QUOTIENTS CAN OCCUR
--------------------------------------------------------------------------

Put

    kappa:=dim_C (Cbar)_2.

Because R_2 has dimension three,

    0<=kappa<=3.

Theorem H10_quadratic_colon_rank_is_two_or_three:
  One has

    kappa in {2,3}.

Proof:
  The ideal Cbar is generated by quadrics and is (s,t)-primary.

  If kappa=0, then Cbar=0, which is not primary to (s,t).

  If kappa=1, then Cbar is generated by one nonzero homogeneous quadratic.
  Its radical has height one, so R/Cbar has positive dimension and cannot have
  finite length.

  Hence kappa>=2.  Since dim R_2=3, only kappa=2 or3 remain.
Qed.

Theorem H10_kappa_three_is_the_square_of_the_maximal_ideal:
  If kappa=3, then

    Cbar=(s,t)^2

and

    Hilb_(R/Cbar)(t)=1+2*t.

Proof:
  Three-dimensionality means

    (Cbar)_2=R_2.

  Since Cbar is generated in degree two, it equals the ideal generated by R_2,
  namely (s,t)^2.  The quotient has basis 1,s,t.
Qed.

Theorem H10_kappa_two_is_a_quadratic_complete_intersection:
  If kappa=2, then Cbar is generated by two linearly independent quadrics with
  no common linear factor.  Consequently it is a complete intersection of type

    (2,2)

and

    Hilb_(R/Cbar)(t)=1+2*t+t^2.

Proof:
  Choose a basis f,g of (Cbar)_2.  Since Cbar is generated in degree two,

    Cbar=(f,g).

  If f and g had a common nonconstant factor, then their common factor would be
  linear and the radical of (f,g) would have a height-one component.  This would
  contradict (s,t)-primaryness.

  Therefore gcd(f,g)=1.  In the two-variable polynomial ring R, the pair f,g is
  a regular sequence.  Hence Cbar is a complete intersection of degrees two and
  two.

  Its Hilbert series is

    ((1-t^2)^2)/(1-t)^2=(1+t)^2=1+2*t+t^2.
Qed.

Corollary exact_H10_colon_Hilbert_dichotomy:
