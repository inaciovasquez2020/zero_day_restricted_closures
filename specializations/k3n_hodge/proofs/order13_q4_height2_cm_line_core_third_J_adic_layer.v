Theorem the_longitudinal_maximal_ideal_annihilates_the_third_layer:
  In both first-layer cases r=4 and r=3,

    n*G=0.

Proof:
  FOUR-RELATION CASE r=4.

  The first initial forms span

    W=U tensor V.

  Let u be z or w and let s be any element of Sym^3(V).  Write s as a sum of
  terms v*t with v in V and t in Sym^2(V).  Since u*v belongs to W, choose a
  constant combination q of the four quadratic generators whose first J-adic
  initial form is u*v.  Multiplying q by t gives an element of Q whose class
  modulo J^4 has leading term u*v*t=u*s; its pure J^2 correction is multiplied
  by t and therefore lies in J^4.  Hence u*s is zero in G.

  THREE-RELATION CASE r=3.

  The preceding second-layer file proves

    V*W = U tensor Sym^2(V).

  Multiplying this equality once more by V gives

    Sym^2(V)*W = U tensor Sym^3(V).

  Therefore every u*s in U tensor Sym^3(V) is a sum of first initial forms
  multiplied by elements of Sym^2(V).  Replacing each first initial form by
  its lifted quadratic generator changes the result only by J^4.  Thus every
  longitudinal multiple again vanishes in G.
Qed.

