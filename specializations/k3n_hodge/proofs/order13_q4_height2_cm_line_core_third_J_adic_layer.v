Theorem r4_has_two_independent_pure_cubic_relations:
  Assume r=4.  After constant changes of generator basis and bases of U,V, write

    q1 = z*l1 + h1,
    q2 = w*l1 + h2,
    q3 = z*l2 + h3,
    q4 = w*l2 + h4,

  with each h_i in Sym^2(V).

  Define

    Pz := l2*h1-l1*h3,
    Pw := l2*h2-l1*h4.

  Then

    Pz,Pw belong to Q intersect Sym^3(V)

  and are C-linearly independent.  In fact they have no common projective zero
  in P(V)=P^1.

Proof:
  The identities

    l2*q1-l1*q3=Pz,
    l2*q2-l1*q4=Pw

  prove membership in Q.

  Suppose Pz and Pw had a common projective zero [a:b] with (a,b) nonzero.
  Compatibility Pz(a,b)=0 gives a scalar z0 satisfying

    a*z0=-h1(a,b),
    b*z0=-h3(a,b).

  Likewise Pw(a,b)=0 gives w0 satisfying

    a*w0=-h2(a,b),
    b*w0=-h4(a,b).

  Thus

    [l1:l2:z:w]=[a:b:z0:w0]

  is a projective zero of all four q_i with (l1,l2) nonzero.  But Qsat=J says
  Proj(S/Q)=Proj(S/J), whose points all satisfy l1=l2=0.  Contradiction.

  Hence Pz,Pw have no common projective zero.  In particular they are nonzero
  and linearly independent.
Qed.

