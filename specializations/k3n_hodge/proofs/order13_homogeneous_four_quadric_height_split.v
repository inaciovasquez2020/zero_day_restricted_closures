ExternalResult FourQuadraticAlmostCompleteIntersectionMultiplicity:
  Let Q be a homogeneous height-three ideal minimally generated by four quadrics in a polynomial ring over a field.  Then

    e(S/Q) <= 6.

  If

    e(S/Q)=6,

  then S/Q is Cohen--Macaulay.

  Source: the multiplicity bound for quadratic almost complete intersections used in Huneke--Mantero--McCullough--Seceleanu, A Tight Bound on the Projective Dimension of Four Quadrics, J. Pure Appl. Algebra 222 (2018), together with the maximal-multiplicity Cohen--Macaulay criterion cited there.

Corollary height_three_four_quadric_multiplicity_is_small:
  In the ht(Q)=3 branch,

    1 <= e(S/Q) <=6.

  The endpoint e=6 is Cohen--Macaulay.
Qed.

Theorem height_three_four_quadric_section_model:
  Assume ht(Q)=3.

  After changing the four-dimensional basis of Q_2, choose generators

    q1,q2,q3,a

  such that

    K := (q1,q2,q3)

  is a regular sequence of three quadrics.

  Set

    R := S/K,
    J := (a)R.

  Then

    S/Q = R/J,

  and X:=Proj(R) is the zero-dimensional complete intersection of three quadrics in P^3, of length eight.
Qed.

Theorem complete_intersection_sections_stabilize_in_degree_three:
  The Hilbert series of R is

    Hilb_R(t)=(1-t^2)^3/(1-t)^4=(1+t)^3/(1-t).

  Hence

    dim R_0=1,
    dim R_1=4,
    dim R_2=7,
    dim R_n=8 for n>=3.

  Since X is finite of length eight,

    dim H^0(X,O_X(n))=8

  for every n.  Since R is one-dimensional Cohen--Macaulay, H^0_m(R)=0, so the natural maps

    R_n -> H^0(X,O_X(n))

  are injective and therefore isomorphisms for every n>=3.
Qed.

Theorem height_three_four_quadric_saturation_defect_vanishes_from_degree_five:
  Let

    Qsat := saturation of Q with respect to m,
    B := S/Q,
    T := H^0_m(B)=Qsat/Q.

  Then

    T_n=0

  for every n>=5.

Proof:
  In R=S/K, Q/K is the principal quadratic ideal J=(a).
  Let Jsat denote its saturation in R.

  On X=Proj(R), the sheaf ideal J~ is generated by the section a, giving a surjection

    O_X(-2) -> J~ -> 0.

  Its kernel is coherent on the zero-dimensional scheme X, hence has vanishing H^1.  After twisting by n, global sections therefore give a surjection

    H^0(X,O_X(n-2)) -> H^0(X,J~(n)).

  For n>=5, both n and n-2 are at least three.  The preceding theorem identifies

    R_n ~= H^0(X,O_X(n)),
    R_(n-2) ~= H^0(X,O_X(n-2)).

  Therefore the degree-n principal piece

    J_n = a R_(n-2)

  equals the full saturated degree-n piece Jsat_n.

  Hence

    T_n=(Jsat/J)_n=0

  for all n>=5.
Qed.

Corollary height_three_four_quadric_saturation_torsion_is_m4_killed:
  Since Qsat is proper, T_0=0.  Together with T_n=0 for n>=5, T is supported in degrees 1 through 4.  Therefore

    m^4 T=0.
Qed.

IMPORTANT_NONCONCLUSION:
  The q=5 tangent closure does not automatically repeat here.

  In the present q=4 branch the final ideal is

    I=Q+(f,g)

