Standalone height split for the homogeneous q=4 order-13 deviation-two branch.

SCOPE:
  This file applies only to homogeneous six-generator ideals

    S := C[x1,x2,x3,x4],
    I subset S homogeneous and m-primary,
    A := S/I Artinian,
    mu(I)=6,
    length(A)=N>=32,

  with exactly four quadratic minimal generators.

  Write

    Q := (I_2),

  so Q is generated by four independent quadrics.  Because the remaining two minimal generators have degree at least three, write

    I = Q + (f,g),
    deg(f),deg(g)>=3.

  The unrestricted nonhomogeneous local deviation-two frontier is not affected.

This is pseudo-formal mathematical documentation.  It is not Coq and does not assert generic F_13 algebraicity.

ExternalResult TwoGeneratorHeightBound:
  For a Noetherian ring and ideal Q,

    ht(Q+(f,g)) <= ht(Q)+2.

  This is the two-generator form of Krull's height theorem.

Theorem four_quadric_core_has_height_two_or_three:
  Since I is m-primary in the four-dimensional polynomial/local ring,

    ht(I)=4.

  From I=Q+(f,g) and TwoGeneratorHeightBound,

    4 <= ht(Q)+2,

  hence

    ht(Q)>=2.

  Suppose ht(Q)=4.  Then the four independent quadratic generators of Q form a homogeneous system of parameters in the Cohen--Macaulay ring S and therefore a regular sequence.  Thus Q is a complete intersection of type (2,2,2,2), and

    length(S/Q)=2^4=16.

  Since Q subseteq I,

    N=length(S/I) <= length(S/Q)=16,

  contradicting N>=32.

  Therefore

    ht(Q) in {2,3}.
Qed.

Corollary homogeneous_q4_splits_into_curve_core_or_one_dimensional_core:
  If ht(Q)=2, then

    dim(S/Q)=2,

  and the two higher-degree generators f,g make the final Artinian cut.

  If ht(Q)=3, then

    dim(S/Q)=1,

  and f,g cut a one-dimensional four-quadric core to finite length.
Qed.

