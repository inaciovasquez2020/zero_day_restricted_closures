3. THE FINAL QUADRATIC VECTOR IS NONZERO MODULO r
--------------------------------------------------------------------------

The final syzygy identity is

    L*(a1,a2,a3)^T + r*Q4=0.

Theorem H01_m2_R2_final_quadratic_vector_nonzero_mod_r:
  Not all of a1,a2,a3 belong to the principal ideal (r).

Proof:
  Suppose

    ai=r*bi

  for linear forms bi. Then

    r*(L*(b1,b2,b3)^T+Q4)=0.

  Since S is a domain and r!=0,

    Q4=-L*(b1,b2,b3)^T.

  Thus the degree-four first-syzygy column Q4 is generated by the three
  degree-three first-syzygy columns using linear coefficients. This contradicts
  minimality of the S(-4) summand in the exact minimal free resolution.
Qed.

Therefore the image

    abar:=(a1,a2,a3) mod r

is a nonzero vector over

    Sbar:=S/(r).

