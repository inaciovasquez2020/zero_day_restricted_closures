1. THE THREE LINEAR COLUMNS HAVE GENERIC RANK THREE
--------------------------------------------------------------------------

Let

    K:=Frac(S).

Exactness of the minimal resolution over K gives

    rank_K(A)=3,
    dim_K ker(A_K)=1.

The one-dimensional kernel is generated by the nonzero vector

    (a1,a2,a3,r)^T.

Theorem H01_m2_R2_linear_submatrix_has_rank_three:
  One has

    rank_K(L)=3.

Proof:
  Suppose rank_K(L)<=2. Then L_K has a nonzero right-kernel vector

    v in K^3.

  Hence

    (v,0) in K^4

  is a nonzero vector in ker(A_K).

  But ker(A_K) is one-dimensional and generated by

    (a1,a2,a3,r)^T,

  whose fourth coordinate r is nonzero in K. No nonzero scalar multiple of
  that generator can have fourth coordinate zero. Contradiction.
Qed.

Thus at least one 3-by-3 maximal minor of L is nonzero.

