5. THE COMMON MINOR FACTOR IS EXACTLY r
--------------------------------------------------------------------------

From Section 2,

    Deltai=ell*qi.

From Section 4,

    r | ell*qi

for every i.

The linear form r is irreducible, hence prime in S. If r did not divide ell,
then r would divide every qi, contradicting primitivity of the quadric row.
Therefore

    r | ell.

Both r and ell are nonzero linear forms, so they differ by a nonzero scalar.
After rescaling the generator of the rank-one final free module S(-5), normalize
that scalar to one.

Theorem H01_m2_R2_final_linear_entry_is_minor_factor:
  After the harmless scalar normalization of the final syzygy generator,

    ell=r.
Qed.

Consequently the signed maximal minors satisfy the exact identities

    Deltai=r*qi

for i=1,2,3,4.

