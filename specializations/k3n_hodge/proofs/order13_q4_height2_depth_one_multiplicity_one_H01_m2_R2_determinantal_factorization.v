4. MODULO r THE LINEAR MATRIX DROPS RANK
--------------------------------------------------------------------------

Reducing

    L*a+r*Q4=0

modulo r gives

    Lbar*abar=0

with abar nonzero.

Because r is a nonzero linear form, Sbar is a polynomial ring in three
variables and hence a domain. Passing to Frac(Sbar) gives a nonzero right-kernel
vector of Lbar. Therefore

    rank_Frac(Sbar)(Lbar)<=2.

Theorem H01_m2_R2_maximal_minors_vanish_mod_r:
  Every 3-by-3 maximal minor Deltai of L lies in (r).
Qed.

Equivalently,

    r | Deltai

for every i.

