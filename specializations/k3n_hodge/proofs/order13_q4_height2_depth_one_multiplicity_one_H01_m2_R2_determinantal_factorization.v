2. THE COFACTOR VECTOR IS THE QUADRIC ROW TIMES ONE LINEAR FORM
--------------------------------------------------------------------------

Let

    q:=(q1,q2,q3,q4)

be the row of the four minimal quadratic generators. Since d1*d2=0, the first
three columns give

    q*L=0.

Because rank_K(L)=3, its left kernel over K is one-dimensional.

Let

    Delta=(Delta1,Delta2,Delta3,Delta4)

be the signed cofactor row of L: Deltai is, with the standard alternating sign,
the determinant of the 3-by-3 matrix obtained by deleting row i. Then

    Delta*L=0.

Since rank_K(L)=3, Delta is nonzero and spans the same one-dimensional left
kernel as q. Therefore there is a nonzero rational homogeneous function f with

    Delta=f*q.

Each Deltai has degree three and each qi has degree two, so f has homogeneous
degree one.

Theorem H01_m2_R2_quadric_row_is_primitive:
  The four quadrics q1,q2,q3,q4 have no common nonconstant polynomial factor.

Proof:
  If a nonconstant g divided every qi, then

    Q subset (g),

  so ht(Q)<=1. This contradicts the standing hypothesis ht(Q)=2.
Qed.

Write f=a/b in lowest terms with homogeneous coprime polynomials a,b. From

    Deltai=(a/b)*qi

one has

    b | a*qi

for every i. Since gcd(a,b)=1, b divides every qi. The preceding theorem forces
b to be a unit. Hence f is a polynomial. Degree comparison then gives a nonzero
linear form ell in S_1 such that

    Deltai=ell*qi

for all i, with the chosen cofactor signs.

Theorem H01_m2_R2_maximal_minors_have_linear_factor:
  There exists a nonzero linear form ell such that

    Delta=ell*q.
Qed.

Equivalently,

    I3(L)=(ell)*Q,

where I3(L) denotes the ideal generated by the 3-by-3 maximal minors of L.

