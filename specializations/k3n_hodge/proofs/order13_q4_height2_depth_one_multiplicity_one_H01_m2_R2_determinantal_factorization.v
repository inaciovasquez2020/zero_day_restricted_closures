6. EXACT DETERMINANTAL FACTORIZATION
--------------------------------------------------------------------------

Theorem H01_m2_R2_determinantal_factorization:
  For the 4-by-3 linear first-syzygy matrix L one has

    I3(L)=(r)*Q.

